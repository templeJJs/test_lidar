"""Габарит по стенам тоннеля: ведение коридора бинами дальности.

Зачем
-----
Целевой вопрос кейса — «есть ли препятствие в габарите на 100 м». Ни один из
прежних источников туда не дотягивается: детекция нити кончается на 40 м,
экстраполяция пути на 150 м промахивается на 5.8 м при полугабарите 1.7 м
(eval_extrapolation.py), карта пути точна, но помнит только пройденное.
Остаются стены: они параллельны пути и на дальности плотнее рельсов —
eval_wall_range.py даёт по ним 90-100 м на прямой.

Чем это отличается от zones.detect_walls
----------------------------------------
Там одна гистограмма по X на ВЕСЬ кадр: берётся самый сильный пик слева и
справа. На кривой путь уходит вбок, и гистограмма размазывается; а рядом с
вторым путём самый сильный пик — вообще не своя стена.

Замер, ради которого написан этот файл (полоса z -1..2 м, пики по X):

    doubleT_platform f120   ближе 10 м: -1.7   |   30-40 м: -5.7 (соседний объём)
    squareT_..._switch f100 ближе 40 м: -2.1   |   40-50 м: -7.5 (появился скачком)

Самый сильный пик на дальности уводит границу габарита на 4-5 м наружу — то
есть коридор станет шире тоннеля и препятствие у стены в него не попадёт.

Поэтому здесь стена не ищется заново в каждом бине, а ВЕДЁТСЯ: положение в
бине предсказывается по уже принятым ближним бинам, кандидат ищется в узком
окне вокруг предсказания, и бин отбраковывается, если стена прыгнула или
ширина тоннеля ушла от ближней медианы. Это тот же приём, которым чинились
перескоки нити на поворотах (README, «Детекция на поворотах»).

Что на выходе
-------------
`trace_walls()` возвращает узлы коридора по дальности и — главное — `reach`:
дальность, до которой габарит ПОДТВЕРЖДЁН измерением. Дальше вывод не
«свободно», а «не наблюдается»: провалы точек на дальности — это дыры между
кольцами лидара (roundT_doubleT f60: 145 точек на 80-90 м, 21 на 90-100 м,
снова 144 на 100-110 м), а не конец тоннеля. Подменять одно другим для задачи
обнаружения препятствий — худший возможный отказ.

Габарит строится в системе ПУТИ, а не прямоугольником в системе кадра: на
кривой прямоугольник срезал бы внутреннюю сторону дуги.
"""
import numpy as np

# --- геометрия поиска -------------------------------------------------------
BIN = 5.0             # шаг бина по дальности, м. 5 м: на 10 м бин на кривой
                      # размазывает стену (путь уходит вбок внутри бина), на
                      # 2.5 м на 70+ м в бине остаются единицы точек
MAX_R = 120.0         # дальше измерять нечего: eval_wall_range даёт максимум
                      # 100 м на прямой
# Полоса высот, в которой ищется стена. Это НЕ «где угодно между полом и
# потолком»: в круглом тоннеле стена — дуга, и её вынос зависит от высоты.
# Замер roundT_doubleT f60 (вынос кромки по слоям 0.25 м):
#     z -1.50: 1.3 м    z +0.50: 2.7 м (максимум)    z +2.75: 1.3 м
# Полоса -1..+2 м смешивает весь этот разброс в один перцентиль, и он гуляет
# от бина к бину на метр — из-за этого коридор терял стену уже на 30 м.
# Поэтому стена меряется ПО СЛОЯМ (Z_STEP), а габарит берёт худший слой в
# пределах высоты поезда: поезд упирается туда, где тоннель уже всего.
# Нижняя граница поднята над полом: у самого пола лежат балласт, лоток и
# шпалы, и они дают «стену» в 0.8 м от оси — то есть коридор уже поезда.
# Пол меряется в кадре (floor), поэтому Z_LO задан относительно него.
H_LO = 0.60              # насколько выше пола начинать искать стену, м.
                         # 0.35 м ещё мало: на этой высоте вдоль пути идут
                         # лоток и плечо балласта, и они дают «стену» в 0.7 м
                         # от оси (замер roundT_doubleT f60, слой h0.35:
                         # p10 = 0.69 м против 1.41 м уже на h0.60). Это
                         # реальная конструкция, но не препятствие поезду —
                         # она ниже кузова. С 0.6 м профиль чистый: 1.4 м на
                         # h0.60, 2.4 м на h1.10, 2.6 м на h1.85
Z_HI = 3.2               # верх диапазона поиска (абсолютный, над полом хватает)
Z_STEP = 0.5             # толщина слоя, м

# Габарит по высоте отсчитывается от ПОЛА, измеренного в кадре, а не от нуля
# лидара: лидар стоит примерно в 1.65 м над уровнем головок (замер по трём
# бэгам: пол на -1.63, -1.65, -1.73 м), и зашивать это константой незачем.
GAUGE_H_LO = 0.1      # низ габарита над полом, м (ниже — балласт и лоток)
GAUGE_H_HI = 3.7      # верх габарита над полом, м — высота вагона метро
# Верх важен не меньше низа: слой z+2.5 в squareT_..._switch — это дуга
# потолка, она заходит внутрь до 1.3 м. Пока он попадал в габарит, худший
# слой давал коридор ±1.25 м вместо ±1.8 м, то есть поезд «не проходил» в
# собственном тоннеле.
MIN_PTS = 4           # точек на стену в бине. Замер по пяти бэгам: с 6 до 4
                      # медиана reach растёт 45 -> 50 м, p10 не падает, а доля
                      # срывов не растёт (1.0% -> 0.0%). Порог держит не
                      # количество точек, а окно GATE вокруг предсказания
SEED_R = 25.0         # ближняя зона, по которой берётся первая оценка стен:
                      # здесь точек десятки тысяч и второй путь ещё не мешает
MIN_OFF = 1.2         # стена не ближе этого от оси: внутри — габарит и поезд
MAX_OFF = 8.0         # и не дальше: снаружи соседний объём

# --- ведение ----------------------------------------------------------------
GATE = 0.45           # полуокно поиска вокруг предсказания, м. Стена своего
                      # тоннеля между соседними бинами (5 м) не смещается
                      # больше чем на пару сантиметров плюс ошибка оси; 0.45 м
                      # ловит их с запасом и при этом вдвое уже расстояния до
                      # второго пути (ближайший замеренный скачок — 3.6 м)
FIT_WIN = 5           # по скольким последним принятым бинам строится
                      # предсказание. Больше одного — принципиально: если
                      # центр окна брать по ПРЕДЫДУЩЕМУ бину, ответ бина
                      # становится центром окна следующего, и на стене без
                      # резкой кромки (круглый тоннель: точки сплошь от -2.7
                      # до -1.6 без провала, roundT_doubleT f60) окно
                      # храповиком сползает внутрь — замерено -2.16 -> -1.68
                      # за пять бинов, после чего настоящая стена выходит за
                      # окно и коридор встаёт на 30 м. Медиана по пяти бинам
                      # этот дрейф не поддерживает.
SLOPE_LIM = 0.06      # максимальный наклон стены, м/м (0.3 м на бин): реальная
                      # стена в кривой R=300 м уходит на 0.04 м/м
WIDTH_TOL = 0.5       # бин не принимается, если ширина ушла от медианы ближних
                      # бинов больше чем на столько. Замер ширины: СКО 0.19-0.34
                      # м на трёх бэгах из четырёх, а разлёт на roundT_doubleT
                      # (2.58-7.54 м) — это как раз второй путь
WIDTH_WIN = 6         # сколько последних принятых бинов держат медиану ширины
MISS_LIMIT = 6        # столько подряд пустых бинов коридор переживает по
                      # предсказанию (дыра между кольцами). 2 было слишком
                      # строго: дыры между кольцами тянутся на 20-30 м
                      # (roundT_doubleT f60 — провал 90-100 м между плотными
                      # 80-90 и 100-110). С 6 медиана reach 45 -> 55 м, p10
                      # 17 -> 27 м при той же доле срывов ~1%. На дальность
                      # ПОДТВЕРЖДЁННОГО габарита это не влияет: reach растёт
                      # только на бинах со статусом ok

# --- габарит ----------------------------------------------------------------
GAUGE_HALF = 1.7      # полуширина габарита поезда, м
WALL_MARGIN = 0.15    # зазор до стены: точки ближе к стене — сама стена


def _wall_in_bin(dx, lo, hi, side):
    """Граница свободного пространства в бине: перцентиль по окну [lo, hi].

    Берётся не медиана, а перцентиль в сторону ОСИ (10-й по модулю выноса).
    Две причины, и обе проверены замером.

    По смыслу: габарит ограничивает ближайшая помеха, а не плоскость стены за
    ней. Кабели, ниши и оборудование на стене — такая же граница, как бетон.

    По данным: именно внутренняя кромка устойчива по бинам, а внешний хвост
    гуляет. squareT_..._switch f100, правая сторона по бинам 10 м — p10
    держится 1.50-1.67, а медиана скачет 1.53 -> 2.93 -> 3.34, потому что за
    стеной открывается ниша. Медиана дала бы «габарит свободен до +3.3 м» там,
    где на +1.6 м уже конструкция.
    """
    sel = dx[(dx >= lo) & (dx <= hi)]
    if len(sel) < MIN_PTS:
        return np.nan, len(sel)
    # side=-1 (слева, dx<0): ближняя к оси кромка — это МАКСИМУМ dx, берём 90-й.
    # side=+1: минимум dx, берём 10-й. Не сам экстремум: одиночный выброс
    # внутрь габарита сузил бы коридор до нуля.
    q = 90.0 if side < 0 else 10.0
    return float(np.percentile(sel, q)), len(sel)


def _seed(dx_near, side):
    """Первая оценка стены по ближней зоне (сильнейший пик, потом уточнение)."""
    cand = dx_near[(dx_near * side > MIN_OFF) & (dx_near * side < MAX_OFF)]
    if len(cand) < MIN_PTS:
        return np.nan
    # Вблизи второго пути ещё нет (замер: расхождение начинается с 20-30 м),
    # поэтому здесь сильнейший пик — это своя стена, и гистограмма безопасна.
    # Из нескольких пиков берётся САМЫЙ БЛИЖНИЙ к оси среди значимых: у
    # платформы и ниш внешний пик плотнее, но габарит режет внутренний.
    h, e = np.histogram(cand, bins=np.arange(-MAX_OFF, MAX_OFF + 0.05, 0.1))
    c = (e[:-1] + 0.05)
    sig = np.nonzero(h >= max(MIN_PTS, 0.15 * h.max()))[0]
    if len(sig) == 0:
        return np.nan
    k = sig[-1] if side < 0 else sig[0]      # ближний к оси значимый пик
    return _wall_in_bin(cand, c[k] - 0.35, c[k] + 0.35, side)[0]



def _predict(hist, mid, seed):
    """Где ждать стену в бине на дальности mid, по последним принятым бинам.

    Пока принятых бинов мало — держим затравку по ближней зоне. Дальше:
    медиана последних FIT_WIN выносов плюс наклон по МНК, ограниченный
    SLOPE_LIM. Медиана вместо последнего значения убирает храповик (см.
    FIT_WIN), наклон нужен для кривой, где стена честно уходит вбок.
    """
    if len(hist) < 2:
        return seed
    h = np.asarray(hist[-FIT_WIN:], dtype=float)
    d, v = h[:, 0], h[:, 1]
    base = float(np.median(v))
    slope = 0.0
    if len(h) >= 3 and np.ptp(d) > 1e-6:
        slope = float(np.clip(np.polyfit(d, v, 1)[0], -SLOPE_LIM, SLOPE_LIM))
    return base + slope * (mid - float(np.median(d)))


def trace_walls(pts, axis_fwd=None, axis_x=None, max_range=MAX_R):
    """Ведёт габаритный коридор бинами дальности от кадра вперёд.

    pts — облако кадра (x вправо, y НАЗАД, z вверх; вперёд = -y).
    axis_fwd/axis_x — ось пути в системе кадра (из track_map.map_to_frame,
    отсортированная по fwd). Без неё окно центрируется на x=0: для прямой
    годится, на кривой сокращает дальность.

    В каждом бине стена ведётся ОТДЕЛЬНО ПО СЛОЯМ ВЫСОТЫ (см. Z_LO/Z_STEP), а
    границей габарита становится худший слой в пределах высоты поезда. Иначе
    в круглом тоннеле один перцентиль на всю полосу высот смешивает дугу
    стены и гуляет на метр между бинами.

    Возвращает dict:
      fwd      — центр каждого бина, м
      left_x   — граница свободного пространства слева (<0), худший слой
      right_x  — то же справа (>0)
      axis_x   — ось пути в этом бине
      status   — 'ok' | 'hole' (ведён по предсказанию) | 'stop'
      reach    — дальность, до которой габарит подтверждён измерением, м
      width    — ширина коридора в бине, м
      z_lo     — нижняя граница слоя, задавшего left_x / right_x
    """
    pts = np.asarray(pts, dtype=float)
    y, x, z = -pts[:, 1], pts[:, 0], pts[:, 2]

    have_axis = (axis_fwd is not None and axis_x is not None
                 and len(np.atleast_1d(axis_fwd)) > 1)

    def axis_at(d):
        if have_axis and axis_fwd[0] <= d <= axis_fwd[-1]:
            return float(np.interp(d, axis_fwd, axis_x))
        if have_axis and d > axis_fwd[-1]:
            return float(axis_x[-1])   # карта кончилась — держим последнее
        return 0.0

    # Пол кадра: 2-й перцентиль Z под самим поездом. Отсюда отсчитывается
    # высота габарита — см. GAUGE_H_LO/HI.
    und = (y > 2.0) & (y < 30.0) & (np.abs(x) < 1.5)
    floor = float(np.percentile(z[und], 2)) if und.sum() > 200 else -1.65
    g_lo, g_hi = floor + GAUGE_H_LO, floor + GAUGE_H_HI

    layers = np.arange(floor + H_LO, Z_HI - 1e-9, Z_STEP)
    # Слои, попадающие в высоту габарита: только они ограничивают поезд.
    in_gauge = [(zl + Z_STEP > g_lo) and (zl < g_hi) for zl in layers]

    # Затравка на каждый слой по ближней зоне, где точек десятки тысяч.
    near = (y >= 2.0) & (y < SEED_R)
    ax_near = np.array([axis_at(v) for v in y[near]]) if near.any() else np.zeros(0)
    dxn, zn = (x[near] - ax_near, z[near]) if near.any() else (np.zeros(0), np.zeros(0))
    seed, hist = {}, {}
    for li, zl in enumerate(layers):
        k = (zn >= zl) & (zn < zl + Z_STEP)
        for side in (-1, +1):
            seed[(li, side)] = _seed(dxn[k], side) if k.sum() >= MIN_PTS else np.nan
            hist[(li, side)] = []

    edges = np.arange(0.0, max_range, BIN)
    out = {k: np.full(len(edges), np.nan) for k in
           ('left_x', 'right_x', 'axis_x', 'width', 'z_lo')}
    out['fwd'] = edges + BIN / 2
    status = np.array(['stop'] * len(edges), dtype=object)
    widths = []
    reach, misses, stopped = 0.0, 0, False

    for i, lo in enumerate(edges):
        hi, mid = lo + BIN, lo + BIN / 2
        ax = axis_at(mid)
        out['axis_x'][i] = ax
        if stopped:
            break

        m = (y >= lo) & (y < hi)
        dx_bin, z_bin = (x[m] - ax, z[m]) if m.any() else (np.zeros(0), np.zeros(0))

        # Ширина коридора считается по слоям габарита; слои выше/ниже ведутся
        # тоже — они держат непрерывность там, где габаритный слой пуст.
        best = {-1: (np.nan, np.nan), +1: (np.nan, np.nan)}   # (вынос, z_lo)
        pred_g = {-1: [], +1: []}
        got = {-1: [], +1: []}
        for li, zl in enumerate(layers):
            k = (z_bin >= zl) & (z_bin < zl + Z_STEP)
            sel = dx_bin[k]
            for side in (-1, +1):
                pred = _predict(hist[(li, side)], mid, seed[(li, side)])
                if np.isnan(pred):
                    continue
                pred = float(np.clip(abs(pred), MIN_OFF, MAX_OFF)) * side
                v = _wall_in_bin(sel, pred - GATE, pred + GATE, side)[0] \
                    if len(sel) else np.nan
                if in_gauge[li]:
                    pred_g[side].append(pred)
                if np.isnan(v):
                    continue
                got[side].append((li, v))
                if not in_gauge[li]:
                    continue
                # Худший (ближайший к оси) слой в пределах габарита и задаёт
                # границу: поезд упрётся именно в него.
                if np.isnan(best[side][0]) or abs(v) < abs(best[side][0]):
                    best[side] = (v, zl)

        vl, zl_l = best[-1]
        vr, zl_r = best[+1]
        ok = not (np.isnan(vl) or np.isnan(vr))

        if ok:
            w = vr - vl
            # Защита от второго пути: ширина не обязана быть константой
            # (тоннель расширяется у платформ), но не прыгает на полметра за
            # 5 м. Именно это отсекает roundT_doubleT с разлётом 2.58-7.54 м.
            if widths:
                ok = abs(w - float(np.median(widths[-WIDTH_WIN:]))) <= WIDTH_TOL

        if ok:
            for side in (-1, +1):
                for li, v in got[side]:
                    hist[(li, side)].append((mid, v))
            out['left_x'][i], out['right_x'][i] = vl, vr
            out['width'][i] = vr - vl
            out['z_lo'][i] = zl_l if abs(vl) < abs(vr) else zl_r
            widths.append(vr - vl)
            status[i] = 'ok'
            reach = hi
            misses = 0
        else:
            misses += 1
            if misses > MISS_LIMIT:
                stopped = True
                continue
            # Дыра между кольцами лидара — не конец тоннеля. Коридор ведётся
            # по предсказанию, но reach НЕ растёт: эти бины не подтверждены.
            # В историю дыра не пишется: предсказание должно опираться только
            # на измеренные бины, иначе оно продолжает само себя.
            pl = max(pred_g[-1]) if pred_g[-1] else np.nan
            pr = min(pred_g[+1]) if pred_g[+1] else np.nan
            if np.isnan(pl) or np.isnan(pr):
                stopped = True
                continue
            status[i] = 'hole'
            out['left_x'][i], out['right_x'][i] = pl, pr
            out['width'][i] = pr - pl

    out['status'] = status
    out['floor'] = floor
    out['have_axis'] = bool(have_axis)
    out['reach'] = reach
    out['n_ok'] = int((status == 'ok').sum())
    return out

def corridor_half_width(wall, margin=WALL_MARGIN, gauge_half=GAUGE_HALF):
    """Полуширина свободного коридора в каждом бине: min(габарит, до стены).

    Габарит поезда ±1.7 м — это то, что должно быть свободно. Если тоннель
    уже (или стена ближе), свободного места меньше, и мерить надо по стене.
    """
    left = np.abs(wall['left_x']) - margin
    right = wall['right_x'] - margin
    return (np.minimum(left, gauge_half), np.minimum(right, gauge_half))


# --- препятствия ------------------------------------------------------------
OBST_DX = 0.30        # ширина ячейки поперёк пути при кластеризации, м
OBST_MIN_PTS = 12     # точек в кластере, чтобы он считался объектом
OBST_MIN_H = 0.4      # минимальная высота объекта над полом, м
OBST_EXCESS = 2.5     # во сколько раз кластер должен превышать фон окна
OBST_WIN = 5.0        # длина окна поиска вдоль пути, м
OBST_STEP = 2.5       # шаг окна, м. ВДВОЕ меньше окна — окна перекрываются,
                      # иначе объект на стыке бинов делится пополам и не
                      # набирает порог: в doubleT_obstacle человек на 55 м
                      # попадал на границу и терялся в 5 кадрах из 9.
OBST_BG_Q = 40.0      # перцентиль для оценки фона. Не медиана: сам объект
                      # входит в выборку ячеек и завышает её (замер f190 —
                      # медиана 20 при фоне 2-6 в соседних окнах), после чего
                      # порог 2.5*фон становится недостижим.


def _column_height(zs, floor, gap=0.5, step=0.25):
    """Верх сплошной снизу части колонки точек, м над полом.

    Человек и свод попадают в одну ячейку по X, поэтому max(Z) описывает не
    объект, а тоннель. Здесь высота растёт, пока слои идут подряд, и
    обрывается на первом разрыве в gap метров — над головой человека такой
    разрыв есть, у стены и колонны его нет.
    """
    zs = np.sort(np.asarray(zs, dtype=float) - floor)
    if len(zs) == 0:
        return 0.0
    # Разрыв ищется по ГИСТОГРАММЕ, а не по соседним точкам: одиночные точки
    # на стойке или кабеле над головой смыкают зазор, и колонна человека
    # тянется до свода (замер doubleT_obstacle f140-f180: высота 3.70 м у
    # той же цели, что в соседних кадрах давала 1.2 м). Слой считается
    # занятым от 2 точек — одна точка разрыв не закрывает.
    nb = max(1, int(np.ceil((zs[-1] - zs[0]) / step)) + 1)
    cnt, edges = np.histogram(zs, bins=nb, range=(zs[0], zs[0] + nb * step))
    # Порог занятости слоя: 2 точки на плотном кластере, 1 на разреженном.
    # На 60 м человек даёт всего 18 точек на 3 м высоты (doubleT_obstacle
    # f160), и при пороге 2 НИ ОДИН слой не занят — разрыв не находится, и
    # высота уходит в потолок. Порог по самому кластеру, а не константой.
    occ = cnt >= (2 if len(zs) >= 40 else 1)
    run = int(np.ceil(gap / step))
    top = zs[0]
    empty = 0
    for i, o in enumerate(occ):
        if o:
            top = min(edges[i + 1], zs[-1])
            empty = 0
        else:
            empty += 1
            if empty >= run:
                break
    return float(top)



def obstacles_in_gauge(pts, wall, min_pts=OBST_MIN_PTS,
                       gauge_half=GAUGE_HALF, margin=WALL_MARGIN):
    """Объекты внутри габарита в подтверждённой зоне коридора.

    Ищет только там, где коридор ПОДТВЕРЖДЁН (status=='ok'): за reach ответ
    не «свободно», а «не наблюдается», и выдавать оттуда «чисто» нельзя.

    Просто «посчитать точки в габарите» не работает: в каждом бине есть
    ровный фон от пола, лотка и дальней стены — замер doubleT_obstacle,
    полоса 50-60 м: ~30 точек в каждой ячейке 0.25 м по всей ширине, и на
    ЭТОМ фоне человек виден как локальный избыток (101 точка в ячейке).
    Поэтому объект ищется как кластер, который выделяется над медианным
    фоном бина, а не как факт наличия точек.

    Возвращает список находок: (fwd, x, n, width, height, z_max, in_gauge).
    """
    pts = np.asarray(pts, dtype=float)
    y, x, z = -pts[:, 1], pts[:, 0], pts[:, 2]
    floor = wall.get('floor', -1.65)
    hl, hr = corridor_half_width(wall, margin, gauge_half)
    # На неподтверждённых бинах стены — предсказание, поэтому опираться на них
    # нельзя: там габарит задаётся только клампом ±gauge_half.
    unconf = np.asarray([st != 'ok' for st in wall['status']])
    hl = np.where(unconf, gauge_half, hl)
    hr = np.where(unconf, gauge_half, hr)

    fwd_nodes = np.asarray(wall['fwd'], dtype=float)
    status = np.asarray(wall['status'], dtype=object)
    last = fwd_nodes[status != 'stop']
    if len(last) == 0:
        return []
    limit = float(last.max()) + BIN / 2

    hits = []
    for w0 in np.arange(0.0, limit - OBST_WIN + 1e-6, OBST_STEP):
        w1 = w0 + OBST_WIN
        mid = (w0 + w1) / 2
        i = int(np.argmin(np.abs(fwd_nodes - mid)))
        if status[i] == 'stop':
            continue
        # Бины 'hole' НЕ пропускаются. Коридор в них не подтверждён, и это
        # честно отражено в поле confirmed у находки, но пропускать их нельзя:
        # в doubleT_obstacle человек на 55 м попадает ровно в такой бин
        # (ширина зала 7.5 м не проходит проверку непрерывности), и при
        # пропуске единственное настоящее препятствие в наборе исчезало.
        # Габарит там держится клампом ±GAUGE_HALF, а не стенами.
        confirmed = status[i] == 'ok'
        ax = wall['axis_x'][i]
        # Полоса поиска НЕ зависит от того, насколько широк коридор в этом
        # бине: на неподтверждённых бинах стены — это клампы MIN_OFF, и окно
        # по ним сжималось до |x|<2.7, обрезая цель у края (doubleT_obstacle
        # f160: человек на x=+0.7..+1.3 терял половину точек и выпадал, хотя
        # в кадре их те же ~130, что и в соседних). Окно задаётся габаритом
        # плюс постоянный запас — объект у края надо увидеть целиком, чтобы
        # честно сказать, заходит он внутрь или нет.
        m = (y >= w0) & (y < w1) & (z > floor + GAUGE_H_LO) & (z < floor + GAUGE_H_HI) \
            & (np.abs(x - ax) < gauge_half + 1.5)
        if m.sum() < min_pts:
            continue
        dx, zz = x[m] - ax, z[m]

        edges = np.arange(dx.min(), dx.max() + OBST_DX, OBST_DX)
        if len(edges) < 3:
            continue
        cnt, _ = np.histogram(dx, bins=edges)
        occ = cnt[cnt > 0]
        bg = float(np.percentile(occ, OBST_BG_Q)) if len(occ) else 0.0
        thr = max(min_pts, OBST_EXCESS * bg)

        k = 0
        while k < len(cnt):
            if cnt[k] < thr:
                k += 1
                continue
            j = k
            while j + 1 < len(cnt) and cnt[j + 1] >= thr:
                j += 1
            sel = (dx >= edges[k]) & (dx < edges[j + 1])
            n = int(sel.sum())
            if n >= min_pts:
                # Высота объекта — не максимум Z в колонке: над человеком
                # в той же ячейке лежат точки свода, и высота получалась 3.70 м
                # у всех находок подряд (замер doubleT_obstacle f130/f190),
                # то есть признак «человек ниже 1.5 м, стена до свода» не
                # работал вовсе. Берём верх СПЛОШНОЙ снизу части колонки:
                # поднимаемся от пола, пока не встретим пустой слой в 0.5 м.
                h = _column_height(zz[sel], floor)
                xc = float(np.median(dx[sel]))
                x0, x1 = float(dx[sel].min()), float(dx[sel].max())
                if h >= OBST_MIN_H:
                    # «В габарите» — если объект пересекается с коридором, а
                    # не если его центр внутри: человек у края опасен краем.
                    inside = (x1 > -hl[i]) and (x0 < hr[i])
                    hits.append(dict(fwd=float(mid), x=xc, n=n,
                                     x_min=x0, x_max=x1,
                                     width=x1 - x0, height=h,
                                     z_max=float(zz[sel].max()),
                                     in_gauge=bool(inside),
                                     confirmed=confirmed))
            k = j + 1
    return _merge_hits(hits)


def _merge_hits(hits, dr=OBST_WIN, dx=0.6):
    """Схлопывает находки соседних перекрывающихся окон в одну.

    Перекрытие окон (OBST_STEP < OBST_WIN) нужно, чтобы не терять объект на
    стыке, но один и тот же человек попадает в два окна. Объединяются
    находки ближе dr по дальности и dx поперёк; остаётся та, где больше точек.
    """
    out = []
    for h in sorted(hits, key=lambda a: -a['n']):
        if any(abs(h['fwd'] - o['fwd']) < dr and abs(h['x'] - o['x']) < dx
               for o in out):
            continue
        out.append(h)
    return sorted(out, key=lambda a: a['fwd'])


def walls_from_bag(bag_dir, frame_idx, max_range=MAX_R):
    """Удобная обёртка: кадр бэга + ось пути из карты, если она есть."""
    import os
    from visualize_bag import BagFrames, find_db3
    from track_map import map_to_frame

    frames = BagFrames(find_db3(bag_dir), cache_size=2)
    pts = frames[frame_idx][0]
    fw = cx = None
    tmp, trp = (os.path.join(bag_dir, f) for f in ('track_map.npz', 'trajectory.npz'))
    if os.path.exists(tmp) and os.path.exists(trp):
        tm, poses = dict(np.load(tmp)), np.load(trp)['poses']
        # Карта из 6 узлов (битый бэг) хуже нулевой оси: окно промахивается.
        if len(tm['s']) > 20 and frame_idx < len(poses):
            pr = map_to_frame(tm, poses, frame_idx, max_range=max_range)
            if len(pr['fwd']) > 1:
                o = np.argsort(pr['fwd'])
                fw, cx = pr['fwd'][o], pr['center_x'][o]
    return pts, trace_walls(pts, fw, cx, max_range)


def main():
    import argparse

    ap = argparse.ArgumentParser(
        description='Габарит по стенам тоннеля: коридор по бинам + препятствия')
    ap.add_argument('bag_dir')
    ap.add_argument('--frame', type=int, default=0)
    ap.add_argument('--max-range', type=float, default=MAX_R)
    ap.add_argument('--obstacles', action='store_true',
                    help='искать объекты в габарите')
    a = ap.parse_args()

    pts, w = walls_from_bag(a.bag_dir, a.frame, a.max_range)
    print(f'{a.bag_dir} кадр {a.frame}: {len(pts)} точек, пол z={w["floor"]:.2f} м')
    print(f'габарит ПОДТВЕРЖДЁН до {w["reach"]:.0f} м '
          f'({w["n_ok"]} бинов по {BIN:.0f} м)')
    if not w.get('have_axis'):
        print('! оси пути нет (карта бэга битая или отсутствует): коридор')
        print('  центрирован на лидаре, а не на пути. Габарит считается от x=0.')
    ok_w = w['width'][w['status'] == 'ok']
    if len(ok_w) and float(np.median(ok_w)) > 5.0:
        print(f'! ширина {np.median(ok_w):.1f} м — это не однопутный тоннель, а зал')
        print('  или двухпутный участок. Стены тут дальше габарита, и границу')
        print(f'  задаёт не они, а кламп ±{GAUGE_HALF} м.')
    print()
    print(f'{"дальн":>6s} {"стат":>5s} {"ось":>6s} {"слева":>7s} {"справа":>7s} {"шир":>6s}')
    for i, d in enumerate(w['fwd']):
        if w['status'][i] == 'stop':
            break
        print(f'{d:6.1f} {w["status"][i]:>5s} {w["axis_x"][i]:+6.2f} '
              f'{w["left_x"][i]:+7.2f} {w["right_x"][i]:+7.2f} {w["width"][i]:6.2f}')

    if a.obstacles:
        hits = obstacles_in_gauge(pts, w)
        print(f'\nобъектов найдено: {len(hits)}')
        print(f'{"дальн":>6s} {"x":>6s} {"шир":>5s} {"выс":>5s} {"точек":>6s} '
              f'{"габарит":>8s} {"подтв":>6s}')
        for o in hits:
            print(f'{o["fwd"]:6.1f} {o["x"]:+6.2f} {o["width"]:5.2f} {o["height"]:5.2f} '
                  f'{o["n"]:6d} {"ДА" if o["in_gauge"] else "нет":>8s} '
                  f'{"да" if o["confirmed"] else "НЕТ":>6s}')

    print(f'\nЗа {w["reach"]:.0f} м ответ — «не наблюдается», НЕ «свободно»:')
    print('провалы точек на дальности это дыры между кольцами лидара.')


if __name__ == '__main__':
    main()
