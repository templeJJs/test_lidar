"""Блок 2б. Объяснение точек внутри коридора конструкциями тоннеля.

Зачем отдельный блок. guard.walls ищет ВНЕШНЮЮ границу коридора и возвращает
одно число на бин. Всё, что лежит внутри коридора, для него не существует.
Но там стоят штатные конструкции: замер doubleT_obstacle f40 — в бине 30-35 м
внутри габарита 235 точек, при том что граница стены найдена на +5.51 м (зал,
а не тоннель). Если отдать эти точки блоку 3 как есть, он объявит препятствием
нишу, откос и кронштейн.

Признак, который разделяет, НЕ подбирался под ответ — он замерен:

    структура d ~ +1.5, h 2.0-3.5:  бины 30,35,40,45,50,65,70,75 м — 8 из 12
    человек   d ~ -1.47, h 0.1-1.0: бин 55-60 м, соседние ПУСТЫЕ

Конструкция тоннеля идёт ВДОЛЬ пути: ниша, кабельный кронштейн, откос, свод —
всё это протяжённые объекты, потому что тоннель сам протяжённый. Препятствие
локально: человек занимает один бин, поезд или вагонетка — несколько, но не
половину дальности.

Поэтому здесь ищутся продольные структуры: ячейки (поперёк x высота), занятые
в нескольких бинах подряд на одном и том же выносе. Что попало в структуру —
объяснено и препятствием не является. Остаток идёт в блок 3.
"""

import numpy as np

from .track import axis_at
from .walls import BIN, MAX_RANGE, GAUGE_HALF, GAUGE_H_HI
from .obstacles import BASE_MAX

# --- сетка ----------------------------------------------------------------
CELL_LAT = 0.40          # ячейка поперёк пути, м
CELL_UP = 0.50           # ячейка по высоте, м
H_LO = 0.10              # ниже — пол, балласт и лоток: отдельная история
H_HI = 4.00              # выше свода искать нечего

# --- что считать структурой ----------------------------------------------
MIN_PTS_CELL = 4         # точек в ячейке бина, чтобы она считалась занятой
MIN_BINS = 3             # в скольких бинах окна ячейка должна быть занята.
                         # 3 из 5 — структура тянется, но допускает пропуски:
                         # дальние бины разрежены, и требовать все 5 значит
                         # потерять реальную стену на 60+ м
WIN_BINS = 5             # ширина окна поиска вдоль пути, бинов (25 м при BIN=5)
LAT_TOL = 1              # на сколько ячеек вбок структура может съехать между
                         # бинами: тоннель расширяется плавно, но не прыгает

# --- третий тип: сплошной низкий лист через весь путь (НЕ штатное) -------
# Ячейки ниже BASE_MAX сознательно не защищены _in_collision — там живут
# рельсы, шпалы и лоток. Но тем же продольным тестом проходит и НИЗКАЯ ПЛИТА/
# КУЧА через весь путь (замер cloud_with_fake_obj f716-789+: слой h 0.1-0.6 м,
# lat -0.9..+0.9, длина до 35 м, ~10-18 тыс. точек): 88-99% её массы
# объяснялось как «рельсы/лоток» и препятствием не становилось.
# Отличие рельсов от плиты — ШИРИНА сплошного ряда занятых ячеек нижнего слоя
# (u=0, высота 0.1-0.6 м): рельсы — две ИЗОЛИРОВАННЫЕ lat-ячейки на бин (между
# ними пусто), плита — сплошной лист. Замер ширины максимальной сплошной
# полосы занятых ячеек u=0 на бин:
#   плита cloud_with_fake_obj f789 — 11 ячеек (4.4 м) во всех бинах
#   чистый путь (f700 того же бэга, doubleT_platform f100) — 4-5 ячеек
#   (рельсы + лоток)
# Порог посередине между 5 и 11.
SLAB_RUN_MAX = 6         # сплошной ряд занятых ячеек u=0 шире этого — лист
                         # плиты, а не рельсы: ячейки листа внутри габарита
                         # по ширине НЕ объясняются и уходят остатком в блок 3
# Одной ширины мало: одиночный широкий бин бывает и у чистого пути — замер
# doubleT_platform f30, бин 40-45 м: локальный низкий слой (настил/горб
# балласта, h 0.13-0.56 м) даёт сплошную полосу 10 ячеек, а соседние бины
# имеют разрыв у оси (два изолированных ряда рельсов по 4-5 ячеек). Плита же
# держит широкую полосу бинами ПОДРЯД (f789: 10 бинов, 0-45 м), потому что
# протяжена на десятки метров. Поэтому лист снимается с объяснения, только
# когда широкая полоса есть и в соседнем бине.
SLAB_BIN_NEIGH = 1       # широкая полоса должна повториться в пределах
                         # стольких соседних бинов, иначе это локальный рельеф

# --- второй тип штатного: вертикальная колонна ---------------------------
# Замер doubleT_obstacle f40, бин 30-35 м: конструкция стоит в ОДНОМ бине
# (соседние пустые), но тянется сплошь от 0.1 до 3.1 м — 6 ячеек по высоте.
# Продольность её не ловит, а это явно не препятствие: ниша, пилон, портал.
# Человек в том же кадре занимает по высоте 0.1-1.0 м и выше обрывается.
COL_MIN_CELLS = 4        # сплошных ячеек по высоте (2.0 м), чтобы счесть
                         # колонной. Сама длина цепочки человека НЕ отсекает:
                         # при росте 1.8 м он занимает ячейки 0.1-2.1 м, то
                         # есть до 4 штук — проходит и этот порог. Его отсекает
                         # COL_TOP_H ниже: верх человека не дотягивается до
                         # 2.6 м
COL_TOP_H = 2.60         # и верх колонны должен быть выше этого, м: объект
                         # ниже 2.6 м не дотягивается до свода, значит это
                         # не конструкция тоннеля
COL_GAP = 1              # сколько пустых ячеек по высоте колонна переживает
                         # (луч скользит по гладкой поверхности)

# --- локальное утолщение нижней ячейки в габарите (отдельный проход) -------
# Ячейка u=0 внутри габарита — НЕ рельс/полотно, если она локально толще
# продольной структуры, на которой лежит: замер cloud_with_fake_obj f400-424 —
# крышка на ходовой рельсе держит верх 0.60-0.63 м, а сечение рельса по
# соседним бинам 0.2-0.35 (норма у _in_collision ниже).
THICK_P95 = 0.40     # p95 высоты точек ячейки u=0 выше этого — тело выше
                     # нормы путевого железа (верх головки 0.2-0.35 + запас)
THICK_JUMP = 0.25    # и превышает медиану p95 той же lat-колонки в соседних
                     # бинах (±2) больше чем на это: у продольной структуры
                     # сечение постоянное, локальный прирост — объект на ней


def _cell_index(d, h):
    """Индексы ячейки (поперёк, по высоте)."""
    return (np.floor(d / CELL_LAT).astype(int),
            np.floor((h - H_LO) / CELL_UP).astype(int))


def _in_collision(l, u):
    """Ячейка внутри КОЛЛИЗИОННОГО ОБЪЁМА поезда (габарит по ширине и высоте
    ВЫШЕ путевого железа).

    Протяжённость — признак штатности только ВНЕ габарита: кабельный лоток у
    стены и свод над крышей тянутся вдоль всего тоннеля и поезду не мешают.
    А объект, который тянется вдоль пути ВНУТРИ габарита (свисающий с потолка
    предмет на высоте кузова — замер cloud_with_fake_obj f329-345: ~2000
    точек, lat +0.45, низ 2.0 м, то есть внутри габарита по высоте — верх
    габарита GAUGE_H_HI=2.50 м), — это не
    конструкция, а препятствие: поезд пройдёт СКВОЗЬ него.

    Ниже BASE_MAX объяснение ОСТАЁТСЯ: там живут сами рельсы, шпалы и лоток
    (верх головки ~0.2-0.35 м над измеренным полом) — они и продольные, и в
    габарите, и отключать их объяснение нельзя (проверено: остаток разрастался
    338 -> 15497 точек и топил находки). Низкий предмет НА рельсах (сценарий
    2×0.2 м) сюда не попадает и не теряется: он короткий (не проходит
    продольный порог MIN_BINS в любом случае) — его ловит блок 3 напрямую.
    Исключение из этого «объяснение остаётся» — сплошной низкий лист шире
    SLAB_RUN_MAX ячеек (плита/куча через весь путь): он выключается отдельным
    проходом в explain() после сборки структурных ячеек.
    """
    hc = H_LO + (u + 0.5) * CELL_UP
    return (abs((l + 0.5) * CELL_LAT) < GAUGE_HALF
            and hc >= BASE_MAX and hc < GAUGE_H_HI)


def explain(fwd, lat, up, floor, axis, max_range=MAX_RANGE):
    """Отмечает точки, объяснённые продольной конструкцией тоннеля.

    Возвращает dict:
      mask       — bool по точкам: True = объяснено конструкцией
      occupancy  — {(bin, ilat, iup): n} занятость ячеек, для отладки
      n_struct   — сколько ячеек признано структурой
    """
    d = lat - axis_at(axis, fwd)
    h = up - floor

    valid = (fwd >= 0) & (fwd < max_range) & (h >= H_LO) & (h < H_HI)
    mask = np.zeros(len(fwd), dtype=bool)
    if not valid.any():
        return dict(mask=mask, occupancy={}, n_struct=0)

    ib = np.floor(fwd / BIN).astype(int)
    il, iu = _cell_index(d, h)

    # Занятость: сколько точек в каждой ячейке каждого бина.
    # Та же группировка, что была у точечного цикла dict.get/setdefault, но
    # векторно: ключ ячейки упаковывается в int64 со смещениями от минимумов
    # кадра (n_l/n_u — точные диапазоны il/iu, поэтому коллизий нет по
    # построению), а np.unique считает те же счётчики тех же ячеек.
    iv = np.flatnonzero(valid)
    bv = ib[iv].astype(np.int64)
    lv = il[iv].astype(np.int64)
    uv = iu[iv].astype(np.int64)
    l0, u0 = int(lv.min()), int(uv.min())
    n_l = int(lv.max()) - l0 + 1
    n_u = int(uv.max()) - u0 + 1
    pkey = (bv * n_l + (lv - l0)) * n_u + (uv - u0)
    uk, cnt = np.unique(pkey, return_counts=True)
    occ = dict(zip(zip((uk // (n_l * n_u)).tolist(),
                       ((uk // n_u) % n_l + l0).tolist(),
                       (uk % n_u + u0).tolist()),
                   cnt.tolist()))

    n_bins = int(max_range // BIN) + 1
    struct_cells = set()

    for (b, l, u), n in occ.items():
        if n < MIN_PTS_CELL:
            continue
        # Сколько бинов в окне вокруг b заняты той же ячейкой (с допуском
        # на боковой съезд): структура тянется вдоль пути.
        hits = 0
        half = WIN_BINS // 2
        for bb in range(max(0, b - half), min(n_bins, b + half + 1)):
            if bb == b:
                hits += 1
                continue
            for dl in range(-LAT_TOL, LAT_TOL + 1):
                if occ.get((bb, l + dl, u), 0) >= MIN_PTS_CELL:
                    hits += 1
                    break
        if hits >= MIN_BINS and not _in_collision(l, u):
            struct_cells.add((b, l, u))

    # Второй тип штатного: вертикальная колонна до свода в пределах одного
    # бина. Собираем по (бин, вынос) цепочки занятых ячеек по высоте.
    cols = {}
    for (b, l, u), n in occ.items():
        if n >= MIN_PTS_CELL:
            cols.setdefault((b, l), []).append(u)

    for (b, l), us in cols.items():
        us = sorted(us)
        run = [us[0]]
        for u in us[1:]:
            if u - run[-1] <= COL_GAP + 1:
                run.append(u)
                continue
            _mark_column(run, b, l, struct_cells)
            run = [u]
        _mark_column(run, b, l, struct_cells)

    # Признанная структура поглощает редкие ячейки, ПРИМЫКАЮЩИЕ к ней по
    # высоте. Иначе по краям конструкции остаются разрозненные точки (ниже
    # MIN_PTS_CELL), которые поодиночке ничего не значат, но вместе набирают
    # кластер: замер doubleT_obstacle f130 — колонна на 76.8 м объяснена, а
    # 36 точек по её краям нет, и блок 3 видел препятствие в трёх кадрах.
    #
    # Поглощать ВЕСЬ столбец нельзя, и это проверено дорогой ценой: над
    # человеком в том же столбце лежит свод, столбец признаётся колонной, и
    # человек исчезает — детектор замолчал на всех семи кадрах. Поэтому
    # только соседняя ячейка, и только вверх от уже признанной.
    for (b, l, u) in sorted(struct_cells):
        # Только ВВЕРХ, как сказано выше: вниз поглощать нельзя — у нижнего
        # края ниши/откоса стоит человек, и его точки съедались бы вместе с
        # ячейкой под признанной структурой, прежде чем их увидит блок 3.
        nb = (b, l, u + 1)
        if nb in occ and nb not in struct_cells and not _in_collision(l, u + 1):
            # Присоединяем, только если ячейка редкая: плотная стоит
            # сама за себя и должна пройти проверку признаком.
            if occ[nb] < MIN_PTS_CELL:
                struct_cells.add(nb)

    # Отдельный проход: сплошной низкий лист (плита/куча через весь путь)
    # НЕ объясняется. Рельсы — две изолированные lat-ячейки на бин, плита —
    # сплошной ряд занятых ячеек u=0 (замер и порог — у SLAB_RUN_MAX выше).
    # Полоса меряется по ЗАНЯТОСТИ (occ), а не по struct_cells: неважно,
    # каким признаком ячейка попала в объяснённые. Выключаются только ячейки
    # внутри габарита по ширине: за габаритом лист поезду не мешает, а
    # обоснование «рельсы» там остаётся нужным (шпалы, плечо балласта).
    low_lats = {}
    for (b, l, u), n in occ.items():
        if u == 0 and n >= MIN_PTS_CELL:
            low_lats.setdefault(b, []).append(l)
    widest_of = {}
    for b, lats in low_lats.items():
        lats.sort()
        run, widest = [lats[0]], []
        for l in lats[1:]:
            run = run + [l] if l == run[-1] + 1 else [l]
            if len(run) > len(widest):
                widest = run
        widest_of[b] = widest
    wide = {b for b, w in widest_of.items() if len(w) > SLAB_RUN_MAX}
    for b in wide:
        # Лист протяжён: широкая полоса повторяется в соседнем бине.
        # Одиночный широкий бин — локальный рельеф (см. SLAB_BIN_NEIGH).
        if not any(b + db in wide
                   for db in range(-SLAB_BIN_NEIGH, SLAB_BIN_NEIGH + 1) if db):
            continue
        for l in widest_of[b]:
            if abs((l + 0.5) * CELL_LAT) < GAUGE_HALF:
                struct_cells.discard((b, l, 0))

    # Защита «ног» объекта в габарите (замер роя, огромный объект f785-810
    # cloud_with_fake_obj): ячейку u=0 ВНУТРИ габарита не объяснять, если в
    # той же lat-ячейке ВЫШЕ путевого железа (hc >= BASE_MAX, см.
    # _in_collision) стоит ТОРС — заняты (>= MIN_PTS_CELL) минимум ДВА слоя
    # ячеек по высоте: иначе блок 2б съедает низ объекта, база кластера в
    # блоке 3 «всплывает» (0.10 -> 0.60) и объект проходит под правило
    # 'base'/'dust'. Один слой — это линия, а не торс: подошва контактного
    # рельса (0.60-0.77 м, ячейка u=1) иначе отпускала бы своё же основание
    # (замер f400: колонка КР lat +1.40 — u=0 до 1197 точек, u=1 до 469 —
    # и блок 3 вспыхивал находками на КР каждый кадр). Ходовые рельсы не
    # отпускаются: торса над ними нет.
    u_hi = int((GAUGE_H_HI - H_LO) / CELL_UP)   # ячейки с hc < GAUGE_H_HI
    for (b, l, u) in sorted(struct_cells):
        if u != 0 or abs((l + 0.5) * CELL_LAT) >= GAUGE_HALF:
            continue
        torso = sum(1 for uu in range(1, u_hi + 1)
                    if occ.get((b, l, uu), 0) >= MIN_PTS_CELL)
        if torso >= 2:
            struct_cells.discard((b, l, 0))

    # Локальное утолщение продольной структуры в габарите (замер роя,
    # крышка на рельсе f400-424): ячейка u=0 в габарите — не рельс/полотно,
    # если p95 высоты её точек > THICK_P95 И превышает медиану p95 той же
    # lat-колонки в ±2 бинах больше чем на THICK_JUMP (постоянное сечение
    # продольной структуры). Gate: ячейку не трогаем, если прямо над ней
    # (u=1, та же l) идёт продольная линия — подошва контактного рельса
    # (0.60-0.77 м), иначе отпускалась бы сборка КР. Радиус gate — ровно та
    # же ячейка l: с боковым допуском LAT_TOL gate гасил объект рядом с КР
    # (замер роя, пробел 3-5 м).
    m0 = uv == 0
    p95_low = {}
    if m0.any():
        bq, lq, hq = bv[m0], lv[m0], h[iv][m0]
        qk = bq * 4096 + (lq - l0)
        order = np.argsort(qk, kind='stable')
        qk_s, hq_s = qk[order], hq[order]
        uk, first, cntk = np.unique(qk_s, return_index=True,
                                    return_counts=True)
        for kk, p0, cn in zip(uk, first, cntk):
            p95_low[int(kk)] = float(np.percentile(hq_s[p0:p0 + cn], 95))
    for (b, l, u) in sorted(struct_cells):
        if u != 0 or abs((l + 0.5) * CELL_LAT) >= GAUGE_HALF:
            continue
        p95c = p95_low.get(b * 4096 + (l - l0))
        if p95c is None or p95c <= THICK_P95:
            continue
        ref = [p95_low[bb * 4096 + (l - l0)]
               for bb in range(max(0, b - 2), min(n_bins, b + 3))
               if bb * 4096 + (l - l0) in p95_low]
        if len(ref) < 2 or p95c - float(np.median(ref)) <= THICK_JUMP:
            continue
        # над ячейкой (u=1) продольная линия — подошва контактного рельса
        line_above = sum(1 for bb in range(max(0, b - 2), min(n_bins, b + 3))
                         if occ.get((bb, l, 1), 0) >= MIN_PTS_CELL)
        if line_above >= MIN_BINS:
            continue
        struct_cells.discard((b, l, 0))

    # Маска по признанным ячейкам: те же точки, что раскладывал цикл
    # idx_of, — все точки кадра, чей ключ ячейки есть в struct_cells.
    # Отбор через occ повторяет прежнее условие `key in idx_of`: ячейка без
    # точек (например, пропуск внутри колонны, допущенный COL_GAP) маски не
    # даёт — и заодно исключает перенос упакованного ключа в соседнее поле
    # (ячейки за диапазоном кадра в occ не входят).
    hit = [c for c in struct_cells if c in occ]
    if hit:
        sk = np.fromiter(((b * n_l + (l - l0)) * n_u + (u - u0)
                          for b, l, u in hit),
                         dtype=np.int64, count=len(hit))
        mask[iv[np.isin(pkey, sk)]] = True

    return dict(mask=mask, occupancy=occ, n_struct=len(struct_cells))


def _mark_column(run, b, l, struct_cells):
    """Помечает цепочку ячеек по высоте, если она дотягивается до свода."""
    if len(run) < COL_MIN_CELLS:
        return
    top = H_LO + (run[-1] + 1) * CELL_UP
    if top < COL_TOP_H:
        return
    for u in range(run[0], run[-1] + 1):
        if not _in_collision(l, u):
            struct_cells.add((b, l, u))
