                          # За 3.0 м ошибка больше метра в 71 бине из 71 на
                          # четырёх независимых бэгах — разрыв не в хвосте, а
                          # полный. Порог на границе: 2.5-3.0 это честный
                          # переходный слой (гейт, портал), его оставляем в
                          # CENTER. Величина сравнима с OFF_MAX = 8.0, но это
                          # РАЗНЫЕ пределы: OFF_MAX — «дальше отступа не
                          # бывает у ОДНОЙ стены», здесь — «пара не бывает
                          # такой перекошенной»; парный предел строже
                          # одиночного, потому и ловит то, что _usable пропускает

# --- упор в стену (переход CENTER -> LEAD) ---------------------------------
GAUGE_CLEAR = 0.25        # насколько ближе СВОЕГО ОТСТУПА должна оказаться
                          # стена, чтобы счесть, что ось в неё упёрлась, м.
                          # Мерится от отступа, а не от полугабарита (см. блок
                          # выше): сравнение с габаритом давало упор на каждом
                          # бине нормальной прямой. Порог = рябь кромки в бине
                          # 5 м (замер axis_wall: +-0.25 м) — сближение меньше
                          # собственной ряби измерением не подтверждается
LEAD_AHEAD = 2 * BIN      # 10 м. На сколько стена должна продолжаться за
                          # бином упора, чтобы упор считался заворотом, а не
                          # торцом. «Стена ПРОХОДИТ ДАЛЬШЕ» — половина правила
                          # заказчика, и без неё ведение цепляется за нишу,
                          # столб или конец прослеженного отрезка: через бин
                          # стена кончится, и ось всё равно уйдёт в HOLD, но
                          # уже сбитая упором. Два бина — минимум, на котором
                          # у стены есть направление, а не одна точка

# --- гистерезис ------------------------------------------------------------
UP_RUN = 2                # столько бинов подряд новый режим должен
                          # подтвердиться, чтобы ПОВЫСИТЬ приоритет (вернуться
                          # к рельсам или ко второй стене). Понижение
                          # мгновенно: стена кончилась — она кончилась.
                          # Причина числа — замер 4 в axis_wall: платформа
                          # даёт РАЗОВЫЙ выброс (med +0.21 при p95 +3.54), а
                          # поворот — монотонный рост. Один бин их не
                          # различает, два уже различают

# --- продолжение формы (режим HOLD) ---------------------------------------
HOLD_WIN = 4              # по скольким последним известным бинам оси строится
                          # продолжение в дыре. Меньше трёх — парабола
                          # проходит точно и продолжать нечего (тот же урок,
                          # что в check_wall.MIN_BINS)
HOLD_CURV = 0.0015        # предел кривизны продолжения, 1/м: |2*a| полинома
                          # lat = a*d^2 + ... Соответствует радиусу ~670 м.
                          # Это предел ЭКСТРАПОЛЯЦИИ, а не реального пути:
                          # дуга по окну 60 м дальше окна не продолжается без
                          # роста ошибки (замер «Предел экстраполяции пути»)
HOLD_MAX = 30.0           # докуда продолжать форму за последним измерением, м.
                          # Дальше ось не «продолжена», а придумана: бины за
                          # этим пределом не выдаются вовсе


class Bin:
    """Решение по одному бину дальности.

    d         — центр бина, м
    mode      — RAILS / CENTER / LEAD / HOLD
    lat       — ось в этом бине, м (абсолютные координаты кадра, нуль лидара)
    side      — для LEAD: с какой стены ведём (-1 слева, +1 справа); иначе 0
    wall      — сама ведущая стена (`check_wall.Wall`) или None
    off       — применённый отступ стена->путь, м (LEAD), иначе nan
    off_measured — отступ измерен в ближней зоне (True) или взят по умолчанию
    width     — измеренная ширина коридора, м (CENTER), иначе nan
    tight     — полугабарит ближе GAUGE_CLEAR к кромке: ось под вопросом
    """

    __slots__ = ('d', 'mode', 'lat', 'side', 'wall', 'off', 'off_measured',
                 'width', 'tight')

    def __init__(self, d, mode, lat, side=0, wall=None, off=np.nan,
                 off_measured=True, width=np.nan, tight=False):
        self.d, self.mode, self.lat = float(d), mode, float(lat)
        self.side, self.wall = int(side), wall
        self.off, self.off_measured = float(off), bool(off_measured)
        self.width, self.tight = float(width), bool(tight)

    def __repr__(self):
        s = f'<{self.d:5.1f}м {self.mode:6s} lat={self.lat:+.2f}'
        if self.mode == LEAD:
            s += (f' {"L" if self.side < 0 else "R"}'
                  f' off={self.off:+.2f}'
                  f'{"" if self.off_measured else "?"}')
        if self.mode == CENTER:
            s += f' w={self.width:.2f}'
        return s + (' TIGHT>' if self.tight else '>')


def _wall_lat(wall, d):
    """Вынос стены на дальности d, м, или nan за пределом экстраполяции.

    Полином стены за прослеженным отрезком продолжать можно, но недалеко:
    чем дальше от последней кромки, тем меньше линия опирается на измерение.
    """
    slack = WALL_EDGE_SLACK * BIN
    if d < wall.d_lo - slack or d > wall.d_hi + slack:
        return np.nan
    return float(wall.lat_at(d))


def _seg_slope(wall, d_lo, d_hi):
    """Наклон ИЗМЕРЕННЫХ кромок стены на плече [d_lo, d_hi] или nan.

    По кромкам, а не по полиному: за прослеженным отрезком полином
    экстраполирует, и его наклон там — свойство фита, а не данных.
    """
    k = (wall.d >= d_lo) & (wall.d <= d_hi)
    if k.sum() < OFF_SHRINK_MIN:
        return np.nan
    return float(np.polyfit(wall.d[k], wall.e[k], 1)[0])


def _seg_curv(wall):
    """Кривизна ИЗМЕРЕННЫХ кромок стены (|2a| со знаком) или nan.

    Знак несёт сторону изгиба, и именно он отделяет свою стену от линии,
    склеившей стену с заворотом: борта одного тоннеля концентричны и гнутся
    в одну сторону.
    """
    if wall.n_bins < 4:
        return np.nan
    return float(2.0 * np.polyfit(wall.d, wall.e, 2)[0])


def cross_limits(walls, axis=None):
    """Докуда каждая стена идёт ВДОЛЬ пути -> {id(wall): предел дальности}.

    Решается ПАРОЙ, а не по одной стене, и это принципиально. Своя стена
    параллельна пути, но «параллельна пути» проверить по одной линии нечем:
    ось — то, что мы и строим, и на дуге она уезжает как раз к той стене,
    которую надо разоблачить (проверено: двухпроходная схема с осью первого
    прохода срезала ЧЕСТНУЮ стену на f71 и гнала ось до +5.8 м).

    Опора, которая оси не требует: ДВЕ СТЕНЫ ОДНОГО ТОННЕЛЯ ПАРАЛЛЕЛЬНЫ ДРУГ
    ДРУГУ — тоннель не сужается. Значит, расстояние между их кромками вдоль
    дальности постоянно, и если оно СХОДИТСЯ, одна из линий идёт не вдоль
    пути. Какая — та, чей наклон сильнее отличается от наклона пары в ближней
    зоне, где ось известна от рельсов и обе стены ещё честны.

    Замер по пяти бэгам (шаг 15 кадров, эталон только РАЗМЕЧАЕТ, в признак не
    входит): расхождение наклона линии с наклоном истинного пути —

        своя стена    med 0.0051   p90 0.0212
        пересекающая  med 0.0702   p90 0.0749

    то есть разделение в 14 раз по медиане. Хвосты перекрываются (своя доходит
    до 0.185), поэтому АБСОЛЮТНОГО порога на наклон здесь нет: он резал бы
    честные стены — ровно та ошибка, из-за которой был откачен запрет
    «стена не проходит через ноль лидара» (README: лучшая стена кадра p10
    65 -> 45 м). Наклон только ВЫБИРАЕТ виноватую из пары, а режет —
    сходимость самих кромок, факт наблюдаемый.
    """
    lim = {id(w): np.inf for w in walls}
    # Плечо, на котором пара сверяется: ближняя зона, где ось от рельсов —
    # истина, и обе стены ещё не успели разойтись с путём.
    near = SEED_NEAR
    for a, b in itertools.combinations(walls, 2):
        lo = max(a.d_lo, b.d_lo)
        hi = min(a.d_hi, b.d_hi)
        if hi - lo < PAIR_SPAN:
            continue            # общего плеча нет: сверять пару не на чем
        # Ширина коридора между кромками этой пары вдоль общей дальности.
        dd = np.arange(lo, hi + 1e-9, BIN)
        wid = np.abs(a.lat_at(dd) - b.lat_at(dd))
        if len(dd) < 2 * OFF_SHRINK_MIN or not np.isfinite(wid).all():
            continue
        seed = float(np.median(wid[:OFF_SHRINK_MIN]))
        if seed < WIDTH_MIN or seed > WIDTH_MAX:
            continue            # это не пара бортов одного тоннеля
        bad = wid < PAIR_SHRINK * seed
        if not bad.any():
            continue            # ширина держится: пара честная целиком
        cut = float(dd[max(0, int(np.argmax(bad)) - 1)])
        # Кто из двух уехал. Опора опять НЕ ось: два борта одного тоннеля
        # КОНЦЕНТРИЧНЫ, то есть гнутся в одну сторону. Линия, склеившая стену с
        # заворотом или со вторым путём, гнётся в ДРУГУЮ — её кривизна
        # противоположна по знаку кривизне партнёра.
        #
        # Наклон для этого не годится, и это проверено: наклон прямой оси
        # блока 1 держится около -0.004 на ВСЕХ кадрах (она прямая по
        # построению — в этом весь блок 1), а на дуге у обеих стен наклон
        # -0.05..-0.23. Сравнение с ней выбирало просто более плоскую линию, и
        # на левом завороте это ВИНОВАТАЯ: f115 и f54 получались наизнанку.
        #
        # Замер знака кривизны (кромки, полином 2-й степени, |2a|):
        #     f71  виноватая +0.00033  честная -0.00064
        #     f51  виноватая +0.00056  честная -0.00047
        #     f54  виноватая +0.00089  честная -0.00026
        #     f115 честная   -0.00148  виноватая +0.00016
        # Во всех парах знаки противоположны, и виновата та, что гнётся не в
        # сторону заворота.
        # ПАРА, СХОДЯЩАЯСЯ ПОЧТИ В ТОЧКУ, — не пара бортов, и признак
        # кривизны к ней неприменим. Он выведен из четырёх кадров НА
        # ЗАВОРОТЕ (f71/f51/f54/f115 ниже), где обе линии реально гнутся, и
        # там верен. На ПРЯМОЙ он даёт обратный ответ: своя стена идёт прямо
        # (кривизна мала именно потому, что она своя), а ушедшая на путь
        # гнётся — и «виновата та, чья кривизна меньше» назначает виноватой
        # ЧЕСТНУЮ. Замер doubleT_platform f10: стена 2.5-102.5 м, 6 слоёв,
        # rms 0.13, отступ от карты +2.48..+2.09 (идеально параллельна) —
        # кривизна +0.00058; ложная линия 7.5-62.5 м, 3 слоя, отступ
        # +6.64 -> +1.66 — кривизна -0.00492, в 8 раз больше. Правило
        # срезало ЧЕСТНУЮ стену на 47.5 м, ведение ушло на ложную, и ось
        # упала с -0.17 до -7.96 м за два бина.
        # Здесь опора снова не ось, а наблюдаемое: линия, ушедшая на путь,
        # сама сдвигается за плечо сильнее партнёра (замер того же кадра:
        # 4.87 м против 1.30 м).
        wmin = float(np.min(wid))
        if wmin < PAIR_CROSS * seed:
            sa = abs(a.lat_at(dd[-1]) - a.lat_at(dd[0]))
            sb = abs(b.lat_at(dd[-1]) - b.lat_at(dd[0]))
            if not (np.isfinite(sa) and np.isfinite(sb)) or sa == sb:
                continue
            culprit = a if sa > sb else b
            lim[id(culprit)] = min(lim[id(culprit)], cut)
            continue
        ca, cb = _seg_curv(a), _seg_curv(b)
        if np.isnan(ca) or np.isnan(cb):
            continue
        if np.sign(ca) == np.sign(cb):
            # Обе гнутся в одну сторону: пара концентрична, и сходимость
            # ширины объясняется не «одна ушла», а реальным сужением тоннеля
            # (гейт, портал). Резать тут нечего — это дело WIDTH_JITTER.
            continue
        # Виновата та, чья кривизна МЕНЬШЕ по модулю: заворот гнёт свою стену
        # сильно, а линия, ушедшая на путь, идёт почти прямо мимо него.
        culprit = a if abs(ca) < abs(cb) else b
        lim[id(culprit)] = min(lim[id(culprit)], cut)
    return lim


def cross_limit(wall, lat_of):
    """Докуда стена ещё параллельна пути -> предел дальности, м.

    Своя стена идёт ВДОЛЬ пути: отступ до неё держит знак и не сходится к
    нулю. Дальний борт заворота в проекции ведёт себя иначе — отступ
    монотонно убывает, обращается в нуль и меняет знак, после чего линия
    лежит уже по ДРУГУЮ сторону пути. Именно это и есть дефект «нижняя стена
    перекидывается на путь и оказывается рядом с другой стеной»: обе стены
    попадают на одну сторону, пара для CENTER рассыпается, и ось рывком
    уходит в LEAD (замер roundT_pressureGate_roundT f71: отступ левой стены
    -2.44 -2.54 -2.38 -1.72 +0.08 +3.30, ось промахивается на -1.86 м).

    Признак берётся по ИЗМЕРЕННЫМ кромкам (`wall.d`/`wall.e`), а не по
    полиному: полином за прослеженным отрезком экстраполирует, и сходимость
    на нём — свойство фита, а не данных.

    `lat_of(d)` — ось на дальности d. Отступ считается от неё, потому что
    «параллельна» — это утверждение о ПУТИ, а не о нуле лидара: на дуге ноль
    лидара сам уходит из коридора (тот же урок, что в `_usable`).

    Возвращается дальность ПОСЛЕДНЕЙ кромки, где отступ ещё держится. Стена
    при этом не отбрасывается: её ближняя часть измерена верно и годится для
    ведения — режется только хвост, ушедший на путь.
    """
    if wall.n_bins < 2 * OFF_SHRINK_MIN:
        # Коротких стен это правило не касается: затравки и хода по ним не
        # набрать, а отбросить честную короткую стену хуже, чем пропустить
        # редкий заворот.
        return np.inf
    ax = np.array([lat_of(x) for x in wall.d], dtype=float)
    # За последним бином оси `lat_at` честно отдаёт nan: там сверять не с чем,
    # и эти кромки в правило не входят (а не подставляют ноль лидара).
    ok = np.isfinite(ax)
    if ok.sum() < 2 * OFF_SHRINK_MIN:
        return np.inf
    dd, off = wall.d[ok], wall.e[ok] - ax[ok]
    seed = float(np.median(off[:OFF_SHRINK_MIN]))
    if not np.isfinite(seed) or abs(seed) < OFF_MIN:
        # Затравка сама внутри габарита: стеной для ведения эта линия не
        # является с самого начала, и резать по ней нечего.
        return np.inf
    # Сошлась = отступ упал ниже доли затравки ЛИБО сменил знак. Знак проверяем
    # отдельно: на крутом заворote линия может перескочить порог за один бин.
    bad = (np.sign(off) != np.sign(seed)) | (np.abs(off) < OFF_SHRINK * abs(seed))
    if not bad.any():
        return np.inf
    first = int(np.argmax(bad))
    if first == 0:
        return -np.inf          # сошлась уже в затравке: вести по ней нельзя
    return float(dd[first - 1])


def _usable(walls, d, axis=None, ref=None, limit=None):
    """Стены, пригодные для ведения в бине d -> {side: (Wall, вынос)}.

    Пригодна = невязка ниже WALL_RMS_MAX и бин лежит в пределах
    экстраполяции. Из нескольких на сторону берётся БЛИЖНЯЯ К ОСИ ПУТИ:
    дальняя на этой дальности — стена второго пути или дальний борт зала.
    Отделять своё от чужого — дело ведения, поэтому решается здесь, а не в
    детекции (см. MAX_OFF в check_wall).

    СТОРОНА СЧИТАЕТСЯ ОТ ОСИ ПУТИ, А НЕ ОТ НУЛЯ ЛИДАРА, и `w.side` здесь не
    используется вовсе. `w.side` — сторона относительно нуля лидара, и на дуге
    она не имеет смысла: путь уходит вбок, ноль лидара оказывается вне
    коридора, и стена может быть слева от нуля, оставаясь СПРАВА от пути.

    Замер roundT_pressureGate_roundT f115 (гейт, путь уходит влево до -12.3 м
    на 120 м). Детекция даёт две правильные стены с устойчивыми отступами от
    истинного пути по карте:

        стена 2-128 м  отступ +2.41 +2.34 +2.44 +2.61 +2.70 +2.53  -> ПРАВАЯ
        стена 2- 58 м  отступ -2.57 -2.50 -2.27                    -> ЛЕВАЯ

    но ПЕРВАЯ помечена `side = -1` (L): в ближней зоне её кромка лежит на
    +2.21, а `_stitch` сшил половинки через ноль и присвоил стороне дальней
    половины, где стена уже левее нуля. По `w.side` обе стены оказывались
    слева, пара для CENTER не складывалась НИКОГДА, а в LEAD отступ применялся
    с обратным знаком — ось уезжала на +3.76 м вправо там, где путь шёл влево.
    Это и был дефект «на прямой выбирается ведущая вместо середины» и «ось
    выходит за стены».
    """
    # Отсчёт стороны ведётся РЕКУРРЕНТНО: `ref` — ось, построенная в
    # предыдущем бине. Прямая ось годится только в ближней зоне, а дальше она
    # сама промахивается (4.75 м на 70 м), и сторона по ней стала бы неверной
    # ровно там, где это важнее всего — на дуге. Тот же урок, что в замере 2
    # axis_wall: окно едет ЗА ОСЬЮ бин за бином, а не привязано к нулю лидара.
    if ref is not None and not np.isnan(ref):
        a = float(ref)
    elif axis is not None:
        a = float(axis_at(axis, d))
    else:
        a = 0.0
    out = {}
    for w in walls:
        if w.rms > WALL_RMS_MAX:
            continue
        if limit is not None and d > limit.get(id(w), np.inf):
            # Дальше этой дальности стена уже не параллельна пути: её отступ
            # сошёлся к нулю, и хвост линии лежит по другую сторону пути
            # (`cross_limit`). Ближняя часть той же стены осталась пригодной —
            # отбрасывается только хвост.
            continue
        v = _wall_lat(w, d)
        if np.isnan(v):
            continue
        side = -1 if v < a else +1
        if abs(v - a) > OFF_LEAD_MAX:
            # Не наша стена: второй путь двухпутки, дальний борт зала или
            # край платформы. Предел — OFF_LEAD_MAX = 3.5 м, а НЕ OFF_MAX =
            # 8.0 м: восемь метров отвечают на вопрос «бывает ли стена так
            # далеко» (бывает), а здесь нужен другой — «своя ли она». Замер
            # 115 стен против карты даёт разрыв 2.6..4.3 м, и чужой борт в
            # 6.7 м проходил через OFF_MAX беспрепятственно (см. константу).
            #
            # Симметричной отсечки снизу (по OFF_MIN) здесь НЕТ намеренно. Она
            # была написана и откачена: на f51/f19 давала выигрыш (max 2.01 ->
            # 1.26 и 0.61 -> 0.41), но f115 ломала втрое (med 0.12 -> 1.33),
            # отбрасывая там хорошие стены. Дефект, который она пыталась
            # закрыть, — стена, ПЕРЕСЕКАЮЩАЯ путь на дальности (f71: своя
            # левая идёт с отступом -2.53 -> -0.17 -> +2.20, то есть меняет
            # знак на ~103 м) — виден только по ХОДУ отступа вдоль стены, а не
            # по одному бину. Его место — в правиле «отступ не меняет знак»
            # вместе с остальными правилами выбора стороны.
            continue
        best = out.get(side)
        if best is None or abs(v - a) < abs(best[1] - a):
            out[side] = (w, v)
    return out


def _rails_lat(axis, d):
    """Ось от рельсов на дальности d, м, или nan, если рельсов там нет.

    Прямая ось блока 1 измерена по ближней зоне (NEAR_FWD до 30 м) и за ней
    лишь продолжена. Продолжать её далеко нельзя — на кривой она промахивается
    втрое больше габарита (замер в axis_wall: 4.75 м на 70 м при полугабарите
    1.70 м). Поэтому RAILS живёт только там, где рельсы НАБЛЮДАЛИСЬ.
    """
    if axis is None or not axis.get('measured'):
        return np.nan
    obs = axis.get('obs_fwd')
    if obs is None or len(obs) == 0:
        return np.nan
    if d > float(np.max(obs)) + BIN / 2:
        return np.nan
    return float(axis_at(axis, d))


def center_agrees(walls, axis, limit=None):
    """Согласна ли середина пары стен с осью ОТ РЕЛЬСОВ -> bool.

    Правило, ради которого функция написана: ось сначала идёт от рельсов, и
    передача её стенам не вправе эту ось СДВИНУТЬ. Пара, которая не объясняет
    ось там, где ось известна точно, не объясняет её и дальше — значит, вести
    по её середине нельзя.

    Проверяется в ближней зоне ЭТОГО кадра (там же, где меряется отступ, см.
    `axis_wall.measure_offset`): для каждого бина, где рельсы наблюдались,
    берётся середина между кромками и сравнивается с осью от рельсов. Решает
    МЕДИАНА по бинам, а не худший бин: одиночная помеха на кромке (ниша,
    столб) не должна отменять режим — тот же принцип "один бин помеха, два
    сигнал", что в UP_RUN и RESID_RUN.

    Сверяется ХОД, А НЕ ПОЛОЖЕНИЕ: из обеих величин вычитается их значение на
    первом сверяемом бине, и сравнивается, одинаково ли они идут дальше.
    Постоянный сдвиг между серединой и прямой осью законен (прямая ось блока
    1 стоит на своём lat0, а середина — на геометрии тоннеля), и отменять по
    нему честную пару нельзя. Замер roundT_pressureGate_roundT f232: рельсы
    наблюдались до 28.5 м, и на 12.5-27.5 м середина двух честных стен даёт
    +0.31/+0.48/+0.71/+0.99 против КАРТЫ +0.26/+0.39/+0.65/+0.94 — совпадение
    до 5-9 см, то есть середина права. Прямая ось там же даёт
    -0.59/-0.57/-0.55/-0.53, расходясь с картой на 0.85-1.47 м: она уже
    промахивается, хотя формально `measured`. Сравнение ПОЛОЖЕНИЙ давало
    расхождение 0.90-1.52 м, проверка запрещала CENTER, и кадр уходил в LEAD
    по стене, пересекающей путь (ось улетала на +18 м). По ходу расхождение
    там 0.05 м, и пара принимается.

    False и тогда, когда сверить негде (рельсов нет, пары нет): режим,
    который нечем подтвердить, не применяется. Это та же сторона ошибки, что
    у всего блока — отказ от ведения честнее ведения по непроверенному.
    """
    if axis is None or not axis.get('measured'):
        return False
    obs = axis.get('obs_fwd')
    if obs is None or len(obs) == 0:
        return False
    omax = float(np.max(obs))
    cc, aa = [], []
    for d in np.arange(BIN / 2, omax, BIN):
        if d < BIN * 2:
            continue      # бины под поездом: там кромка ещё не стена
        wa = _usable(walls, float(d), axis, None, limit=limit)
        if len(wa) != 2:
            continue
        # Без `ref`: перекос пары здесь НЕ проверяется намеренно. Эта функция
        # отвечает на свой вопрос — «объясняет ли пара ось от рельсов», и
        # сверяет ХОД, а не положение. Отсеяв тут перекошенные бины, мы
        # оставили бы функцию без данных ровно на тех кадрах, где пара плоха,
        # и она вернула бы False «нечем сверить» вместо честного ответа.
        c, _ = _center(wa)
        if np.isnan(c):
            continue
        cc.append(c)
        aa.append(float(axis_at(axis, float(d))))
    if len(cc) < 2:
        # Одного бина мало: по нему ход не построить, а по положению
        # сверять нельзя (см. докстроку).
        return False
    cc = np.asarray(cc) - cc[0]
    aa = np.asarray(aa) - aa[0]
    return float(np.median(np.abs(cc - aa))) <= CENTER_VS_RAILS


def _center(pair, ref=None):
    """Середина между двумя кромками -> (ось, ширина) или (nan, nan).

    Три причины отказать паре, и все три — об одном: это не два борта
    ОДНОГО тоннеля.

      WIDTH_MIN      уже физического коридора: кромки цепляются не за стены
      WIDTH_MAX      шире всякого тоннеля: второй путь или дальний борт зала
      PAIR_FAR_MAX   пара ПЕРЕКОШЕНА: ближняя кромка на штатном отступе, а
                     дальняя ускакала (выезд на двухпутку, край платформы)

    Перекос меряется от `ref` — оси предыдущего бина, потому что «далеко»
    это утверждение о ПУТИ, а не о нуле лидара: на дуге ноль лидара сам
    уходит из коридора (тот же довод, что в `_usable`). Без `ref` проверка
    не делается: сверять не с чем, а отменять пару по нулю лидара — значит
    получить отказ на каждом кадре дуги.

    Отказ здесь означает «ведения по середине не будет», и дальше `_pick`
    сам падает в LEAD по одной стене. Это ровно та сторона ошибки, которую
    держит весь блок: у LEAD есть ИЗМЕРЕННЫЙ отступ, и он ось не двигает, а
    середина ложной пары двигает её скачком.
    """
    (_, vl), (_, vr) = pair[-1], pair[+1]
    width = abs(vr - vl)
    if not (WIDTH_MIN <= width <= WIDTH_MAX):
        return np.nan, np.nan
    if ref is not None and not np.isnan(ref):
        if max(abs(vl - ref), abs(vr - ref)) > PAIR_FAR_MAX:
            return np.nan, np.nan
    return (vl + vr) / 2.0, width


def _bump(walls_at, lat, d, off, memo):
    """В какую стену упёрся путь -> side или 0.

    ПЕРВИЧНЫЙ признак заворота, словами заказчика: «если габарит упирается в
    стену и она проходит дальше — мы считаем стену ведущей и делаем от неё
    отступ и линию выстраиваем».

    Упор — это ПЕРЕКОС: ось прижата к одной кромке заметно сильнее, чем к
    другой (больше чем на 2*GAUGE_CLEAR). На дуге именно так: внешняя стена
    имеет больший радиус, хорда сужается, и середина двух кромок съезжает к
    внутренней стене, хотя путь идёт вдоль внешней.

    ИЗВЕСТНОЕ ОГРАНИЧЕНИЕ: `lat` здесь — середина коридора, а у неё зазоры до
    кромок РАВНЫ по построению, то есть в режиме CENTER перекос тождественно
    ноль и упор не срабатывает. Плавное сужение на гейте этим не ловится
    (замер roundT_pressureGate_roundT f51: коридор 4.81 -> 2.37 м на 62-122 м,
    перекос 0.00 на каждом бине, CENTER держался до 117 м, ошибка росла до
    0.50 м, а потом ось рывком падала в LEAD и промахивалась на -3.8 м;
    сужение 0.06..0.32 м на бин, так что и WIDTH_JITTER молчал).

    Пробовали мерить перекос от ИНЕРЦИИ — продолжения уже построенных бинов.
    Замер это ловило, но на кино ось задрожала: режим стал меняться от бина к
    бину, а ось прыгать между серединой и кромкой с отступом. Рельс так не
    идёт, и правка откачена (коммит «Упор в стену считается от инерции»).
    Возвращать её можно только вместе со сглаживанием оси — дрожь хуже, чем
    поздний переход.

    Абсолютные пороги здесь не годятся, и оба уже были ошибкой:
      * с полугабаритом (1.70) — упор выходил на КАЖДОМ бине нормальной
        прямой, где стены штатно стоят в 1.44..1.72 м;
      * с собственным отступом стены — упор выходил всюду, где тоннель просто
        УЖЕ отступа, измеренного в ближней зоне (замер doubleT_platform f19:
        середина ровно в 1.98 м от каждой стены, слева измерено 2.56 м, и
        «стена ближе своего отступа» объявляло упор на 32-77 м).

    Вторая половина правила не менее важна первой: стена ПРОХОДИТ ДАЛЬШЕ (не
    меньше LEAD_AHEAD), иначе упор — торец или ниша, вести по ней некуда.
    """
    if len(walls_at) < 2:
        return 0
    (wl, vl), (wr, vr) = walls_at[-1], walls_at[+1]
    gl, gr = abs(vl - lat), abs(vr - lat)
    if abs(gl - gr) < 2 * GAUGE_CLEAR:
        return 0                  # коридор симметричен: середина и есть ось
    side = -1 if gl < gr else +1
    w = wl if side < 0 else wr
    if w.d_hi - d < LEAD_AHEAD:
        return 0
    return side


def _lead_off(side, off, memo):
    """Отступ для ведения по стене side -> (отступ, измерен ли он).

    Порядок: измерение этого кадра в ближней зоне -> запомненное с прошлых
    бинов -> OFF_FALLBACK. Знак отступа всегда уводит ось ОТ стены к нулю
    лидара: стена слева (side=-1) -> ось правее.

    Отбраковывается то, что вне диапазона OFF_MIN..OFF_LEAD_MAX: такой
    «отступ» значит, что кромка зацепилась не за свою стену. Верхний предел —
    OFF_LEAD_MAX = 3.5 м, а не OFF_MAX = 8.0 м, по той же причине и по тому же
    замеру, что в `_usable`: своя стена стоит в 1.8..2.6 м, чужая в 4.3..7.0,
    и восемь метров не ловят ничего. Габаритный зазор здесь ни при чём — в
    тоннеле стена стоит ближе полугабарита, и это норма (см. OFF_MIN).
    """
    v = np.nan
    if off is not None and side in off and not np.isnan(off[side]):
        v = abs(float(off[side]))
    elif not np.isnan(memo.get(side, np.nan)):
        v = abs(memo[side])
    if np.isnan(v) or not (OFF_MIN <= v <= OFF_LEAD_MAX):
        # Зеркало берётся раньше дефолта: честная сторона того же кадра — это
        # измерение ЭТОГО тоннеля, а OFF_FALLBACK = 1.60 м лишь медиана по
        # чужим бэгам (на roundT_doubleT зеркало даёт 2.0 м против 1.6 м).
        # off_measured при этом остаётся False, и картинка честно ставит
        # пустой квадрат «отступ не измерен».
        other = np.nan
        if off is not None and -side in off and not np.isnan(off[-side]):
            other = abs(float(off[-side]))
        if np.isnan(other):
            other = abs(memo.get(-side, np.nan))
        if not np.isnan(other) and OFF_MIN <= other <= OFF_LEAD_MAX:
            return other, False
        return OFF_FALLBACK, False
    return v, True


def _hold(bins, d):
    """Продолжение формы оси в дыре -> вынос, м, или nan.

    Парабола по последним HOLD_WIN известным бинам с ограничением кривизны:
    без ограничения фит по четырём точкам на дуге улетает (тот же смысл, что
    у HOLD_CURV). Дальше HOLD_MAX за последним измерением не продолжаем.
    """
    known = [b for b in bins if b.mode != HOLD][-HOLD_WIN:]
    if len(known) < 3:
        return np.nan
    dd = np.array([b.d for b in known])
    ll = np.array([b.lat for b in known])
    if d - dd[-1] > HOLD_MAX:
        return np.nan
    a, b1, c = np.polyfit(dd, ll, 2)
    if abs(2.0 * a) > HOLD_CURV:
        # Кривизна за пределом экстраполяции: парабола ведёт не путь, а свой
        # собственный разгон. Продолжаем по прямой — касательной в последней
        # известной точке.
        slope, icpt = np.polyfit(dd, ll, 1)
        return float(icpt + slope * d)
    return float(a * d * d + b1 * d + c)


def _lead(walls_at, side, off, memo):
    """Ведение по стене `side` -> (mode, lat, side, wall, off, width).

    Ведущая ВСЕГДА одна: вторая стена в этом режиме не участвует, даже если
    видна. Отступ уводит ось от стены к нулю лидара (side=-1 -> ось правее).
    Знак `off` в кортеже несёт, измерен ли отступ: минус — взят по умолчанию
    (распаковывается в `build`), потому что `Bin` держит это отдельным полем.
    """
    wall, v = walls_at[side]
    o, measured = _lead_off(side, off, memo)
    return LEAD, v - side * o, side, wall, o * (1 if measured else -1), np.nan


def _pick(walls_at, axis, d, off, memo, center_ok=True, ref=None):
    """Какой режим применим в бине d -> (mode, lat, side, wall, off, width).

    Приоритет RAILS -> CENTER -> LEAD. HOLD решается вызывающим: он один
    знает историю оси. Здесь же — только то, что видно в этом бине.

    Упор (`_bump`) проверяется от СЕРЕДИНЫ коридора. Пробовали от инерции —
    продолжения уже построенных бинов: по замеру это ловило плавное сужение на
    гейте, которого не видит ни перекос от середины (он там тождественно ноль),
    ни WIDTH_JITTER. Но на кино ось от этого задрожала — режим стал меняться от
    бина к бину, а ось прыгать между серединой и кромкой с отступом. Рельс так
    не идёт, и откачено именно поэтому (коммит «Упор в стену считается от
    инерции»): дрожь хуже, чем поздний переход. Возвращать это можно только
    вместе со сглаживанием оси, а не само по себе.

    Правило целиком, словами заказчика: «на прямой используется 2 — когда 2
    стабильные; когда не стабильные — по одной стабильной ближней. А в стену
    упираемся когда в заворот уходит и стена в заворот уходит.»
    """
    lat = _rails_lat(axis, d)
    if not np.isnan(lat):
        return RAILS, lat, 0, None, np.nan, np.nan

    # Две стабильные стены -> середина. Обе нужны только чтобы НАЙТИ её:
    # ведущей здесь нет и отступ не нужен — он вычитается сам. На прямой это
    # устойчивее ведения по одной: ошибки двух кромок частично гасятся, и не
    # надо выбирать сторону произвольно (открытый дефект старого ведения —
    # 21% смен ведущей стороны между соседними кадрами).
    # center_ok — согласие пары с рельсами, проверенное на кадр целиком
    # (`center_agrees`). Пара, которая в ближней зоне не объясняет ось от
    # рельсов, не получает ведения вовсе: её середина увела бы ось скачком
    # ровно там, где рельсы кончились (замер: зал 9 м, +2.0 м на каждом
    # кадре doubleT_obstacle). Тогда остаётся LEAD по одной стене — у него
    # есть измеренный отступ, и он ось не двигает.
    #
    # `center_ok` — проверка НА КАДР, и одной её мало: пара может сложиться
    # ПОЗЖЕ зоны рельсов, где сверять уже не с чем. Замер roundT_doubleT f118
    # (выезд на двухпутку): в зоне рельсов честная пара 2-48 / 2-32 м,
    # center_agrees = True; на 57.5 м левая стена сходится с ДАЛЬНЕЙ линией
    # 62-112 м, ширина 10 м (WIDTH_MAX = 24 пропускает), и ошибка против карты
    # скачет +0.72 -> +2.07 в том же бине, а дальше LEAD цепляется за эту
    # дальнюю стену и держит +4.7 м пятьдесят метров. cross_limits пару тоже
    # не ловит: общего плеча у них нет вовсе (одна кончается на 47.5, вторая
    # начинается на 62.5 — короче PAIR_SPAN). Поэтому перекос пары проверяется
    # ПОБИННО, внутри `_center`, а не один раз на кадр.
    if center_ok and len(walls_at) == 2:
        lat, width = _center(walls_at, ref)
        if not np.isnan(lat):
            # ...но если путь уже упёрся в стену, которая
            # идёт дальше, — это заворот, и середина больше не ось.
            side = _bump(walls_at, lat, d, off, memo)
            if side:
                return _lead(walls_at, side, off, memo)
            return CENTER, lat, 0, None, np.nan, width

    # Одна стена (вторая не найдена или нестабильна) -> ведём по ней. Из двух,
    # не давших середины, берётся БЛИЖНЯЯ К ОСИ ПУТИ: дальняя на этой
    # дальности — стена второго пути или дальний борт зала, и отступ до неё не
    # тот, что измерен в ближней зоне.
    #
    # Близость считается от `ref` (ось предыдущего бина), А НЕ ОТ НУЛЯ ЛИДАРА,
    # по той же причине, что в `_usable`: на дуге путь уходит вбок, ноль лидара
    # оказывается вне коридора, и «ближняя к нулю» — уже не «ближняя к пути».
    # Замер roundT_doubleT f118 (52.5 м, путь по карте на -4.66): своя стена
    # 2-48 м стоит на -7.0, чужая 62-112 м на +2.5. По модулю от нуля ближе
    # ЧУЖАЯ (2.5 против 7.0), ведение уходило на неё и держало ошибку +4.7 м
    # полсотни метров. От оси ближе своя (2.3 против 7.2), и выбор верен.
    if walls_at:
        a = float(ref) if (ref is not None and not np.isnan(ref)) else 0.0
        side = min(walls_at, key=lambda s: abs(walls_at[s][1] - a))
        return _lead(walls_at, side, off, memo)
    return None, np.nan, 0, None, np.nan, np.nan


def build(walls, axis, off=None, max_range=MAX_RANGE, _limit=None):
    """Ось пути по правилам ведения -> список `Bin` от 0 до max_range.

    walls — все стены кадра из `check_wall.detect` (про ось не знают).
    axis  — прямая ось из `track.straight_axis` (ось от рельсов, истина в
            ближней зоне).
    off   — отступ стена->путь, измеренный в ближней зоне ЭТОГО кадра, как его
            выдаёт `axis_wall.measure_offset`: {-1: слева, +1: справа}, nan
            там, где не измерен. Без него LEAD берёт нижнюю границу физики и
            помечает бины как неизмеренные.

    Каждый бин объясняет себя сам: режим, ось, ведущая стена, отступ. Это и
    есть то, что рисует plot_axis и по чему правятся пороги.
    """
    if _limit is None:
        _limit = cross_limits(walls, axis)
    # Согласие пары с рельсами — один раз на кадр: вопрос "объясняет ли эта
    # пара ось там, где ось известна" от бина не зависит.
    center_ok = center_agrees(walls, axis, limit=_limit)

    memo = {-1: np.nan, +1: np.nan}
    if off is not None:
        for s in (-1, +1):
            if s in off and not np.isnan(off[s]):
                memo[s] = abs(float(off[s]))

    bins, pend = [], []
    prev_width = np.nan
    for lo in np.arange(0.0, max_range - 1e-9, BIN):
        d = lo + BIN / 2
        # Сторона стены считается от ОСИ, и ось эта — предыдущий бин (в ближней
        # зоне её нет, там берётся прямая). Ведение рекуррентно, и вопрос
        # «слева или справа» не возникает: см. `_usable`.
        ref = bins[-1].lat if bins else None
        walls_at = _usable(walls, d, axis, ref, limit=_limit)
        mode, lat, side, wall, o, width = _pick(walls_at, axis, d, off, memo,
                                                center_ok=center_ok, ref=ref)

        # Согласие двух стен проверяется ВДОЛЬ дальности, а не в одном бине:
        # ширина, скакнувшая между соседними бинами, значит, что коридор уже
        # не тот же самый (гейт, платформа, двухпутка). Тогда середина не ось,
        # и надо падать в LEAD по непрерывной стене.
        if (mode == CENTER and not np.isnan(prev_width)
                and abs(width - prev_width) > WIDTH_JITTER):
            # Ведём по той, что тянется ДАЛЬШЕ: ширина скакнула, значит одна из
            # кромок сменила объект, и опорой должна быть непрерывная стена.
            side = max(walls_at, key=lambda s: walls_at[s][0].d_hi)
            mode, lat, side, wall, o, width = _lead(walls_at, side, off, memo)

        if mode is None:
            lat = _hold(bins, d)
            if np.isnan(lat):
                # Ни измерения, ни права продолжать форму: ось кончилась.
                break
            mode = HOLD

        # Гистерезис: ПОВЫШЕНИЕ приоритета (к рельсам или ко второй стене)
        # требует UP_RUN бинов подряд, понижение — мгновенно. Один выброс на
        # стене иначе дёргает ось (замер 4 в axis_wall: платформа даёт разовый
        # выброс, поворот — монотонный рост).
        if bins:
            was, now = MODES.index(bins[-1].mode), MODES.index(mode)
            if now < was:
                pend.append(mode)
                if len(pend) < UP_RUN:
                    # Держим прежний режим, пока новый не подтвердится.
                    keep = bins[-1]
                    if keep.mode == LEAD and keep.side in walls_at:
                        w2, v2 = walls_at[keep.side]
                        mode, wall, side = LEAD, w2, keep.side
                        o, measured = _lead_off(keep.side, off, memo)
                        lat = v2 - keep.side * o
                        o = o * (1 if measured else -1)
                        width = np.nan
                    else:
                        lat = _hold(bins, d)
                        if np.isnan(lat):
                            lat = keep.lat
                        mode, side, wall = HOLD, 0, None
                        o = width = np.nan
                else:
                    pend = []
            else:
                pend = []

        # `tight` — НАСТОЯЩАЯ аномалия, а не признак заворота: упор в стену
        # уже разобран выше и стал причиной перехода в LEAD. Пометка остаётся
        # только там, где зазора не хватает ДАЖЕ в ведении с отступом (отступ
        # устарел, стена не та) или где упёрлись в стену, которая тут же
        # кончается, — вести по ней было нельзя (LEAD_AHEAD), а габарит в неё
        # всё равно лезет. Ось не правится: на завороте стена и путь
        # концентричны, отступ постоянен, и молчаливая правка дала бы ось,
        # которая на картинке не задевает стен, но врёт по сути.
        # Порог — НЕ полугабарит: в тоннеле стена штатно стоит ближе него
        # (замеренный отступ 1.44..1.72 при полугабарите 1.70), и сравнение с
        # габаритом пометило бы каждый бин нормальной прямой. Аномалия — когда
        # ось подошла к стене ближе, чем физически бывает отступ: кромка
        # зацепилась не за ту стену или ось уехала.
        tight = any(abs(v - lat) < OFF_MIN for _, v in walls_at.values())

        if o is not None and not np.isnan(o) and o < 0:
            bins.append(Bin(d, mode, lat, side, wall, -o, False, width, tight))
        else:
            bins.append(Bin(d, mode, lat, side, wall, o, True, width, tight))
        prev_width = width if mode == CENTER else np.nan

        if mode == LEAD and side and not np.isnan(bins[-1].off) \
                and bins[-1].off_measured:
            memo[side] = bins[-1].off
    return bins


def lat_at(bins, d):
    """Ось на дальности d, м, по построенным бинам (линейно между центрами).

    За последним бином — nan: там оси нет, и делать вид, что есть, нельзя.
    """
    if not bins:
        return np.nan
    dd = np.array([b.d for b in bins])
    ll = np.array([b.lat for b in bins])
    d = float(d)
    if d < dd[0]:
        return float(ll[0])
    if d > dd[-1]:
        return np.nan
    return float(np.interp(d, dd, ll))


def leading(bins):
    """Ведущая стена кадра -> (`Wall`, side) или (None, 0).

    Заменяет старую `check_wall.leading`, которая отвечала на другой вопрос
    («какая стена наружная») и на прямой возвращала None. Здесь ведущая — та,
    по которой ось РЕАЛЬНО построена: стена самого дальнего бина в режиме
    LEAD. На прямой ось идёт по рельсам и середине, и ведущей стены нет — это
    тот же None, но по другой, честной причине.
    """
    for b in reversed(bins):
        if b.mode == LEAD and b.wall is not None:
            return b.wall, b.side
    return None, 0


def summary(bins):
    """Одна строка про ось кадра: сколько бинов в каком режиме, докуда.

    Для заголовка картинки и для отладки в консоли.
    """
    if not bins:
        return 'оси нет'
    cnt = {m: sum(1 for b in bins if b.mode == m) for m in MODES}
    parts = [f'{m} {cnt[m]}' for m in MODES if cnt[m]]
    w, side = leading(bins)
    txt = f'ось до {bins[-1].d:.0f} м [' + ', '.join(parts) + ']'
    if w is not None:
        off = next((b.off for b in reversed(bins) if b.mode == LEAD), np.nan)
        txt += (f', ведёт {"L" if side < 0 else "R"} {w.d_lo:.0f}-{w.d_hi:.0f} м'
                f' отступ {off:.2f}')
    n_tight = sum(1 for b in bins if b.tight)
    if n_tight:
        txt += f', TIGHT {n_tight}'
    return txt
