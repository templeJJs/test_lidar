"""Общая геометрия кадра: система координат, пол, ближние рельсы.

Система координат лидара во всех бэгах: x вправо, y НАЗАД, z вверх.
Вперёд — это -y. Чтобы не тащить минус через весь код, здесь один раз
делается переход к рабочей тройке (fwd, lat, up):

    fwd = -y   дальность вперёд, м
    lat =  x   поперёк пути, м (вправо +)
    up  =  z   высота, м

Дальше по всему пакету используются только fwd/lat/up.
"""

import numpy as np

# Пол ищется под самим поездом: там он гарантированно есть и не заслонён.
FLOOR_FWD = (2.0, 30.0)   # окно дальности для оценки пола, м
FLOOR_LAT = 1.5           # полуширина окна поиска пола, м
FLOOR_Q = 2.0             # перцентиль Z: не минимум, чтобы один выброс не увёл
FLOOR_COL = 0.25          # ширина колонки поперёк пути для оценки пола, м
FLOOR_MIN_PTS = 200       # меньше — оценке верить нельзя
FLOOR_FALLBACK = -2.0     # уровень ПОЛА, а не головок: лидар на 1.65-1.73 м
                         # над головками, а пол на 0.30-0.45 м ниже головок
                         # (двугорбая гистограмма, README "Блок 1"), итого
                         # пол на -(1.65..1.73) - (0.30..0.45) ~ -1.95..-2.18.
                         # Значение -1.65 было высотой головок и смещало полосу
                         # поиска H_LO..H_HI выше рельсов — ось терялась.


def to_frame(pts):
    """Облако кадра -> (fwd, lat, up), каждый массив float."""
    p = np.asarray(pts, dtype=float)
    return -p[:, 1], p[:, 0], p[:, 2]


def floor_level(fwd, lat, up):
    """Уровень пола в кадре, м.

    Берётся перцентиль высоты под поездом, а не минимум по всему облаку:
    минимум ловит одиночный выброс, а дальний балласт лежит ниже ближнего.
    """
    m = (fwd > FLOOR_FWD[0]) & (fwd < FLOOR_FWD[1]) & (np.abs(lat) < FLOOR_LAT)
    if m.sum() < FLOOR_MIN_PTS:
        return FLOOR_FALLBACK
    # Q2 считается в каждой колонке по FLOOR_COL м, итог — медиана по
    # колонкам, а не общий Q2 по полосе: общий перетягивался дренажным
    # жёлобом между рельсами (f1 cloud_with_fake_obj: 7% точек окна на
    # z=-1.9..-1.6 давали пол -1.678 вместо -1.44, и постель всплывала в
    # габарит). Жёлоб — 3-4 центральные колонки из 12 и медиану по колонкам
    # не переопределяет: пол — поверхность под всей шириной пути, жёлоб —
    # узкий канал. На кадрах без жёлоба оценка та же (f400: -1.442 ->
    # -1.429).
    lat_m, up_m = lat[m], up[m]
    col = np.floor(lat_m / FLOOR_COL)
    lev = [np.percentile(up_m[col == c], FLOOR_Q) for c in np.unique(col)]
    return float(np.median(lev))
