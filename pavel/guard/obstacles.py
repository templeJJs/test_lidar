def _column_height(zs, floor, gap=COL_GAP, step=COL_STEP):
    """Верх сплошной снизу части колонки точек, м над полом.

    Человек и свод попадают в одну ячейку по X, поэтому max(Z) описывает не
    объект, а тоннель. Высота растёт, пока слои идут подряд, и обрывается на
    первом разрыве в `gap` метров. Разрыв ищется по ГИСТОГРАММЕ, а не по
    соседним точкам: одиночные точки на стойке над головой смыкают зазор, и
    колонна человека тянулась до свода (замер doubleT_obstacle f140-f180:
    высота 3.70 м у той же цели, что в соседних кадрах давала 1.2 м).
    """
    zs = np.sort(np.asarray(zs, dtype=float) - floor)
    if len(zs) == 0:
        return 0.0
    nb = max(1, int(np.ceil((zs[-1] - zs[0]) / step)) + 1)
    cnt, edges = np.histogram(zs, bins=nb, range=(zs[0], zs[0] + nb * step))
    occ = cnt >= (2 if len(zs) >= COL_DENSE else 1)
    run = int(np.ceil(gap / step))
    top = zs[0]
    empty = 0
    for i, o in enumerate(occ):
        if o:
            top = min(edges[i + 1], zs[-1])
            empty = 0
        else:
            empty += 1
            if empty >= run:
                break
    return float(top)


def _vsplit_ranges(h, gap=COL_GAP, step=COL_STEP):
    """Высотные диапазоны непрерывных по вертикали частей колонки точек.

    Гистограмма, шаг слоя и занятость слоя — те же, что в _column_height;
    часть обрывается на разрыве >= gap. Возвращает список (h_lo, h_hi) в
    метрах над полом; точки незанятых (одиночных при плотном кластере) слоёв
    не входят ни в одну часть — это и есть отсекаемый шум.
    """
    h = np.asarray(h, dtype=float)
    if not len(h):
        return []
    h0 = float(h.min())
    nb = max(1, int(np.ceil((float(h.max()) - h0) / step)) + 1)
    cnt, ed = np.histogram(h, bins=nb, range=(h0, h0 + nb * step))
    occ = cnt >= (2 if len(h) >= COL_DENSE else 1)
    run = int(np.ceil(gap / step))
    segs = []
    lo = None
    empty = 0
    for i, o in enumerate(occ):
        if o:
            if lo is None:
                lo = i
            empty = 0
        elif lo is not None:
            empty += 1
            if empty >= run:
                segs.append((float(ed[lo]), float(ed[i - empty + 1])))
                lo = None
                empty = 0
    if lo is not None:
        segs.append((float(ed[lo]), float(ed[len(occ)])))
    return segs


def _band_line(d_pts, h_pts, f_pts, de, he,
               floor_visible, wall_l, wall_r, raw_l, raw_r):
    """Стеновая линия с низким хвостом внутрь габарита (контактный рельс +
    флуктуирующий слой полотна, cloud_with_fake_obj f1-40): кластер КАСАЕТСЯ
    полосы WALL_RIPPLE доверенной кромки (кромка уже прошла проверку доверия
    в detect — самообъяснения нет), масса полосы >= 2/3 кластера и верх
    полосы ниже нормы низкой продольной линии (LOW_LINE_TOP: контактный
    рельс <= 0.77 м по замеру), а ВНУТРЕННИЙ остаток (точки вне полосы) сам
    по себе был бы объяснён штатными правилами (проверяется рекурсивным
    прогоном тех же правил — новых порогов не вводится) — тогда это линия у
    стены, а не вторжение. Без правила хвост заимствовал у подошвы стены
    высоту и массу и проходил глубокую ветку освобождения 'dust' с
    параметрами один в один как у плиты f789 — мигание f10-12/f17-22.
    Разделение по замерам роя: у блинкера 72-84% массы в полосе и верх
    полосы 0.85, остаток — слой 0.27-0.40 м с spread 3.6-4.2 (объяснялся бы
    'dust' без освобождения: верх 0.40 < DUST_EXC_LO_TOP); плита f789 — 54%
    в полосе (правило не применяется), щит f581 / диагональ f624 / машина
    f676 — верх полосы 2.3-2.5 (защищены высотным тестом).

    Применяется и к целому кластеру (в detect, до вертикального разреза), и
    к частям разреза (из _explain_cluster): целиком склеенный кластер линия+
    слой правилом ловится, а разрезанные части проходят свою проверку.
    """
    if not len(h_pts):
        return False
    for edge, sgn in ((wall_r, 1), (wall_l, -1)):
        if not np.isfinite(edge):
            continue
        inner = (d_pts < edge - WALL_RIPPLE
                 if sgn > 0 else d_pts > edge + WALL_RIPPLE)
        if inner.all():          # полосы не касается
            continue
        if int((~inner).sum()) * 3 < len(d_pts) * 2:
            continue             # в полосе меньше 2/3 массы
        if _column_height(h_pts[~inner], 0.0) >= LOW_LINE_TOP:
            continue             # полоса высокая — это не линия у подошвы
        n_in = int(inner.sum())
        if (n_in < OBST_MIN_PTS
                or _column_height(h_pts[inner], 0.0) < OBST_MIN_H):
            return True          # остаток сам по себе находкой не стал бы
        hi = h_pts[inner]
        di = d_pts[inner]
        why_inner = _explain_cluster(
            _column_height(hi, 0.0), hi, f_pts[inner],
            float(di.min()), float(di.max()), float(np.median(di)),
            de, he, di, floor_visible, wall_l, wall_r, raw_l, raw_r)
        if why_inner is not None:
            return True          # остаток был бы объяснён штатным
    return False


def _explain_cluster(col_top, h_pts, f_pts, x0, x1, xc, de, he, d_pts,
                     floor_visible, wall_l, wall_r, raw_l, raw_r):
    """Чем кластер остатка объясняется штатным — или None (тогда препятствие).

    Пять правил, все — про геометрию, а не про объект (никакого описания
    человека: прежний блок 3 был откачен именно за это):

    'column'   — колонна достала до свода (>= COL_TOP_H): пилон, портал,
                 створка. Тот же принцип, что в structures.py.
    'wall'     — кластер целиком в полосе WALL_RIPPLE внутрь от измеренной
                 кромки стены или за ней: это сама стена (кромка — перцентиль
                 стеновых точек, внутрь от неё всегда лежит рябь стены).
                 Только по ИЗМЕРЕННЫМ сторонам: кламп габарита стену не
                 измерял и ничего не объясняет. Сюда же — правило
                 _band_line: кластер, у которого >= 2/3 массы в полосе
                 доверенной кромки, верх полосы ниже LOW_LINE_TOP, а
                 внутренний остаток (вне полосы) сам по себе был бы объяснён
                 штатными правилами (рекурсивный прогон), — линия у стены с
                 низким хвостом, а не вторжение.
    'dust'     — точки размазаны по дальности больше DEPTH_MAX: твёрдый
                 объект впереди виден лицевой гранью и компактен вдоль луча;
                 размах в метры — это пыль рассеяния у стен и между кольцами
                 и продольные линии у края габарита (контактный рельс,
                 платформа, скамейка). Плотное вторжение в габарит (глубоко
                 или высоко, см. константы DUST_EXC_*) правило не объясняет.
    'base'     — колонна НЕ стоит на полотне: её низ выше BASE_MAX над полом.
                 Контактный рельс, подвесы, оборудование над поездом.
                 Отключается, где пол не покрыт кольцами (floor_visible=False):
                 там низ объекта принципиально невидим.
    'fragment' — над верхом колонны в той же полосе поперёк продолжается
                 МАССИВНАЯ (>= FRAG_MIN_ABOVE точек) уже объяснённая
                 конструкция с разрывом не больше FRAG_GAP: это её нижний
                 фрагмент, недобранный блоком 2б.

    Кромка стены засчитывается в правилах 'column' и 'wall', только когда она
    измерена ЗА габаритом (|wall| >= GAUGE_HALF) или СТАБИЛЬНО лежит внутри
    него (медиана окрестности ±PERSIST_BINS бинов внутри габарита — платформа
    или контактный рельс, идущие вдоль всего кадра). Локальный провал кромки
    внутрь габарита — это само препятствие, и оно не может объяснять само
    себя (замер: cloud_with_fake_obj f581, щит мерялся стеной на 0.93 м
    внутри габарита; f624, диагональная стенка мерялась стеной на 0.5 м
    внутри). По той же причине 'fragment' требует массивного продолжения:
    обрезь верха самого препятствия, объяснённая блоком 2б, иначе съедает
    его низ (тот же щит f581 получал 'fragment' с зазором 0.00).

    Порядок важен: 'column' первым — у пилона низ тоже может быть выше пола
    (низ съеден объяснением), а поверхность его реальна и по глубине
    компактна.
    """
    # Кромки стен, прошедшие проверку доверия в detect() (за габаритом или
    # стабильно внутри него): только они — настоящие стены.
    wall_r_out = np.isfinite(wall_r)
    wall_l_out = np.isfinite(wall_l)
    near_wall = ((wall_r_out and x0 >= wall_r - WALL_RIPPLE)
                 or (wall_l_out and x1 <= wall_l + WALL_RIPPLE))
    if col_top >= COL_TOP_H:
        # Колонна до свода объясняется, только если она У КРАЯ коридора
        # (пилон, створка портала у стены). Колонна/подвес посреди пути —
        # препятствие: пилон на пути — это столкновение, свисающий с потолка
        # предмет в габарите — тоже (замер: cloud_with_fake_obj f329-345,
        # подвес на lat +0.45, ~2000 точек, низ ~2.0 м при габарите 2.5 м).
        if near_wall:
            return 'column'
        # середина пути — не объясняем, идём дальше по правилам
    if not len(h_pts):
        return None
    if near_wall:
        return 'wall'
    if _band_line(d_pts, h_pts, f_pts, de, he,
                  floor_visible, wall_l, wall_r, raw_l, raw_r):
        return 'wall'
    # Глубина захода в габарит — min проникновения через обе кромки: кластер
    # у правого края не «зашёл слева» на x1+GAUGE_HALF.
    depth = max(0.0, min(GAUGE_HALF - x0, x1 + GAUGE_HALF))
    # Низ колонны — 5-й перцентиль, а не минимум: одиночный шумовой отскок
    # от балласта не должен «приземлять» подвес.
    base = float(np.percentile(h_pts, 5))
    spread = (float(np.percentile(f_pts, 90) - np.percentile(f_pts, 10))
              if len(f_pts) >= 4 else 0.0)
    if spread > DEPTH_MAX:
        n_pts = len(h_pts)
        # Геометрия коридора для освобождения — по СЫРЫМ измеренным кромкам
        # (raw_*), без проверки доверия: локальный провал кромки на самом
        # объекте не меняет физическую ширину коридора.
        both_in = (np.isfinite(raw_l) and raw_l > -GAUGE_HALF
                   and np.isfinite(raw_r) and raw_r < GAUGE_HALF)
        corr_w = (raw_r - raw_l
                  if np.isfinite(raw_l) and np.isfinite(raw_r)
                  else float('inf'))
        # Масса, слившаяся с ОБЕИМИ кромками коридора (дотягивается до
        # WALL_RIPPLE обеих измеренных кромок) — это само сечение пути
        # (подтопленный/настильный слой полотна, сросшийся в остатке с
        # подошвами обеих стен: замер doubleT_platform f30 — n=3773,
        # x=[-1.6,1.6] при кромках -1.45/+1.8; cloud_with_fake_obj f1208 —
        # слой на всю ширину), а не объект В коридоре: препятствие стоит
        # МЕЖДУ стен и сливается максимум с одной кромкой (замеры: плита
        # f750 — только правая, x=[0.20,1.60] при кромках -1.97/+1.40;
        # огромный объект f1031 — только правая, x=[0.28,1.60]). Такая
        # масса освобождения от 'dust' не получает. Порогов новых нет:
        # WALL_RIPPLE и измеренные кромки — существующие величины.
        touch_both = (np.isfinite(raw_l) and np.isfinite(raw_r)
                      and x0 <= raw_l + WALL_RIPPLE
                      and x1 >= raw_r - WALL_RIPPLE)
        if touch_both:
            return 'dust'
        # Ветки освобождения — замеры у констант DUST_EXC_*.
        deep = (depth >= DUST_EXC_DEEP and corr_w <= DUST_EXC_WIDE
                and not both_in and base <= FLOOR_BASE
                and col_top >= DUST_EXC_LO_TOP)
        tall = (depth >= DUST_EXC_LAT and col_top >= DUST_EXC_TOP
                and n_pts >= DUST_EXC_N_TALL and corr_w <= DUST_EXC_WIDE_TALL
                and (depth >= DUST_EXC_MID or spread <= DUST_EXC_SPREAD))
        # ТВЁРДОЕ ТЕЛО (solid): стоит на полотне (низ <= FLOOR_BASE), верх >=
        # DUST_EXC_LO_TOP, масса >= DUST_EXC_N_TALL, заход > 0 — пыль/линии
        # таким телом не бывают; замер: огромная масса f806 (n=2788, низ
        # 0.11, верх 0.74, заход 0.40) съедалась 'dust' без этой ветки.
        # Контактный рельс (низ 0.60 > FLOOR_BASE), балластные плечи (верх
        # 0.31-0.36) и пылевые кластеры (n <= 60) под ветку не проходят.
        # Коридор ограничен как в соседних ветках (замеренные плато у
        # DUST_EXC_WIDE*): в ШИРОКОМ сечении (зал/станция, 4.4-6.7 м) у края
        # живут штатные пристеночные массы — замер new_data f11215: сборка
        # пути у правого края (n до 6.6 тыс., верх 0.73-0.78) в коридоре
        # 4.6 м; ветка без ограничения ширины освобождала её.
        solid = (base <= FLOOR_BASE and col_top >= DUST_EXC_LO_TOP
                 and n_pts >= DUST_EXC_N_TALL and corr_w <= DUST_EXC_WIDE)
        exempt = depth > 0.0 and ((n_pts >= DUST_EXC_N and (deep or tall))
                                  or solid)
        if not exempt:
            return 'dust'
    if floor_visible and base > BASE_MAX:
        # «Не стоит на полотне» — отмазка только для того, что ВЫШЕ габарита
        # целиком (оборудование над крышей поезда, GAUGE_H_HI). Подвес, чей
        # низ заходит в габарит по высоте — препятствие: поезд влетит в него
        # крышей. Замер: свисающий объект на cloud_with_fake_obj f329-345 —
        # низ ~2.0 м при верхе габарита 2.5 м, ~2000 точек.
        if base >= GAUGE_H_HI:
            return 'base'
        # ...и для низкой продольной линии у самого края габарита, не
        # стоящей на полотне (контактный рельс: низ 0.60-0.61, верх до
        # 0.77 — замер; у вторжений низ 0.10-0.28 или верх выше 1.0).
        if col_top < LOW_LINE_TOP and depth < DUST_EXC_DEEP:
            return 'base'
    # Фрагмент конструкции: над верхом колонны продолжается МАССИВНАЯ
    # объяснённая конструкция (свод, портал — от 13 точек в полосе, замер
    # FRAG_MIN_ABOVE) с разрывом не больше FRAG_GAP, И при этом коридор там
    # честно измерен
    # (обе СЫРЫЕ кромки за габаритом — фрагменты свода посреди зала,
    # doubleT_obstacle/roundT_doubleT) или кластер стоит у самой измеренной
    # кромки (фрагменты пристеночных конструкций, doubleT_platform d~50-60).
    # Двойной gate плюс высотная ветка, потому что: без массивности
    # (FRAG_MIN_ABOVE) тонкая обрезь верха самого объекта, объяснённая
    # блоком 2б, съедает его низ (щит cloud_with_fake_obj f581: 11-12 точек,
    # зазор 0.00); без честного коридора/кромки то же делает свод над НИЗКИМ
    # препятствием в низком туннеле (плита f789: свод объяснён в 0.1-0.5 м
    # над верхом 0.80 м, а кромка +1.48 внутри габарита — коридор нечестный,
    # до кромки плита не тянется). Высокая ветка (верх >= DUST_EXC_TOP)
    # безопасна: до потолка габарита дотягиваются конструкции (порталы,
    # несущие стены зала на кривой — roundT_doubleT f150/f170, пристеночные
    # колонны doubleT_platform d~55) и машина f676, у которой хватает других
    # находок; диагональ f624 защищена разрывом (свод над ней дальше 0.5 м).
    corridor_honest = (np.isfinite(raw_l) and raw_l <= -GAUGE_HALF
                       and np.isfinite(raw_r) and raw_r >= GAUGE_HALF)
    near_edge = ((np.isfinite(raw_r) and x0 >= raw_r - WALL_RIPPLE)
                 or (np.isfinite(raw_l) and x1 <= raw_l + WALL_RIPPLE))
    if len(he):
        near = np.abs(de - xc) < FRAG_LAT
        # Продолжение ищется над верхом ОСНОВНОЙ массы кластера, а не над
        # col_top, который 1-2 шумовые точки пола обваливают до подошвы
        # (замер роя f466: 2 точки из 22 оборвали колонну 1.57 -> 0.36, и
        # объяснённый блоком 2б контактный рельс съел кластер как
        # 'fragment'). Тот же принцип, что у base=p5: единичный шум не
        # переопределяет протяжённость тела. У щита f581 масса и есть низ
        # (p90 ≈ col_top) — поведение не меняется.
        frag_top = col_top
        h_lo = float(h_pts.min())
        nb = max(1, int(np.ceil((float(h_pts.max()) - h_lo) / COL_STEP)) + 1)
        hcnt, hed = np.histogram(h_pts, bins=nb,
                                 range=(h_lo, h_lo + nb * COL_STEP))
        frag_top = max(col_top, float(hed[int(np.argmax(hcnt)) + 1]))
        above = near & (he > frag_top)
        # Массивность продолжения: у честного коридора/кромки достаточно
        # FRAG_MIN_ABOVE; высокая ветка (ею пользуются и препятствия — машина
        # f676 держится на 16-18 точках свода над собой) требует больше.
        if corridor_honest or near_edge:
            min_above = FRAG_MIN_ABOVE
        elif col_top >= DUST_EXC_TOP:
            min_above = FRAG_MIN_ABOVE_TALL
        else:
            min_above = None
        if (min_above is not None and int(above.sum()) >= min_above
                and float(he[above].min()) - frag_top <= FRAG_GAP):
            return 'fragment'
    return None


def gauge_centers(wall, axis):
    """Ось отсчёта габарита по бинам, м (абсолютный lat).

    Ведомая ось коридора, КРОМЕ бинов, где она не подтверждена ничем: обе
    стены дальше габарита (стена не держит ось, отступ к ней измерен в другом
    месте) и при этом ось измерена рельсами. Там — прямая ось блока 1.
    Обоснование и замер — в докстринге модуля.
    """
    center = np.asarray(wall['axis'], dtype=float).copy()
    if axis.get('measured'):
        unanchored = ((np.abs(wall['left']) > GAUGE_HALF)
                      & (wall['right'] > GAUGE_HALF))
        straight = axis_at(axis, np.asarray(wall['fwd_mid'], dtype=float))
        center[unanchored] = straight[unanchored]
    return center


def resid_mask(fwd, lat, up, floor, wall):
    """Маска остатка блока 3 (cand в detect): полоса дальности/высоты минус
    объяснённое конструкциями.

    Выделена из detect, чтобы тот же остаток без дублирования логики
    получали темпоральный фон (TemporalBG) и накопление остатка
    (_ResidAggregator в run.py). Возвращает (mask, limit); mask=None, если
    живых бинов нет.
    """
    h = up - floor
    fm = np.asarray(wall['fwd_mid'], dtype=float)
    status = np.asarray(wall['status'], dtype=object)
    live = np.isfinite(wall['axis']) & (status != 'stop')
    if not live.any():
        return None, 0.0
    limit = float(fm[live].max()) + BIN / 2
    cand = (fwd >= 0) & (fwd < limit) & (h >= GAUGE_H_LO) & (h < GAUGE_H_HI)
    st = wall.get('structures')
    if st is not None:
        cand &= ~st['mask']   # объяснено конструкцией — не препятствие
    return cand, limit


def gauge_lateral(fwd, lat, wall, axis):
    """Вынос точек от оси габарита d = lat - center(fwd), как в detect."""
    fm = np.asarray(wall['fwd_mid'], dtype=float)
    status = np.asarray(wall['status'], dtype=object)
    live = np.isfinite(wall['axis']) & (status != 'stop')
    center = np.interp(fwd, fm[live], gauge_centers(wall, axis)[live])
    return lat - center


class TemporalBG:
    """Темпоральный фон ячеек остатка: p40 по ПРОШЛЫМ кадрам вместо текущего.

    Зачем — обоснование и замеры у констант BG_*: покадровый p40 фон
    самофонится на протяжённом объекте (он сам становится фоном), а статичный
    мир в прошлых кадрах — честный фон. Живёт рядом с трекером (run.py),
    требует arc из trajectory.npz и последовательный проход кадров.

    Устройство: кольцевой буфер последних BG_NBACK кадров; на кадр — массивы
    (r_med, cnt) занятых ячеек остатка (ячейка = бин BIN вдоль × OBST_DX
    поперёк, как в detect; ~100-300 ячеек/кадр). Фон окна с серединой mid —
    p40 (та же OBST_BG_Q) счётчиков ячеек буфера с |r_med - mid| <= BG_RING,
    из которых FG-маской выкинуты ячейки с мировым s (arc кадра + r_med) в
    интервалах находок последних BG_NBACK кадров (d ± BG_FG_PAD). Образцов
    меньше BG_MIN_SAMPLES — None, и detect откатывается на покадровый p40
    бит-в-бит.

    Кольцо по дальности от лидара инвариантно к геометрии пути — кривые его
    не ломают; FG-интервал через arc — приближение, на кривой s расходится с
    мировой хордой на сантиметры в пределах окна.

    Использование (вызывающий проход, см. run.analyze):
        tbg.begin_frame(i)                # до detect: чистка протухшего
        detect(..., tbg=tbg)              # фон окна — tbg.window_bg(mid)
        tbg.add_hits(i, hits)             # FG-интервалы находок кадра
        tbg.update(i, fwd_res, d_res)     # статистика остатка в буфер
    """

    def __init__(self, arc, nback=BG_NBACK):
        self.arc = arc            # метры пути по кадрам (trajectory.npz)
        self.nback = nback
        self._ring = []           # [(frame_idx, arc, r_med[], cnt[])]
        self._fg = []             # [(frame_idx, s0, s1)] интервалы находок
        self._last_arc = None     # arc последнего ЗАПИСАННОГО кадра
        self._pool = None         # ленивая склейка буфера: (s, r_med, cnt)

    def begin_frame(self, frame_idx):
        """Прогон кадра frame_idx: выкинуть протухшие кадры и FG-интервалы."""
        lo = frame_idx - self.nback
        if self._ring and self._ring[0][0] <= lo:
            self._ring = [e for e in self._ring if e[0] > lo]
            self._pool = None
        if self._fg and self._fg[0][0] <= lo:
            self._fg = [e for e in self._fg if e[0] > lo]

    def add_hits(self, frame_idx, hits):
        """FG-интервалы находок кадра: их мировые s не должны учиться фоном."""
        if frame_idx >= len(self.arc):
            return
        a = float(self.arc[frame_idx])
        for h in hits:
            self._fg.append((frame_idx, a + h['d'] - BG_FG_PAD,
                             a + h['d'] + BG_FG_PAD))

    def update(self, frame_idx, fwd, d):
        """Поячеечная статистика остатка кадра — в буфер (если сместились).

        fwd — дальности точек остатка, d — их вынос от оси габарита (тот же,
        что в detect). Запись только при смещении по arc > BG_MIN_MOVE
        (защита от стоянки у объекта).
        """
        if frame_idx >= len(self.arc):
            return
        a = float(self.arc[frame_idx])
        if self._last_arc is not None and abs(a - self._last_arc) <= BG_MIN_MOVE:
            return
        band = np.abs(d) < GAUGE_HALF + SEARCH_EXTRA
        f = fwd[band]
        dd = d[band]
        if not len(f):
            return
        self._last_arc = a
        fb = np.floor(f / BIN).astype(np.int64)
        cl = np.floor(dd / OBST_DX).astype(np.int64)
        key = fb * 4096 + (cl + 2048)   # cl в полосе поиска: |cl| <= 10
        order = np.argsort(key, kind='stable')
        ks, fs = key[order], f[order]
        uk, first, cnt = np.unique(ks, return_index=True, return_counts=True)
        r_med = np.array([float(np.median(fs[p:p + n]))
                          for p, n in zip(first, cnt)])
        self._ring.append((frame_idx, a, r_med, cnt.astype(float)))
        if len(self._ring) > self.nback:
            self._ring.pop(0)
        self._pool = None

    def _build_pool(self):
        parts = [(e[1] + e[2], e[2], e[3]) for e in self._ring]
        if not parts:
            return None
        return (np.concatenate([p[0] for p in parts]),
                np.concatenate([p[1] for p in parts]),
                np.concatenate([p[2] for p in parts]))

    def window_bg(self, mid):
        """Фон окна с серединой mid, м: p40 счётчиков ячеек буфера в кольце
        |r_med - mid| <= BG_RING за вычетом FG-интервалов находок; None —
        образцов мало, откат на покадровый фон."""
        if self._pool is None:
            self._pool = self._build_pool()
        if self._pool is None:
            return None
        s, r, c = self._pool
        m = np.abs(r - mid) <= BG_RING
        if not m.any():
            return None
        s_m, c_m = s[m], c[m]
        if self._fg:
            keep = np.ones(len(s_m), dtype=bool)
            for _, s0, s1 in self._fg:
                keep &= (s_m < s0) | (s_m > s1)
            c_m = c_m[keep]
        if len(c_m) < BG_MIN_SAMPLES:
            return None
        return float(np.percentile(c_m, OBST_BG_Q))


def _accum_hits(acc, fm, status, live, center_bins, half_l, half_r,
                meas_l, meas_r, reach, limit, axis):
    """Находки из накопленного за ACC_K кадров остатка (см. константы ACC_*).

    acc — dict(f, l, h, src, cidx, frame) из _ResidAggregator.for_frame:
    точки остатка кадров [i-K+1, i] в системе кадра i (f/l — fwd и абсолютный
    lat, h — высота над полом СВОЕГО кадра, src — номер кадра-источника,
    cidx — индекс точки в массивах её кадра, frame — текущий кадр i).

    Механика — та же, что в покадровом цикле detect (окна OBST_WIN x OBST_STEP,
    ячейки OBST_DX, избыток над p40-фоном окна, вертикальный разрез
    _vsplit_ranges), но с накопленными порогами (ACC_CELL_MIN/ACC_MIN_PTS)
    и тремя антифантомными гейтами: кластер живёт >= ACC_MIN_FRAMES кадров,
    имеет >= ACC_MIN_CUR точек текущего кадра, а ПОКАДРОВЫЙ разброс по fwd
    (p95-p5) <= DEPTH_MAX — продольная полоса (база стены, 4695 точек через
    весь кадр) и пыль его не проходят (замеры — у ACC_*). Дальше — стеновые
    правила (полоса WALL_RIPPLE у измеренной кромки за габаритом: кластер
    целиком в полосе, либо >= 2/3 массы в полосе при непроходящем внутреннем
    остатке — аналог _band_line, без них база стены набирает сотни точек)
    и правила 'base' из _explain_cluster (линия не на полотне / над габаритом).
    """
    frame_idx = acc['frame']
    f = acc['f']
    center = np.interp(f, fm[live], center_bins[live])
    dd_all = acc['l'] - center
    hh_all = acc['h']
    ss_all = acc['src']

    # Нормативное сечение контактного рельса (константы CR_*, замеры там же):
    # кластер целиком в полосе сборки по оси пути + непрерывность по
    # соседним бинам (по накопленным точкам — сборка есть в каждом кадре).
    def cr_exempt(x0, x1, col_top, f_med, mid):
        bi = int(np.argmin(np.abs(fm - f_med)))
        off = float(center_bins[bi]) - float(axis_at(axis, f_med))
        if not _in_cr_band(x0 + off, x1 + off, col_top):
            return False
        return _cr_continuous(f, acc['l'], hh_all, mid - OBST_WIN / 2,
                              mid + OBST_WIN / 2, x0 + off, x1 + off,
                              axis, limit)

    hits = []
    for w0 in np.arange(0.0, limit - OBST_WIN + 1e-6, OBST_STEP):
        w1 = w0 + OBST_WIN
        mid = (w0 + w1) / 2
        i = int(np.argmin(np.abs(fm - mid)))
        if status[i] == 'stop':
            continue
        m = (f >= w0) & (f < w1) & (np.abs(dd_all) < GAUGE_HALF + SEARCH_EXTRA)
        if m.sum() < ACC_MIN_PTS:
            continue
        dd, hh, ff, ss = dd_all[m], hh_all[m], f[m], ss_all[m]
        edges = np.arange(dd.min(), dd.max() + OBST_DX, OBST_DX)
        if len(edges) < 3:
            # одна занятая ячейка: фонового сравнения нет (в отличие от
            # покадрового пути, SINGLE_CELL_MIN здесь не применялся —
            # накопленная одиночная ячейка без фона не валидирована)
            continue
        cnt, _ = np.histogram(dd, bins=edges)
        occ_idx = np.flatnonzero(cnt > 0)
        qual = np.zeros(len(cnt), dtype=bool)
        for c in occ_idx:
            rest = cnt[occ_idx[np.abs(occ_idx - c) > BG_EXCL]]
            bg = float(np.percentile(rest, OBST_BG_Q)) if len(rest) else 0.0
            qual[c] = cnt[c] >= max(ACC_CELL_MIN, OBST_EXCESS * bg)
        k = 0
        while k < len(cnt):
            if not qual[k]:
                k += 1
                continue
            j = k
            while j + 1 < len(cnt) and qual[j + 1]:
                j += 1
            sel = np.flatnonzero((dd >= edges[k]) & (dd < edges[j + 1]))
            k = j + 1
            if len(sel) < ACC_MIN_PTS:
                continue
            # Вертикальный разрез (как в detect): низкие точки-загрязнения в
            # тех же ячейках иначе обрывают колонку снизу (замер f343-346:
            # col_top 0.37 вместо 1.65).
            parts = [sel[(hh[sel] >= lo) & (hh[sel] < hi)]
                     for lo, hi in _vsplit_ranges(hh[sel])]
            parts = [p for p in parts if len(p) >= ACC_MIN_PTS]
            if not parts:
                parts = [sel]
            for p in parts:
                hit = _accum_gate(p, dd, hh, ff, ss, acc['cidx'][m],
                                  frame_idx, mid, fm, status, live,
                                  center_bins, half_l, half_r,
                                  meas_l, meas_r, reach, cr_exempt)
                if hit is not None:
                    hits.append(hit)
    return hits


def _accum_gate(p, dd, hh, ff, ss, cidx, frame_idx, mid, fm, status, live,
                center_bins, half_l, half_r, meas_l, meas_r, reach,
                cr_exempt):
    """Гейты кластера накопленного остатка -> находка или None."""
    fr = np.unique(ss[p])
    if len(fr) < ACC_MIN_FRAMES:
        return None
    n_cur = int((ss[p] == frame_idx).sum())
    if n_cur < ACC_MIN_CUR:
        return None
    col_top = _column_height(hh[p], 0.0)
    if col_top < OBST_MIN_H:
        return None
    # Покадровая компактность вдоль пути (анти-линия/пыль): в каждом кадре-
    # источнике точки кластера компактны по fwd (p95-p5), как лицевая грань
    # твёрдого объекта (та же физика, что у DEPTH_MAX в правиле 'dust').
    for fr_j in fr:
        fj = ff[p][ss[p] == fr_j]
        if len(fj) >= 8:
            sp = float(np.percentile(fj, 95) - np.percentile(fj, 5))
        elif len(fj) >= 4:
            sp = float(fj.max() - fj.min())
        else:
            continue
        if sp > DEPTH_MAX:
            return None
    x0, x1 = float(dd[p].min()), float(dd[p].max())
    xc = float(np.median(dd[p]))
    f_med = float(np.median(ff[p]))
    bi = int(np.argmin(np.abs(fm - f_med)))
    # Стеновые правила: кластер целиком в полосе WALL_RIPPLE у ИЗМЕРЕННОЙ
    # кромки — это стена; >= 2/3 массы в полосе — линия у стены, если
    # внутренний остаток сам по себе гейтов накопления не проходит
    # (аналог _band_line: без правила база стены проходит все гейты — замер
    # прототипа, f335-338, n≈350). Кромки — ДОВЕРЕННЫЕ (те же meas_*,
    # что в покадровом пути: за габаритом или стабильно внутри него по
    # PERSIST_BINS): торец платформы держится внутри габарита весь прогон,
    # и без доверенной кромки накопленная масса его подошвы проходила
    # все гейты (замер doubleT_platform f34: n=6551 у кромки -1.46).
    if status[bi] in ('ok', 'gauge'):
        for edge, sgn in ((meas_r[bi], 1), (meas_l[bi], -1)):
            if not np.isfinite(edge):
                continue
            inband = (dd[p] >= edge - WALL_RIPPLE
                      if sgn > 0 else dd[p] <= edge + WALL_RIPPLE)
            if inband.all():
                return None
            if int(inband.sum()) * 3 >= len(p) * 2:
                inner = p[~inband]
                if (len(inner) < ACC_MIN_PTS
                        or len(np.unique(ss[inner])) < ACC_MIN_FRAMES
                        or int((ss[inner] == frame_idx).sum()) < ACC_MIN_CUR):
                    return None
    # 'base': низкая линия не на полотне (контактный рельс) / над габаритом.
    base = float(np.percentile(hh[p], 5))
    depth = max(0.0, min(GAUGE_HALF - x0, x1 + GAUGE_HALF))
    if base >= GAUGE_H_HI:
        return None
    if base > BASE_MAX and col_top < LOW_LINE_TOP and depth < DUST_EXC_DEEP:
        return None
    # Нормативное сечение контактного рельса (CR_*): сборка в своей полосе по
    # оси пути, не выше нормы и непрерывная вдоль пути — не препятствие.
    if cr_exempt(x0, x1, col_top, f_med, mid):
        return None
    inside = (x1 > -half_l[bi]) and (x0 < half_r[bi])
    confirmed = status[bi] in ('ok', 'gauge') and fm[bi] <= reach
    cur = p[ss[p] == frame_idx]
    return dict(d=float(mid), lat=xc,
                lat_abs=xc + float(center_bins[bi]),
                x_min=x0, x_max=x1, width=x1 - x0,
                height=col_top, n_pts=len(p),
                in_gauge=bool(inside), confirmed=bool(confirmed),
                # point_idx — по точкам ТЕКУЩЕГО кадра (индексы прошлых кадров
                # в его массивах бессмысленны); не пуст: ACC_MIN_CUR >= 2
                point_idx=cidx[cur],
                n_frames=len(fr), n_cur=n_cur, accum=True)


def detect(fwd, lat, up, floor, wall, axis, tbg=None, acc=None):
    """Остаток необъяснённого -> находки в габарите.

    fwd/lat/up — кадр в рабочей системе (geom.to_frame), floor — пол кадра,
    wall — коридор из walls.trace (с 'structures' из structures.explain, если
    блок 2б был включён), axis — ось блока 1.

    tbg — необязательный темпоральный фон (TemporalBG): фон ячеек окна берётся
    из прошлых кадров вместо покадрового p40 (протяжённый объект не становится
    сам себе фоном); None или нехватка образцов в буфере — покадровый фон
    бит-в-бит.

    acc — необязательный накопленный остаток последних ACC_K кадров в системе
    текущего (dict из _ResidAggregator.for_frame в run.py): даёт дополнительные
    находки мелких дальних объектов (_accum_hits); None — чисто покадровый
    проход бит-в-бит.

    Возвращает (hits, summary). hits — список по окнам (после слияния
    перекрывающихся): d (дальность центра, м), lat (медиана относительно оси
    габарита), lat_abs (то же в системе лидара), width, height, n_pts,
    in_gauge (пересекается с коридором), confirmed (бин измерен, не 'hole'),
    point_idx — np-индексы точек находки в массивах fwd/lat/up кадра (для
    подсветки точек; при слиянии перекрывающихся находок индексы объединяются,
    поэтому их может быть больше n_pts оставленной находки).
    summary — счётчики кадра.
    """
    fwd = np.asarray(fwd, dtype=float)
    lat = np.asarray(lat, dtype=float)
    up = np.asarray(up, dtype=float)
    h = up - floor

    fm = np.asarray(wall['fwd_mid'], dtype=float)
    status = np.asarray(wall['status'], dtype=object)
    live = np.isfinite(wall['axis']) & (status != 'stop')
    summary = dict(resid_pts=0, windows=0, hits=0, hits_in_gauge=0,
                   hits_in_gauge_confirmed=0, detect_ms=0.0, acc_hits=0,
                   # 'explained' обязан быть даже на раннем выходе: сводка
                   # sweep читает его безусловно (падение на cloud_with_fake_obj)
                   explained=dict(base=0, fragment=0, column=0, dust=0, wall=0))
    cand, limit = resid_mask(fwd, lat, up, floor, wall)
    if cand is None:
        return [], summary
    # Непрерывная подтверждённая дальность коридора (walls.trace): бин
    # ok/gauge за первой дырой — знание за неизвестным участком, и находка в
    # нём не может считаться подтверждённой (замер роя: cloud_with_fake_obj
    # f1110 — находка на 122.5 м при reach 110 м). reach — дальняя кромка
    # последнего непрерывно подтверждённого бина, поэтому центр бина <= reach
    # ровно для бинов непрерывной цепи. Новых констант нет.
    reach = float(wall.get('reach', limit))

    center_bins = gauge_centers(wall, axis)
    # Коридор ведётся по GAUGE_HALF (кламп по стене), а находка помечается
    # по ПОЕЗДУ: дополнительный кламп на GAUGE_HALF_CHECK. Сужение только
    # здесь — детектор, объяснения (_trust_edge, _explain_*) и полоса поиска
    # остаются на GAUGE_HALF, поэтому число найденных объектов не меняется,
    # меняется лишь отметка «в габарите» (замер: находок всего 25/3/9 до и
    # после на cloud_with_fake_obj / doubleT_platform / roundT_doubleT, в
    # габарите 24->19 / 3->3 / 6->3).
    half_l = np.minimum(np.asarray(wall['half_left'], dtype=float),
                        GAUGE_HALF_CHECK)
    half_r = np.minimum(np.asarray(wall['half_right'], dtype=float),
                        GAUGE_HALF_CHECK)
    # Ось бина -> точки: интерполяция между центрами бинов, как в walls.trace
    center = np.interp(fwd, fm[live], center_bins[live])
    d = lat - center

    st = wall.get('structures')
    if st is not None:
        expl = st['mask'] & (fwd >= 0) & (fwd < limit)
    else:
        expl = np.zeros(len(fwd), dtype=bool)
    summary['resid_pts'] = int(cand.sum())
    # Слепые зоны колец пола: там низ объекта принципиально невидим, и
    # требовать «стоит на полотне» нельзя — ноги объекта съедает дыра.
    unc = np.asarray(wall.get('uncovered', np.zeros(len(fm), bool)), dtype=bool)

    t0 = time.perf_counter()
    # Работаем по индексам кандидатов/объяснённых один раз: полные маски по
    # облаку на каждое окно — это десятки миллионов операций на кадр.
    ci = np.flatnonzero(cand)
    cf, cd, cz, ch = fwd[ci], d[ci], up[ci], h[ci]
    ei = np.flatnonzero(expl)
    ef, ed, eh = fwd[ei], d[ei], h[ei]
    # Измеренные кромки стен по сторонам (nan там, где сторона не измерена —
    # кламп габарита или предсказание дыры: они ничего не объясняют).
    lead = np.asarray(wall.get('lead', ['none'] * len(fm)), dtype=object)
    raw_l = np.where((status == 'ok') | ((status == 'gauge') & (lead == 'left')),
                     wall['left'], np.nan)
    raw_r = np.where((status == 'ok') | ((status == 'gauge') & (lead == 'right')),
                     wall['right'], np.nan)

    def _trust_edge(edge):
        """Кромке можно объяснять 'wall'/'column', только если она за
        габаритом или СТАБИЛЬНО внутри него вдоль пути (платформа, контактный
        рельс — настоящий край коридора). Локальный провал кромки внутрь
        габарита — само препятствие, замеренное как стена (замеры — у
        PERSIST_BINS); доверять ему — самообъяснение."""
        a = np.abs(np.asarray(edge, dtype=float))
        ok = np.isfinite(a)
        trust = ok & (a >= GAUGE_HALF)
        for i in np.flatnonzero(ok & ~trust):
            lo, hi = max(0, i - PERSIST_BINS), min(len(a), i + PERSIST_BINS + 1)
            m = ok[lo:hi]
            # Медиане нужна выборка: не меньше PERSIST_BINS измеренных бинов
            # из 2*PERSIST_BINS+1 в окрестности
            if m.sum() >= PERSIST_BINS and float(np.median(a[lo:hi][m])) < GAUGE_HALF:
                trust[i] = True
        return trust

    meas_l = np.where(_trust_edge(raw_l), raw_l, np.nan)
    meas_r = np.where(_trust_edge(raw_r), raw_r, np.nan)

    def edge_at(arr, f):
        """Измеренная кромка стороны на дальности f (интерполяция по бинам)."""
        ok = np.isfinite(arr)
        if ok.sum() < 2:
            return np.nan
        return float(np.interp(f, fm[ok], arr[ok]))

    # Нормативное сечение контактного рельса (константы CR_* с замерами):
    # кластер целиком в полосе сборки по ОСИ ПУТИ (не по оси габарита — на
    # кривой они расходятся), не выше нормы над УГР и непрерывный вдоль пути
    # (та же полоса занята в соседних fwd-бинах) — штатное путевое железо, а
    # не препятствие. Проверяется по точкам остатка И объяснённым: сборка
    # частично объясняется блоком 2б, и её полоса занята в обоих множествах.
    fa_all = np.concatenate([cf, ef])
    la_all = np.concatenate([lat[ci], lat[ei]])
    ha_all = np.concatenate([ch, eh])

    def cr_exempt(x0, x1, col_top, f_med, w0, w1):
        off = float(center_bins[i]) - float(axis_at(axis, f_med))
        if not _in_cr_band(x0 + off, x1 + off, col_top):
            return False
        return _cr_continuous(fa_all, la_all, ha_all, w0, w1,
                              x0 + off, x1 + off, axis, limit)

    hits = []
    explained = dict(base=0, fragment=0, column=0, dust=0, wall=0)
    for w0 in np.arange(0.0, limit - OBST_WIN + 1e-6, OBST_STEP):
        w1 = w0 + OBST_WIN
        mid = (w0 + w1) / 2
        i = int(np.argmin(np.abs(fm - mid)))
        if status[i] == 'stop':
            continue
        summary['windows'] += 1
        # Бины 'hole' НЕ пропускаются: в doubleT_obstacle человек на 55 м
        # попадает ровно в такой бин. Габарит там держится клампом, а находка
        # помечается confirmed=False. Подтверждение также не дальше
        # непрерывного reach коридора (см. выше, у его загрузки).
        confirmed = status[i] in ('ok', 'gauge') and fm[i] <= reach
        m = (cf >= w0) & (cf < w1) & (np.abs(cd) < GAUGE_HALF + SEARCH_EXTRA)
        if m.sum() < OBST_MIN_PTS:
            continue
        dd, zz, h_pts_w, f_pts_w = cd[m], cz[m], ch[m], cf[m]
        pi_w = ci[m]     # индексы точек окна в массивах кадра (для point_idx)
        # Объяснённые конструкцией точки того же окна — для проверки
        # «фрагмент конструкции» (колонна продолжается в объяснённую массу).
        me = (ef >= w0) & (ef < w1)
        de, he = ed[me], eh[me]

        edges = np.arange(dd.min(), dd.max() + OBST_DX, OBST_DX)
        if len(edges) < 3:
            # Все точки окна в одной ячейке (размах поперёк < OBST_DX):
            # фонового сравнения нет, но плотная ячейка — это объект
            # (замер SINGLE_CELL_MIN: плита на рельсах 1317 точек, фоновые
            # ячейки остатка — единицы-десятки). Редкая — шум, пропускаем.
            if m.sum() < SINGLE_CELL_MIN:
                continue
            edges = np.array([dd.min(), dd.max() + OBST_DX])
        cnt, _ = np.histogram(dd, bins=edges)
        # Порог ячейки — избыток над фоном окна. Фон считается по занятым
        # ячейкам ВНЕ окрестности самой ячейки (BG_EXCL): иначе объект сам
        # завышает свой фон — на разреженном остатке после блока 2б в окне
        # может вообще не быть других ячеек (замер f90: все 3 занятые ячейки
        # окна — это человек, p40 по ним дал фон 19.8 и съел избыток).
        # Разделение фона по регионам (внутри/вне габарита) проверено роем и
        # НЕ применено: на f95 фоном объекта становятся его же соседние ячейки
        # (p40 по ним = сам объект, избытка нет), а разреженные ячейки вне
        # габарита в старой схеме как раз давали честный фон; занавес f346
        # отсекается уже порогом избытка (2.5x), а не регионом.
        # Абсолютный минимум ячейки — 4, а не кластерный OBST_MIN_PTS: он
        # применяется к кластеру ниже (n >= OBST_MIN_PTS), и поячеечное
        # дублирование резало объекты шириной в 1-2 ячейки по случайной фазе
        # сетки (замер роя: брус f499 — на f510 его 19 точек резались 8+11
        # при пороге 12 на ячейку и объект пропадал, на f511 те же точки
        # попали в одну ячейку и дали находку; регрессия 18 эталонов —
        # у agent-147 в отчёте роя).
        # Темпоральный фон окна (если буфер прогрет): тот же перцентиль
        # OBST_BG_Q и тот же порог избытка, но выборка — ячейки ПРОШЛЫХ
        # кадров, поэтому протяжённый объект не становится сам себе фоном
        # (замеры и обоснования — у BG_* и класса TemporalBG). Берётся
        # МИНИМУМ из темпорального и покадрового: каждый из них в своём
        # режиме отказа ЗАВЫШЕН (покадровый — самофоном заполняющего окно
        # объекта, плита f735-761: 332-652 против ~30; темпоральный — когда
        # текущее окно необычно пусто, а в истории кольца лежит плотный
        # контент: мелкий объект f347, 12-14 против 1.0 — терялся; и когда
        # FG-маска/подход вычищают из кольца именно ячейки низкого ближнего
        # слоя, doubleT_platform f30-37 / roundT_pressureGate f58-59: вспышка
        # 4-13 тыс. точек при низком темпоральном фоне). Заниженный фон лишь
        # добавляет кандидатов правилам-объяснениям, завышенный теряет объект
        # — поэтому рабочая оценка фона всегда нижняя. None — покадровый
        # бит-в-бит.
        bg_win = tbg.window_bg(mid) if tbg is not None else None
        occ_idx = np.flatnonzero(cnt > 0)
        qual = np.zeros(len(cnt), dtype=bool)
        for c in occ_idx:
            rest = cnt[occ_idx[np.abs(occ_idx - c) > BG_EXCL]]
            bg = float(np.percentile(rest, OBST_BG_Q)) if len(rest) else 0.0
            if bg_win is not None and bg_win < bg:
                bg = bg_win
            qual[c] = cnt[c] >= max(4, OBST_EXCESS * bg)

        k = 0
        while k < len(cnt):
            if not qual[k]:
                k += 1
                continue
            j = k
            while j + 1 < len(cnt) and qual[j + 1]:
                j += 1
            sel = (dd >= edges[k]) & (dd < edges[j + 1])
            n = int(sel.sum())
            if n < OBST_MIN_PTS:
                k = j + 1
                continue
            # Вертикальный разрез склеенного ряда: разрыв по высоте >= COL_GAP
            # (та же константа непрерывности, что в _column_height: твёрдое
            # тело непрерывно по высоте в её пределах) делит кластер на
            # отдельные тела, и каждое оценивается своим набором правил
            # (замер роя f465/f466: объект h 1.32-1.57 и 2 шумовые точки пола
            # в том же ряду обрывали колонну до 0.36-0.46 — ниже OBST_MIN_H —
            # или подставляли её под 'fragment' контактного рельса; зазор
            # 0.57+ м — это два тела). Куски мельче OBST_MIN_PTS — шум; если
            # ни один кусок порога не набрал (разреженная дальняя цель:
            # человек на 55-90 м — ~18 точек на 3 м высоты, замер у
            # COL_DENSE), кластер оценивается целиком.
            wi = np.flatnonzero(sel)
            # Линия у доверенной кромки с низким хвостом ловится ЦЕЛИКОМ, до
            # вертикального разреза: после разреза часть без подошвы стены
            # перестаёт набирать 2/3 массы в полосе кромки и ускользает в
            # глубокую ветку 'dust' (замер роя на конфиге с разрезом: те же
            # кадры f1-40 давали находки 0.7-1.1 тыс. точек вместо тишины).
            if _band_line(dd[sel], h_pts_w[sel], f_pts_w[sel], de, he,
                          not unc[i],
                          edge_at(meas_l, float(np.median(f_pts_w[sel]))),
                          edge_at(meas_r, float(np.median(f_pts_w[sel]))),
                          edge_at(raw_l, float(np.median(f_pts_w[sel]))),
                          edge_at(raw_r, float(np.median(f_pts_w[sel])))):
                explained['wall'] += 1
                k = j + 1
                continue
            parts = [wi[(h_pts_w[wi] >= lo) & (h_pts_w[wi] < hi)]
                     for lo, hi in _vsplit_ranges(h_pts_w[wi])]
            parts = [p for p in parts if len(p) >= OBST_MIN_PTS]
            if not parts:
                parts = [wi]
            for p in parts:
                n = len(p)
                # Высота — верх сплошной снизу части колонки, не max(Z):
                # над объектом в той же ячейке лежат точки свода.
                hh = _column_height(zz[p], floor)
                xc = float(np.median(dd[p]))
                x0, x1 = float(dd[p].min()), float(dd[p].max())
                f_med = float(np.median(f_pts_w[p]))
                why = _explain_cluster(hh, h_pts_w[p], f_pts_w[p],
                                       x0, x1, xc, de, he, dd[p],
                                       floor_visible=not unc[i],
                                       wall_l=edge_at(meas_l, f_med),
                                       wall_r=edge_at(meas_r, f_med),
                                       raw_l=edge_at(raw_l, f_med),
                                       raw_r=edge_at(raw_r, f_med))
                if why is not None:
                    explained[why] += 1
                elif hh >= OBST_MIN_H:
                    # Нормативное сечение контактного рельса — не препятствие
                    # (как ходовые рельсы уже исключены): полоса по оси пути,
                    # верх в норме и непрерывность вдоль пути (CR_*).
                    if cr_exempt(x0, x1, hh, f_med, w0, w1):
                        explained['base'] += 1
                        continue
                    # «В габарите» — если объект пересекается с коридором, а
                    # не если его центр внутри: человек у края опасен краем
                    # (README: для безопасности это правильная сторона ошибки).
                    inside = (x1 > -half_l[i]) and (x0 < half_r[i])
                    hits.append(dict(d=float(mid), lat=xc,
                                     lat_abs=xc + float(center_bins[i]),
                                     x_min=x0, x_max=x1, width=x1 - x0,
                                     height=hh, n_pts=n,
                                     in_gauge=bool(inside),
                                     confirmed=bool(confirmed),
                                     point_idx=pi_w[p]))
            k = j + 1

    # Накопленный за ACC_K кадров остаток — дополнительные находки (мелкие
    # дальние объекты ниже покадрового OBST_MIN_PTS). Аддитивно: покадровые
    # находки не меняются, дубли сливает _merge_hits.
    n_acc = 0
    if acc is not None and len(acc.get('src', ())):
        acc_hits = _accum_hits(acc, fm, status, live, center_bins,
                               half_l, half_r, meas_l, meas_r, reach, limit,
                               axis)
        n_acc = len(acc_hits)
        hits += acc_hits
    hits = _merge_hits(hits)
    summary['acc_hits'] = n_acc
    summary['detect_ms'] = (time.perf_counter() - t0) * 1000.0
    summary['explained'] = explained
    summary['hits'] = len(hits)
    summary['hits_in_gauge'] = sum(h['in_gauge'] for h in hits)
    summary['hits_in_gauge_confirmed'] = sum(
        h['in_gauge'] and h['confirmed'] for h in hits)
    return hits, summary


def _merge_hits(hits, dr=OBST_WIN, dx=MERGE_DX):
    """Схлопывает находки перекрывающихся окон: ближе dr по дальности и dx
    поперёк — один объект; остаётся находка с большим числом точек.
    point_idx снятого дубля объединяется с оставленным: перекрывающиеся окна
    режут объект по дальности, и для подсветки нужны точки обеих половин."""
    out = []
    for h in sorted(hits, key=lambda a: -a['n_pts']):
        dup = None
        for o in out:
            if abs(h['d'] - o['d']) < dr and abs(h['lat'] - o['lat']) < dx:
                dup = o
                break
        if dup is not None:
            dup['point_idx'] = np.union1d(dup['point_idx'], h['point_idx'])
            continue
        out.append(h)
    return sorted(out, key=lambda a: a['d'])


def _print_hits(hits, prefix=''):
    print(f'{prefix}{"дальн":>6s} {"lat":>6s} {"от оси":>7s} {"шир":>5s} '
          f'{"выс":>5s} {"точек":>6s} {"габарит":>8s} {"подтв":>6s}')
    for o in hits:
        print(f'{prefix}{o["d"]:6.1f} {o["lat_abs"]:+6.2f} {o["lat"]:+7.2f} '
              f'{o["width"]:5.2f} {o["height"]:5.2f} {o["n_pts"]:6d} '
              f'{"ДА" if o["in_gauge"] else "нет":>8s} '
              f'{"да" if o["confirmed"] else "НЕТ":>6s}')


def main():
    ap = argparse.ArgumentParser(
        description='Блок 3: препятствия в габарите из остатка после '
                    'объяснения штатным')
    ap.add_argument('bag_dir')
    ap.add_argument('--frame', type=int, default=0)
    ap.add_argument('--sweep', type=int, default=0,
                    help='пройти по бэгу с этим шагом кадров и дать сводку')
    a = ap.parse_args()

    from .run import analyze, _frames
    frames = _frames(a.bag_dir)

    if a.sweep:
        fr_hits, fr_ingauge, fr_unc = 0, 0, 0
        n_in, n_in_conf, tms = 0, 0, []
        expl_tot = dict(base=0, fragment=0, column=0, dust=0, wall=0)
        idx = range(0, len(frames), a.sweep)
        for i in idx:
            axis, wall = analyze(frames[i][0])
            fwd, lat, up = to_frame(frames[i][0])
            hits, summ = detect(fwd, lat, up, wall['floor'], wall, axis)
            tms.append(summ['detect_ms'])
            for key in expl_tot:
                expl_tot[key] += summ['explained'][key]
            ing = [h for h in hits if h['in_gauge']]
            fr_hits += bool(hits)
            n_in += len(ing)
            n_in_conf += sum(h['confirmed'] for h in ing)
            if ing:
                fr_ingauge += 1
                fr_unc += any(not h['confirmed'] for h in ing)
                for h in ing:
                    print(f'  [{i:4d}] ПРЕПЯТСТВИЕ d={h["d"]:5.1f} '
                          f'lat={h["lat_abs"]:+.2f} (от оси {h["lat"]:+.2f}) '
                          f'ш={h["width"]:.2f} в={h["height"]:.2f} '
                          f'n={h["n_pts"]}'
                          + ('' if h['confirmed'] else '  [hole, не подтв.]'))
        n = len(list(idx))
        print(f'{a.bag_dir}: {n} кадров')
        print(f'  кадров с находками        : {fr_hits}')
        print(f'  кадров с находкой в габарите: {fr_ingauge} '
              f'(из них с неподтверждённой: {fr_unc})')
        print(f'  находок в габарите        : {n_in}, подтверждённых: {n_in_conf}')
        print(f'  объяснено штатным         : полотно={expl_tot["base"]} '
              f'фрагмент={expl_tot["fragment"]} колонна={expl_tot["column"]} '
              f'пыль={expl_tot["dust"]} стена={expl_tot["wall"]}')
        print(f'  время detect, мс          : med {np.median(tms):.1f}  '
              f'max {np.max(tms):.1f}')
        return

    pts = frames[a.frame][0]
    axis, wall = analyze(pts)
    fwd, lat, up = to_frame(pts)
    hits, summ = detect(fwd, lat, up, wall['floor'], wall, axis)
    print(f'{a.bag_dir} кадр {a.frame}: остаток после конструкций '
          f'{summ["resid_pts"]} точек, находок {len(hits)}')
    _print_hits(hits, prefix='  ')


if __name__ == '__main__':
    main()
