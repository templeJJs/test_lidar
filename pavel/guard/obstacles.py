#   размах <= 2.63, коридор 3.6) и машина (f676: верх 2.46+, n от 577, заход
#   от 0.7, коридор до 4.0). Стена зала на кривой (roundT_doubleT f110:
#   коридор 4.4-6.7 м), пристеночные конструкции платформ (n <= 130) и
#   лестница у края (doubleT_platform f300: заход 0.36, размах 3.96) под
