# --- оценка квантиля кромки ------------------------------------------------
HD_MIN_N = 8             # гибрид Harrell-Davis / percentile. Замер роя на 206
                        # реальных слоях: HD при том же привязанном ранге
                        # q=clip(100*Q_RANK/n,10,30) снижает шум кромки на
                        # 10-17% и дрейф оценки от n в 2.5 раза, НО при n=4
                        # один выброс сдвигает HD на -0.57 м (percentile лишь
                        # -0.23): носитель весов HD покрывает ВСЮ выборку, и
                        # на крошечном n крайние точки получают заметный вес.
                        # Поэтому n < HD_MIN_N — прежний percentile.

_HD_W = {}               # кэш весов Harrell-Davis: (n, q) -> вектор длины n


def _hd_weights(n, q):
    """Веса Harrell-Davis квантиля q по n точкам.

    w_i = Beta_cdf(i/n; q(n+1), (1-q)(n+1)) - Beta_cdf((i-1)/n; ...),
    оценка — взвешенная сумма порядковых статистик. В отличие от линейной
    интерполяции percentile между двумя соседними точками, HD усредняет всю
    выборку с колоколообразными весами вокруг квантиля — отсюда меньший шум.
    """
    key = (n, round(q, 6))
    w = _HD_W.get(key)
    if w is None:
        from scipy.special import betainc
        w = np.diff(betainc(q * (n + 1), (1.0 - q) * (n + 1),
                            np.arange(n + 1) / n))
        _HD_W[key] = w
    return w


def _qval(s, q):
    """Квантиль q выборки s: HD при n >= HD_MIN_N, иначе percentile.

    HD зажат в соседние порядковые статистики ранга (s[j-1], s[j+1]): он
    сглаживает оценку ВНУТРИ локального шага точек, но не может перепрыгнуть
    провал плотности или съехать вверх по её склону. Замер (3806 реальных
    вызовов _edge из trace, 6 кадров doubleT_platform и roundT_doubleT):
    медиана |HD - percentile| всего 0.0002-0.012 м, но хвост p99 до 0.8 м —
    это двумодальные слои (лоток + стена в слое 0.6) и склоны плотности.
    Такой сдвиг на 0.10 м (roundT_doubleT f190, бин 32.5, слой 0.6, n=120)
    каскадом через предсказание цепочки давал ложное срабатывание
    физического триггера и обрыв reach 115 -> 90. Зажим убирает хвост,
    сохраняя сглаживание на одномодальных слоях.
    """
    n = len(s)
    if n < HD_MIN_N:
        return float(np.percentile(s, 100.0 * q))
    ss = np.sort(s)
    hd = float(ss @ _hd_weights(n, q))
    j = int(np.clip(round(q * (n - 1)), 0, n - 1))
    return float(min(max(hd, ss[max(j - 1, 0)]), ss[min(j + 1, n - 1)]))


