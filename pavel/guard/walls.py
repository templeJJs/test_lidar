GATE = 0.50              # полуокно поиска вокруг предсказания, м
FIT_WIN = 5              # по скольким последним принятым бинам предсказание
SLOPE_LIM = 0.06         # предел наклона стены, м/м (0.3 м на бин)
MISS_LIMIT = 6           # столько подряд неподтверждённых бинов коридор
