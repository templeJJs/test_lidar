"""Блок 2. Ведение стен и коридора вдоль прямого пути.

Смысл блока в постановке задачи: когда впереди "начинает появляться что-то",
это сначала надо попытаться объяснить СТЕНОЙ. Что объяснилось стеной —
препятствием не является, и по этой же стене коридор продолжается дальше.

Три замера по doubleT_platform f100 (относительно оси пути из блока 1)
задали конструкцию:

1. ГРАНИЦА — ВНУТРЕННЯЯ КРОМКА, А НЕ МЕДИАНА. Слева кромка держится
   1.46-1.54 м на бинах до 50 м (doubleT_platform f100), а медиана модуля
   выноса скачет 2.96 -> 6.71 м: за стеной открывается второй путь.
   Медиана дала бы "свободно до 6 м" там, где на 1.5 м уже
   конструкция. Поэтому берётся нижний перцентиль модуля выноса.

2. СТЕНА ВЕДЁТСЯ ПО СЛОЯМ ВЫСОТЫ. Тоннель круглый: вынос кромки зависит от
   высоты. Один перцентиль на всю полосу смешивает дугу стены и гуляет между
   соседними бинами. Границей габарита становится ХУДШИЙ (ближайший к оси)
   слой в пределах высоты поезда — поезд упрётся именно туда.

3. НЕПРЕРЫВНОСТЬ ВМЕСТО САМОГО СИЛЬНОГО ПИКА. Слева на 50-90 м самый
   плотный отклик приходит с 5.0-5.4 м (соседний объём), а своя стена там
   даёт единицы точек. Брать сильнейший пик — значит увести границу на 5 м
   наружу. Поэтому в каждом бине стена ищется в окне вокруг ПРЕДСКАЗАНИЯ по
   уже принятым бинам, а не по всему профилю.

Отдельно и важно: пустой бин — это "не наблюдается", а НЕ "свободно".
Лучи лидара расходятся веером, и на дальности между кольцами есть дыры;
за дырой точки возвращаются. Поэтому коридор в дыре ведётся предсказанием,
но дальность подтверждения (reach) на ней не растёт.
"""

