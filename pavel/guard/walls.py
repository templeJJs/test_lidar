# --- покрытие кольцами (слепые зоны пола) ----------------------------------
RING_EL_WIN = (-26.0, 16.0)  # окно вертикальных углов колец, град (Pandar128:
                             # FOV -25..+15, запас по краям)
RING_EL_STEP = 0.02      # шаг гистограммы углов, град: минимальный зазор
                         # колец ~0.1 град, шаг в 5 раз тоньше
RING_EL_DIST = 4         # мин. расстояние между пиками, шагов гистограммы
                         # (0.08 град < 0.1 град мин. зазора колец)
RING_MARGIN = 1.0        # допуск положения кольца пола при пометке бина
                         # непокрытым, м (в пользу "покрыт": ложный uncovered
                         # хуже пропущенной дыры). Замеры: пики колец
                         # стабильны между кадрами до 0.005 град (6 кадров
                         # doubleT_platform, по 128 колец), квантование сетки
                         # полшага = 0.01 град даёт dr = H*dtheta/sin^2(theta)
                         # = 0.45-0.9 м на theta 1.5-2 град; пол стабилен
                         # std 0.008-0.031 м (40 кадров doubleT_platform и
                         # roundT_pressureGate_roundT) и даёт dr = r*dH/H =
                         # ~0.9 м на 55 м. На дальних бинах абсолютный сдвиг
                         # кольца доходит до 2-3 м, но там зазоры колец
                         # 7.5-11 м — шире бина 5 м с двумя допусками,
                         # поэтому пометка устойчива.


def _ring_floor_ranges(fwd, lat, up, floor, max_range=MAX_RANGE):
    """Дальности, где кольца лидара пересекают пол, м (по возрастанию).

    Кольца — ЭМПИРИЧЕСКИЕ, из текущего кадра: гистограмма вертикального угла
    всех точек (стены видит каждое кольцо, поэтому пики есть и там, где пола
    нет), пики — углы колец. Тангаж лидара входит в оценку автоматически —
    подгонять его к заводской таблице не нужно (замер роя: после фита одного
    параметра таблица совпадает с эмпирикой с медианной ошибкой 0.0133 град,
    тангаж стабильно +0.44 град на 6 кадрах двух бэгов).

    Кольцо с углом theta < 0 бьёт в пол на r = H/tan(-theta), H — высота
    лидара над полом. Ширина слепой зоны между соседними кольцами
    dr = H*dtheta/sin^2(theta): замер роя даёт 2.0 м на 40 м, 5.3 м на 65 м,
    6.2 м на 70 м — наблюдаемая дыра doubleT_platform f100 на 62-72 м этой
    формулой воспроизводится.

    None, если колец различить не удалось (точек мало) — тогда покрытие не
    оценивается, и все дыры остаются просто 'hole'.
    """
    r = np.hypot(fwd, lat)
    m = r > 1.0
    if m.sum() < 10000:
        return None
    el = np.degrees(np.arctan2(up[m], r[m]))
    grid = np.arange(RING_EL_WIN[0], RING_EL_WIN[1], RING_EL_STEP)
    hist, _ = np.histogram(el, bins=grid)
    sm = np.convolve(hist, np.ones(3) / 3, mode='same')
    from scipy.signal import find_peaks
    peaks, _ = find_peaks(sm, distance=RING_EL_DIST,
                          prominence=max(2.0, 0.002 * sm.max()))
    th = np.radians((grid[:-1] + RING_EL_STEP / 2)[peaks])
    h_lidar = -floor              # пол в системе лидара лежит ниже нуля
    down = th[th < 0]
    rf = h_lidar / np.tan(-down)  # где кольцо пересекает пол
    rf = np.sort(rf[(rf > 0) & (rf <= max_range + RING_MARGIN)])
    return rf if len(rf) >= 3 else None


def _uncovered_mask(rf, edges):
    """Маска бинов, куда принципиально не попадает ни одно кольцо пола.

    Бин [lo, hi] покрыт, если в [lo - RING_MARGIN, hi + RING_MARGIN] есть
    хотя бы одна дальность кольца пола. Допуск RING_MARGIN — в пользу
    "покрыт": ошибочно назвать непокрытым бин, куда кольцо всё же бьёт,
    хуже, чем пропустить дыру (дыра и так ведётся предсказанием).
    """
    if rf is None or not len(rf):
        return np.zeros(len(edges), dtype=bool)
    idx = np.searchsorted(rf, edges - RING_MARGIN)
    has = idx < len(rf)
    covered = np.zeros(len(edges), dtype=bool)
    covered[has] = rf[idx[has]] <= edges[has] + BIN + RING_MARGIN
    return ~covered


