SEED_RANGE = 25.0        # ближняя зона для первой оценки: там точек десятки
                         # тысяч, стена видна надёжно
GATE = 0.50              # полуокно поиска вокруг предсказания, м
FIT_WIN = 5              # по скольким последним принятым бинам предсказание
SLOPE_LIM = 0.06         # предел наклона стены, м/м (0.3 м на бин)
MISS_LIMIT = 6           # столько подряд неподтверждённых бинов коридор
                         # переживает, дальше ведение останавливается


def _edge(d_layer, lo, hi, side):
    """Внутренняя кромка стены в окне [lo, hi] с одной стороны оси.

    side = -1 слева (вынос отрицательный), +1 справа.
    """
    if side < 0:
        sel = -d_layer[(d_layer <= -abs(lo)) & (d_layer >= -abs(hi))]
    else:
        sel = d_layer[(d_layer >= abs(lo)) & (d_layer <= abs(hi))]
    if len(sel) < MIN_PTS:
        return np.nan
    return edge_val(sel) * side


def edge_q(n, outer=False):
    """Перцентиль кромки для слоя из `n` точек (см. `Q_RANK`).

    Держит кромку на одной и той же ТОЧКЕ распределения, а не на одной и той
    же доле: при большом `n` это прежний `WALL_Q`, при малом — глубже внутрь
    распределения, чтобы оценка не садилась на пару крайних отражений.

    `outer=False` — внутренний край стены (ближний к пути). Это нужно
    ГАБАРИТУ: поезд упрётся в самое узкое, и край, обращённый к пути, и есть
    граница коридора.

    `outer=True` — внешний край (дальний от пути), отсчёт с того же конца, но
    зеркально: p90 вместо p10. Это нужно ВЕДЕНИЮ ОСИ: внутренний край стены
    размывают кабели, кронштейны и ниши, висящие перед стеной, а внешний
    задан самой стеной — дальше неё луч не проходит.
    """
    q = float(np.clip(100.0 * Q_RANK / max(n, 1), WALL_Q, Q_MAX))
    return 100.0 - q if outer else q


def edge_val(s, outer=False):
    """Кромка по модулям выносов `s` (одна сторона, один слой), м.

    `outer=True` — внешний край, но не дальше `OUTER_SPAN` от внутреннего:
    за этой границей дальний конец разброса принадлежит уже не стене, а
    тому, что за ней открылось (см. `OUTER_SPAN`).
    """
    q = edge_q(len(s)) / 100.0
    inner = _qval(s, q)
    if not outer:
        return inner
    return float(min(_qval(s, 1.0 - q), inner + OUTER_SPAN))


def _predict(hist, fwd_mid, seed):
    """Где ждать стену в этом бине по уже принятым бинам."""
    if len(hist) < 2:
        return seed
    h = hist[-FIT_WIN:]
    f = np.array([p[0] for p in h])
    v = np.array([p[1] for p in h])
    base = float(np.median(v))
    if len(h) < 3:
        return base
    # Ограниченный наклон: стена может расходиться, но не прыгать.
    sl = np.polyfit(f, v, 1)[0]
    sl = float(np.clip(sl, -SLOPE_LIM, SLOPE_LIM))
    return base + sl * (fwd_mid - float(np.median(f)))


