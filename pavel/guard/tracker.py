"""Блок 3.5. Межкадровый трекинг препятствий: отсечение однокадровых
транзиентов без потери настоящих находок.

Зачем. Блок 3 (obstacles.py) покадров: однокадровый транзиент (пыль,
случайное сгущение остатка на дальности) неотличим от настоящего дальнего
объекта. Известный подтверждённый ложный: roundT_squareT_pressureGate_squareT
f280 — 95 м, 19 точек, ровно 1 кадр (замер _tmp_trk_meas3: на кадрах 250-310
это единственная находка в габарите, ни кадра рядом). Настоящий объект живёт
десятки кадров: человек A в doubleT_obstacle виден 201 кадр из 201
(замер _tmp_trk_meas1).

Как. Каждая находка переводится в мировые координаты полным SE(2) по позам
trajectory.npz (конвенция та же, что в accum._shift_along_path и
run._PointAggregator: p_world = R(theta) @ p_local + t, локальная система
лидара x=lat, y=-fwd; проверка знака поворота — _tmp_trk_meas2: на кривой
cloud_with_fake_obj верный знак собирает статичный вставленный объект в один
компактный мировой кластер, неверный размазывает). Связывание — ближайший
трек в пределах допуска; трек с числом кадров >= CONFIRM_FRAMES помечается
confirmed. Находки НЕ удаляются: однокадровая находка остаётся в выдаче
блока 3, трекер лишь добавляет ей уровень подтверждения (сторона ошибки:
лучше показать неподтверждённое, чем скрыть настоящее).

Допуск связывания — анизотропный, в системе ТЕКУЩЕГО кадра:

* поперёк пути: GATE_LAT0 + |f_t| * tan(GATE_THETA * пропущено_кадров) +
  WALK_STEP * пропущено_кадров, где f_t — предсказанная дальность трека.
  WALK_STEP из физики: пешеход <= 2 м/с при 10 Гц = 0.2 м/кадр (эталон:
  человек A ходит 0.1-0.15 м/кадр, замер _tmp_trk_meas1 med 0.074 м/кадр
  поперёк). GATE_LAT0 — ошибка переноса координат и шум центроида находки:
  одометрия даёт сантиметры на кадр (замер accum: за 4 кадра снос <= 0.04 м,
  поворот <= 0.06 deg; на 100 м дальности поворот 0.06 deg — это 0.10 м),
  шум медианы lat у человека на 55 м — сантиметры (плавный ход 0.07-0.15
  м/кадр без дрожания). Член с GATE_THETA — накопление шума курса одометрии
  за пропуски: боковая ошибка переноса дальнего трека растёт с дальностью и
  числом пропущенных кадров (замер у константы); без него гейт на 95 м
  пробивался уже с gap=2.
* вдоль пути: GATE_FWD0 + WALK_STEP * пропущено_кадров + travel, где
  GATE_FWD0 = OBST_WIN + GATE_LAT0, а travel = ||pose(f) - pose(last)|| —
  ход поезда за пропуски. Поле d находки — ЦЕНТР окна поиска (окно OBST_WIN
  = 5 м, шаг OBST_STEP = 2.5 м), а не центроид кластера: истинное положение
  объекта в пределах полуокна, поэтому у стоящего объекта сообщённый центр
  между кадрами может прыгнуть на целое окно (замер: у человека на границе
  окон f120->f130 doubleT_obstacle d: 57.5 -> 52.5 м, поперёк тот же 0.1 м —
  с базой OBST_WIN/2 трек рвался). Член travel — сползание окна протяжённой
  цели: детектор сообщает ближайшее видимое пятно, и пока поезд проезжает
  мимо, якорь трека в мире отстаёт ровно на ход поезда (замер плиты
  f737->f746: 14.4 м за 9 кадров = ходу поезда; без travel dn=1.49 FAIL при
  живом треке). Поперечный гейт travel не получает — он несёт всю селекцию
  (замер: lat-расхождения цепочек <= 0.33 м при гэпах до 9 кадров).

Подтверждение CONFIRM_FRAMES = 2: транзиент живёт 1 кадр (замер f280 выше;
человек A — каждый кадр), поэтому второй кадр уже разделяет классы. Платим
за это один кадр задержки подтверждения настоящего препятствия — приёмлемо:
находка первого кадра всё равно показывается, но как неподтверждённая.

Смерть трека — MAX_MISS обработанных кадров без находки. Объект может
выпадать на дыру между кольцами лидара (бин 'hole'/'uncovered' в walls) или
за край обработанной дальности. Замеренное распределение серий пропусков
реального объекта в габарите — у константы MAX_MISS.

Масс-эскалация (MASS_N / MASS_W / MASS_LAT): находка с n_pts >= MASS_N
подтверждает свой трек немедленно, если в пределах MASS_W кадров назад была
ДРУГАЯ массивная находка с |Δd| <= OBST_WIN и |Δlat| <= MASS_LAT в системе
кадра (для пары находок n >= MASS_N2 на ближнем окне d <= NEAR_D условие
по lat снято — см. константы). Разделитель — повторяемость, не масса:
шумовое сгущение 500+ точек
(это 17x измеренного фона ячейки ~30) не повторяется дважды на той же
позиции за 10 кадров, поэтому однокадровый транзиент правило не проходит
никогда (проверено на n=4800-6300, f257/f480/f532). Плато «чистый порог по
n» не существует: сток-неподтверждённые массивные находки n=300-11847,
стоящие на полотне, есть во всех бэгах (замер _tmp_w2_base) — поэтому
подтверждение даёт только пара находок, а не одиночная вспышка.

Анти-FP статичности: цепочки РАЗНЫХ опор контактного рельса склеиваются в
«трек» — d прибито к центру окна (12.5 м), а мировая позиция ползёт вместе
с поездом (замер _tmp_w2_fpmap_*: s растёт 1:1 с arc, опоры идут с шагом
3-6 м, гейт вдоль пути шире шага опор). У настоящего статичного объекта d
уменьшается на пройденный путь. Поэтому confirmed не выставляется, пока
(d_first − d) < OBST_WIN/2 при пройденном (arc − arc_first) > OBST_WIN;
трек при этом не умирает и не удаляется — только остаётся
неподтверждённым. Проверка на реальных: плита 30→10 м и 20→7.5 м, столбы
117→52 м — проходят; без поз (стоящий бэг) правило не активно. Исключение —
протяжённый объект на ближнем окне (MASS_RUN / NEAR_D, см. константы): у
него d прибито к ближнему центру окна, пока поезд едет вдоль, и проверка
d_first − d резала настоящую плиту (замер cloud_with_fake_obj f725-728:
проезд 6.5 м > OBST_WIN при d=5.0 неизменном, n=14 тыс. каждый кадр).

Без trajectory.npz мировой перенос невозможен — трекер работает в системе
датчика (эквивалентно стоящему поезду) и честно предупреждает поле
world_ok=False: на стоящем бэге (doubleT_obstacle, снос 0.013 м/кадр) это
корректно, на едущем трекинг деградирует до покадрового.
"""

import numpy as np

from .obstacles import OBST_STEP, OBST_WIN

# --- допуск связывания (вывод — в докстринге модуля) -------------------------
WALK_STEP = 0.2          # м/кадр: пешеход <= 2 м/с при 10 Гц
GATE_LAT0 = 0.3          # м поперёк: одометрия (см/кадр) + поворот на
                         # дальности (0.10 м на 100 м) + шум центроида (см)
GATE_FWD0 = OBST_WIN + GATE_LAT0      # м вдоль: d — центр окна 5 м с шагом
                         # 2.5 м; окно шире шага, поэтому у объекта на границе
                         # окон сообщённый центр может прыгнуть на OBST_WIN
                         # за кадр (замер: f120->f130 doubleT_obstacle,
                         # 57.5 -> 52.5 при неподвижном человеке — рвало трек)
GATE_THETA = np.radians(0.3)  # рад/кадр: p99 покадрового шума курса
                         # одометрии (замер _tmp_w2_theta_noise, все 1510 поз
                         # cloud_with_fake_obj: |Δθ| med 0.026 / p90 0.212 /
                         # p99 0.314 / max 0.734 °/кадр; кумулятивный p99
                         # растёт ~линейно, 0.28°/кадр). Боковая ошибка
                         # переноса на дальности d за gap кадров:
                         # d*tan(GATE_THETA*gap) — на 95 м и gap 3 это 1.4 м.

# --- подтверждение и смерть ---------------------------------------------------
CONFIRM_FRAMES = 2       # кадров с находкой для confirmed: транзиент живёт
                         # ровно 1 кадр (замер roundT_sqT f250-310), настоящий
                         # объект — каждый кадр; второй кадр разделяет классы
MAX_MISS = 5             # обработанных кадров без находки до смерти трека.
                         # Замеренное распределение серий пропусков реального
                         # объекта в габарите (реплей _tmp_w2_slab_replay,
                         # cloud_with_fake_obj f0-800): плита f719-761 даёт
                         # серии {2,4,6,6} при мостуемых гейтом dn≈0.03-0.3;
                         # смерть при miss > MAX_MISS, поэтому 5 переживает
                         # серию из 5 пустых кадров (gap 6). Серии из 8 пустых
                         # (gap 9) — смена сечения протяжённого объекта, а не
                         # пропуск видимости; их не мостуем (сторона ошибки:
                         # не протаскивать устаревшее). Человек A на стоящем
                         # поезде — 0 пропусков за 201 кадр (_tmp_trk_meas1).

# Масс-эскалация (обоснования — в докстринге модуля, замеры _tmp_w2_tier*,
# sweep всех 8 бэгов: новых красных зон 0, эффект — те же эпизоды
# подтверждаются на 1-10 кадров раньше).
MASS_N = 500           # n_pts находки масс-тира: плато решений 400-600
                       # (добавленные находки 55/51/45, эпизоды в чистых бэгах
                       # одинаковы); сверху ничего не режет — разделитель
                       # повторяемость, не масса
MASS_W = 10            # окно повторения, кадров: низкий объект (h≈0.75)
                       # виден ~12 кадров от 20 м до near-field клипа при
                       # 1.6 м/кадр; измеренный максимум мерцательного
                       # разрыва плиты — 9 кадров (f737→f746)
MASS_LAT = 0.4         # = GATE_LAT0 + 0.1 на квантование оси; замеренный
                       # разброс lat массивных находок плиты 0.24 м
MASS_N2 = 4000         # n_pts ОБЕИХ находок пары для матча без MASS_LAT:
                       # 130x фона ячейки (~30) — совпадение двух таких вспышек
                       # в одном окне дальности за MASS_W кадров бывает только
                       # у одного протяжённого объекта. На ближних окнах
                       # медиана сечения широкой цели гуляет сильнее MASS_LAT
                       # (замер плиты f720->f721: 0.78 м, f742->f744: 0.89 м,
                       # f1222->f1223: 0.70 м — все рвали эскалацию)
NEAR_D = 7.5           # правила MASS_N2/MASS_RUN — только ближние окна: там
                       # протяжённый низкий объект (h~0.75, виден только
                       # вблизи) едет вместе с кадром; плотные цепочки на
                       # дальних окнах существуют (замер new_data f2879-2890:
                       # d=12.5 прибито 12 кадров подряд) и остаются под
                       # _static_ok
MASS_RUN = 4           # подряд кадров с находкой n>=MASS_N -> _static_ok
                       # пропускает трек: опора (шаг 3-6 м) сидит в окне
                       # OBST_WIN=5 м <= 3 кадров при 1.6 м/кадр (замеренный
                       # максимум серии у цепочек опор — 2: f1087-1088,
                       # f1257-1258), протяжённый объект в габарите виден
                       # каждый кадр (плита f721-728: 8 подряд, n=13-15 тыс.)

# Двойные находки одной цели в ОДНОМ кадре. Окна блока 3 перекрываются
# (OBST_WIN 5 м с шагом OBST_STEP 2.5 м), и широкая цель может дать две
# находки, которые _merge_hits не слил (у него допуск MERGE_DX=0.6 поперёк).
# Замер (cloud_with_fake_obj f130): пара d=70.0/72.5 (= OBST_STEP вдоль),
# Δlat=0.75, обе n=52 — края одной цели в соседних окнах. Без дедупликации
# вторая находка порождала трек-паразит, который на следующих кадрах крал
# связывания у основного (объект распадался на 2 подтверждённых трека по
# 6-8 кадров вместо одного на 11). Допуск поперёк — ширина цели (у человека
# до 0.8 м, замеры obstacles.py) плюс запас. Дедупликация НЕ удаляет находку
# из выдачи блока 3 — только не даёт ей создать второй трек. Побочный случай
# (новый объект, впервые виденный вплотную к существующему треку, стартует
# кадром позже) принят: два объекта ближе 1 м поперёк и 2.5 м вдоль одновре-
# менно в габарите — вне замеренной реальности.
DUP_LAT = 1.0            # м поперёк
DUP_FWD = OBST_STEP      # м вдоль: перекрытие окон блока 3 ровно OBST_STEP


class ObstacleTracker:
    """Связывает находки блока 3 между кадрами в мировых координатах.

    Использование:
        trk = ObstacleTracker(poses)      # poses из accum.load_poses или None
        tracks = trk.update(frame_idx, hits)   # hits — из obstacles.detect
    update возвращает список ЖИВЫХ треков (словарей) после этого кадра;
    полный список (с умершими) — self.tracks.
    """

    def __init__(self, poses=None):
        self.poses = poses
        self.world_ok = poses is not None
        self.tracks = []          # все треки, живые и умершие
        self._next_id = 1
        self.frames_confirmed = 0  # кадров, где была находка подтверждённого
                                   # трека
        # Пройденный путь по позам (кумулятивная длина по xy) — для проверки
        # мировой статичности трека (анти-FP цепочек опор, см. докстринг).
        if poses is not None:
            xy = np.asarray(poses, dtype=float)[:, :2]
            seg = np.hypot(*np.diff(xy, axis=0).T)
            self._arc = np.concatenate(([0.0], np.cumsum(seg)))
        else:
            self._arc = None
        self._massive = []        # (frame, d, lat_abs, n_pts) массивных
                                  # находок за последние MASS_W кадров
                                  # (масс-эскалация)

    def _pose(self, i):
        if self.poses is None or i >= len(self.poses):
            return 0.0, 0.0, 0.0
        x, y, t = (float(v) for v in self.poses[i])
        return x, y, t

    def _travel(self, i_from, i_to):
        """Ход поезда между кадрами (хорда по позам), м; без поз — 0."""
        if self.poses is None:
            return 0.0
        i_from = min(i_from, len(self.poses) - 1)
        i_to = min(i_to, len(self.poses) - 1)
        dx, dy = (self.poses[i_to][:2] - self.poses[i_from][:2])
        return float(np.hypot(dx, dy))

    def _arc_at(self, i):
        return float(self._arc[min(i, len(self._arc) - 1)])

    def _static_ok(self, tr, frame_idx):
        """Анти-FP статичности (см. докстринг модуля): цепочка разных опор
        контактного рельса едет вместе с поездом (d прибито к центру окна),
        настоящий объект приближается на пройденный путь. Без поз правило
        не активно."""
        # Протяжённый объект на ближнем окне (см. MASS_RUN): d прибито к
        # ближнему центру окна, пока поезд едет вдоль него, поэтому проверка
        # d_first - d его режет (плита f725-728: 6.5 м проезда при d=5.0).
        if tr.get('mass_run', 0) >= MASS_RUN and tr['d'] <= NEAR_D:
            return True
        if self._arc is None:
            return True
        if self._arc_at(frame_idx) - tr['arc_first'] <= OBST_WIN:
            return True
        return (tr['d_first'] - tr['d']) >= OBST_WIN / 2

    def _bump_run(self, tr, h, frame_idx):
        """Серия подряд идущих кадров с массивной находкой в треке (MASS_RUN)."""
        if h.get('n_pts', 0) >= MASS_N:
            if tr.get('mass_run_frame') == frame_idx - 1:
                tr['mass_run'] = tr.get('mass_run', 0) + 1
            else:
                tr['mass_run'] = 1
            tr['mass_run_frame'] = frame_idx

    def _to_world(self, hit, i):
        """Находка кадра i -> мир: p = R(theta) (lat_abs, -d) + t."""
        x, y, t = self._pose(i)
        c, s = np.cos(t), np.sin(t)
        lx, ly = hit['lat_abs'], -hit['d']
        return np.array([c * lx - s * ly + x, s * lx + c * ly + y])

    def _to_frame(self, w, i):
        """Мир -> система кадра i: (fwd, lat)."""
        x, y, t = self._pose(i)
        c, s = np.cos(-t), np.sin(-t)
        gx, gy = w[0] - x, w[1] - y
        lx, ly = c * gx - s * gy, s * gx + c * gy
        return -ly, lx                     # fwd=-y, lat=x

    def update(self, frame_idx, hits):
        """Добавить находки кадра; вернуть живые треки.

        hits — находки obstacles.detect (словари с 'd', 'lat_abs'). Список не
        меняется; трекеру нужны только положение и флаги для сводки.
        """
        # Двойники одной цели из перекрывающихся окон блока 3 (см. DUP_LAT):
        # оставляем находку с большим числом точек. Это не фильтрация выдачи
        # блока 3 — только защита от трека-паразита.
        if len(hits) > 1:
            ded = []
            for h in sorted(hits, key=lambda a: -a.get('n_pts', 0)):
                if any(abs(h['d'] - k['d']) <= DUP_FWD
                       and abs(h['lat_abs'] - k['lat_abs']) <= DUP_LAT
                       for k in ded):
                    continue
                ded.append(h)
            hits = ded
        # Связывание жадное по нормированному расстоянию: находок и треков
        # в кадре единицы, венгерский алгоритм избыточен.
        cand = []   # (d_norm, трек, находка, мир)
        for tr in self.tracks:
            if not tr['alive']:
                continue
            gap = frame_idx - tr['last']
            f_t, l_t = self._to_frame(tr['world'], frame_idx)
            # Поперёк: шум курса одометрии, накопленный за пропуски, в метрах
            # на дальности трека (GATE_THETA) + пешеходный член.
            gl = (GATE_LAT0 + abs(f_t) * np.tan(GATE_THETA * gap)
                  + WALK_STEP * gap)
            # Вдоль: окно блока 3 + пешеходный член + сползание окна
            # протяжённой цели на ход поезда (travel).
            gf = (GATE_FWD0 + WALK_STEP * gap
                  + self._travel(tr['last'], frame_idx))
            for h in hits:
                dn = np.hypot((h['d'] - f_t) / gf, (h['lat_abs'] - l_t) / gl)
                if dn <= 1.0:
                    cand.append((dn, tr, h))
        cand.sort(key=lambda c: c[0])
        used_tr, used_h = set(), set()
        owner = {}   # id(находки) -> её трек (для масс-эскалации)
        for dn, tr, h in cand:
            if id(tr) in used_tr or id(h) in used_h:
                continue
            used_tr.add(id(tr)); used_h.add(id(h))
            tr['n'] += 1
            tr['last'] = frame_idx
            tr['miss'] = 0
            tr['world'] = self._to_world(h, frame_idx)
            tr['d'] = h['d']
            tr['lat_abs'] = h['lat_abs']
            self._bump_run(tr, h, frame_idx)
            tr['confirmed'] = (tr['n'] >= CONFIRM_FRAMES
                               and self._static_ok(tr, frame_idx))
            tr['hits'].append((frame_idx, h))
            owner[id(h)] = tr
        for h in hits:
            if id(h) in used_h:
                continue
            tr = dict(id=self._next_id, n=1, first=frame_idx, last=frame_idx,
                      miss=0, world=self._to_world(h, frame_idx), d=h['d'],
                      d_first=h['d'], arc_first=self._arc_at(frame_idx)
                      if self._arc is not None else 0.0,
                      lat_abs=h['lat_abs'], confirmed=False, alive=True,
                      hits=[(frame_idx, h)])
            self.tracks.append(tr)
            owner[id(h)] = tr
            self._next_id += 1
            self._bump_run(tr, h, frame_idx)
        # Масс-эскалация (см. докстринг модуля): повторная массивная находка
        # подтверждает свой трек немедленно; однокадровый транзиент правило
        # не проходит никогда. Гейтится той же проверкой статичности.
        for h in hits:
            if h.get('n_pts', 0) < MASS_N:
                continue
            n_h = h.get('n_pts', 0)
            # Пара гигантов (MASS_N2) на ближнем окне (NEAR_D) матчится без
            # MASS_LAT: медиана сечения широкой цели вблизи гуляет до ~0.9 м
            # (замеры у константы MASS_N2) — это всё та же масса.
            if any(0 < frame_idx - f0 <= MASS_W
                   and abs(h['d'] - d0) <= OBST_WIN
                   and (abs(h['lat_abs'] - l0) <= MASS_LAT
                        or (n_h >= MASS_N2 and n0 >= MASS_N2
                            and h['d'] <= NEAR_D))
                   for f0, d0, l0, n0 in self._massive):
                tr = owner.get(id(h))
                if tr is not None and not tr['confirmed'] \
                        and self._static_ok(tr, frame_idx):
                    tr['confirmed'] = True
        self._massive = [(f0, d0, l0, n0) for f0, d0, l0, n0 in self._massive
                         if frame_idx - f0 <= MASS_W]
        self._massive += [(frame_idx, h['d'], h['lat_abs'], h.get('n_pts', 0))
                          for h in hits if h.get('n_pts', 0) >= MASS_N]
        # Смерть по пропускам (в обработанных кадрах, не в кадрах бэга:
        # трекер видит только то, что ему скармливают).
        for tr in self.tracks:
            if not tr['alive'] or tr['last'] == frame_idx:
                continue
            tr['miss'] += 1
            if tr['miss'] > MAX_MISS:
                tr['alive'] = False
        if any(tr['alive'] and tr['confirmed'] for tr in self.tracks):
            self.frames_confirmed += 1
        return [tr for tr in self.tracks if tr['alive']]

    def summary(self):
        """Сводка для печати: счётчики и самый длинный трек."""
        conf = [t for t in self.tracks if t['confirmed']]
        longest = max(self.tracks, key=lambda t: t['n'], default=None)
        return dict(tracks=len(self.tracks), confirmed=len(conf),
                    frames_confirmed=self.frames_confirmed, longest=longest,
                    world_ok=self.world_ok)
