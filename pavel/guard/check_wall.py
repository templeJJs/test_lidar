"""Детекция стен как геометрии кадра — без всякого знания о пути.

Зачем отдельный блок. Блок 1б (`axis_wall.py`) ищет стену И ведёт по ней ось
в одном цикле, причём в координатах ОТ ОСИ: `d_bin = lat[m] - pred`, где
`pred` — предсказание той самой оси, которую мы строим. Окно поиска
центрируется по `pred`, а `pred` строится по кромке, найденной в окне. Эта
обратная связь и есть источник отказов, которые лечились порогами: уехавшая
ось уводит окно, в уехавшем окне стена не находится, ведение встаёт (замер
f240 в докстринге `scan_edges`).

Здесь стены ищутся В АБСОЛЮТНЫХ КООРДИНАТАХ кадра. Вход — только облако,
`axis` на входе нет вовсе, и это проверяемое свойство блока: его выход нельзя
испортить неверной осью, потому что он её не видит. Ведение строится ПОВЕРХ
(выбрать из списка ведущую и отнять отступ) и в этот файл не входит.

Три отличия от того, как стена ищется в блоке 1б.

1. СЛОИ ГОЛОСУЮТ, А НЕ ВЫБИРАЮТСЯ. `pick_layer` выбирает один слой высоты на
   кадр по гладкости кромки, и вся ось висит на нём — при попадании 67-95%
   (замер в его докстринге). Здесь кромки собираются в КАЖДОМ слое, линии
   фитятся в каждом слое, а потом линии из разных слоёв сливаются, если идут
   рядом. Стена — это то, что видно в нескольких слоях сразу; кабель,
   кронштейн и навес живут в одном. Свод отсеивается тем же признаком: он
   есть только наверху.

2. РЕЗАТЬ ПО РАЗРЫВУ, А НЕ ОТБРАКОВЫВАТЬ. В кадре несколько стен, и это не
   выбросы (замер f240: ближняя стена 2-32 м, за поворотом вторая с 48 м).
   Бывший `fit_line` блока 1б искал ветви перебором затравок и возвращал
   САМУЮ ДЛИННУЮ — для ведения одной осью этого хватало. Здесь нужны ВСЕ
   стены, поэтому профиль кромок сначала режется по разрывам, и каждый кусок
   фитится отдельно.

3. СТОРОНА — ОТ ЛИДАРА, А НЕ ОТ ОСИ. Пока оси нет, «слева/справа» может
   значить только «слева/справа от нуля лидара». На повороте это не то же
   самое, что сторона от пути, и именно поэтому окно, привязанное к нулю,
   в кривой умирает (замер 2 в докстринге `axis_wall`). Сторона здесь — лишь
   подсказка для сборки профиля, а не утверждение о пути.

Что выдаётся — список `Wall`: полином кромки по дальности, отрезок
дальностей, в скольких слоях подтверждена, невязка. Дальше по этому списку
можно спрашивать что угодно: какая ближе, какая обрывается раньше (наружная
стена поворота — та, в которую луч бьёт поперёк), какие две идут параллельно.
"""

import numpy as np

from . import walls as W
from . import axis_wall as AW
from .track import axis_at

# --- разбиение -------------------------------------------------------------
BIN = W.BIN               # шаг бина дальности, м — тот же, что у стен и оси
MAX_RANGE = 110.0         # цель задачи

# --- окно поиска кромки ----------------------------------------------------
MIN_OFF = W.MIN_OFF / 2   # 0.6 м. У W.MIN_OFF другой смысл: там «ближе к ОСИ
                          # пути стены не бывает», а здесь отсчёт идёт от НУЛЯ
                          # ЛИДАРА. На кривой путь уходит в дугу, и СВОЯ
                          # внутренняя стена подходит к нулю лидара ближе 1.2 —
                          # замер detect с порогом 1.2/0.9/0.6/0.3/0.0 на 5
                          # кадрах трёх бэгов: roundT_pressureGate f240 левая
                          # при 1.2 обрывается на -1.37 м, при 0.6 ведётся до
                          # -0.52 м; f100 правая — до +0.78 вместо +1.20.
                          # До нуля опускать нельзя: при 0.0 на f100 появляется
                          # псевдостена, пересекающая ноль (62-98 м, 5 слоёв) —
                          # это путь впереди на дуге. При 0.6 мусора в замере
                          # не было (прямые кадры doubleT_platform не меняются)
MAX_OFF = 12.0            # шире, чем MAX_OFF блока 2 (8 м): тот ограничивает
                          # ГАБАРИТ, где чужой объём надо отсечь, а здесь чужая
                          # стена — такая же стена, её надо НАЙТИ, а не срезать.
                          # Отделять своё от чужого — дело ведения, не детекции

# --- кромка в бине ---------------------------------------------------------
MIN_PTS = W.MIN_PTS       # точек на слой в бине, чтобы кромке верить

# --- разрезание профиля на стены ------------------------------------------
JUMP = 0.70               # разрыв кромки между соседними бинами, м: выше —
                          # это другая стена, а не та же. Порог взят из замера
                          # по истинной оси (1736 переходов, `JUMP_LIM` в
                          # axis_wall): своя стена med 0.10, p95 0.50-0.66,
                          # max 1.04; чужой объём med 3.50. Здесь он работает
                          # не фильтром, а НОЖОМ — то, что за разрывом, не
                          # выбрасывается, а становится следующей стеной
GAP_BINS = 2              # столько подряд пустых бинов отрезок переживает.
                          # Пустой бин — дыра между кольцами лидара, а не конец
                          # стены (см. `walls.trace`: за дырой точки
                          # возвращаются). Больше двух — разрыв признаётся

# --- что считать стеной ----------------------------------------------------
MIN_BINS = 5              # короче — это не стена, а объект: ниша, столб,
                          # торец. Причина числа — отбраковка в fit_seg: при
                          # 4 точках берётся deg=2, парабола по четырём точкам
                          # проходит почти точно, и резать нечего — любой
                          # рваный 4-бинный кусок становился «линией». При 5
                          # точках у параболы есть свобода для невязки.
                          # (Тот же урок был в LINE_MIN блока 1б; при
                          # рефакторинге axis_wall константа удалена вместе с
                          # fit_line, поэтому число обосновано здесь локально)
MIN_SPAN = 15.0           # и протяжённость не меньше трёх бинов, м. Два
                          # условия не дублируют друг друга: бины могут быть
                          # рваными, и 5 кромок на 40 м — это не то же самое,
                          # что 5 кромок подряд на 15 м
FIT_TOL = 0.55            # допуск невязки кромки от линии, м: p95 разброса
                          # своей стены между бинами (тот же замер, что дал
                          # JUMP выше) — то, что не лезет в собственный разброс
                          # стены, стеной и не является

# --- слияние слоёв ---------------------------------------------------------
MERGE_LAT = 0.60          # насколько линии из соседних слоёв могут расходиться
                          # по выносу, чтобы считаться ОДНОЙ стеной, м.
                          # Тоннель круглый, и стена реально гнётся по высоте:
                          # замер профиля f108 (правая стена, слои 0.6-3.1 м)
                          # на 12.5 м — 1.86/2.31/2.42/2.43/2.40/2.27, то есть
                          # шаг между СОСЕДНИМИ слоями 0.02-0.45 м; повторный
                          # замер по бинам 12.5/27.5/52.5 м обеих сторон дал
                          # max 0.45. Стоявшее здесь раньше «0.02-0.85»
                          # относилось к старой разбивке со слоем 0.0-0.5 м:
                          # шаг 1.48->2.33 между двумя нижними слоями — это
                          # балласт/лоток, а не тело стены. Порог 0.60 лежит
                          # выше наблюдённого максимума 0.45 с запасом 0.15.
                          # Сливаются только соседние по высоте, поэтому порог
                          # сравнивает шаг, а не полный размах дуги
MERGE_OVER = 10.0         # и перекрытие по дальности не меньше, м: две линии,
                          # идущие в разных местах трассы, — разные стены, даже
                          # если вынос совпал
MIN_LAYERS = 2            # в скольких слоях стена должна быть подтверждена.
                          # Один слой — это кабель, кронштейн, навес, край
                          # платформы: всё, что висит перед стеной, живёт в
                          # своей полосе высоты. Настоящая стена тянется по
                          # высоте, и в соседнем слое она тоже есть


class Wall:
    """Одна стена кадра.

    coef    — полином `lat(fwd)`, абсолютные координаты кадра (нуль лидара)
    d_lo/d_hi — отрезок дальности, на котором стена ПРОСЛЕЖЕНА, м
    side    — с какой стороны от нуля лидара (-1 слева, +1 справа)
    layers  — список слоёв высоты (низ слоя, м), где она подтверждена
    n_bins  — сколько кромок легло на линию
    rms     — невязка этих кромок от линии, м
    d/e     — сами кромки (дальность, вынос): для картинки и проверки
    """

    def __init__(self, coef, d, e, side, layers, rms):
        self.coef, self.d, self.e = coef, d, e
        self.side, self.layers, self.rms = side, layers, rms
        self.d_lo, self.d_hi = float(d.min()), float(d.max())
        self.n_bins = len(d)

    @property
    def span(self):
        return self.d_hi - self.d_lo

    def lat_at(self, fwd):
        """Вынос стены на дальности `fwd`, м. За отрезком — экстраполяция."""
        return np.polyval(self.coef, np.asarray(fwd, dtype=float))

    def __repr__(self):
        return (f'<Wall {"L" if self.side < 0 else "R"} '
                f'{self.d_lo:.0f}-{self.d_hi:.0f}м '
                f'{self.lat_at(self.d_lo):+.2f}->{self.lat_at(self.d_hi):+.2f} '
                f'слоёв={len(self.layers)} rms={self.rms:.2f}>')


def layer_edges(fwd, lat, up, floor, z, side, max_range=MAX_RANGE, _grid=None):
    """Кромка в каждом бине одного слоя высоты, независимо по бинам.

    Независимо — принципиально. Рекуррентный поиск (окно вокруг предыдущей
    кромки) имеет отказ, который не чинится порогами: одна испорченная кромка
    отравляет всё, что за ней, потому что следующее окно строится вокруг
    вранья. Здесь одна плохая кромка остаётся одной плохой кромкой, и её
    снимет либо разрез по разрыву, либо отбраковка при фите.

    Кромка берётся ВНЕШНЯЯ (`outer=True`): внутренний край стены размывают
    кабели, кронштейны и ниши, висящие перед ней, а внешний задан самой
    стеной — дальше неё луч не проходит. Габариту (блок 2) нужен внутренний,
    геометрии стены — внешний.

    _grid — решётка точек кадра (axis_wall._FrameGrid): выборка (бин, слой)
    берётся готовым слайсом вместо масок по всему облаку; множества точек те
    же, кромки не меняются.

    -> (d[], e[]) — центры бинов и вынос кромки, абсолютные координаты.
    """
    if _grid is not None:
        # Ячейка (бин, слой) решётки отсортирована по выносу: окно
        # [MIN_OFF, MAX_OFF] — два searchsorted ПО ЯЧЕЙКЕ (те же сравнения
        # границ, что у маски), дальше квантиль по отсортированному срезу.
        # Окно по всему пролёту слоя строить НЕЛЬЗЯ: пролёт отсортирован
        # только внутри каждой ячейки, глобально по выносу — нет.
        li = _grid.layer_index(z)
        lat_s, coff, nb = _grid.lat_s, _grid.coff_l, _grid.n_bins
        nb2 = len(np.arange(0.0, max_range, BIN))
        ds, es = [], []
        for b in range(nb2):
            c = li * nb + b
            c0, c1 = coff[c], coff[c + 1]
            if c1 - c0 < MIN_PTS:
                continue
            cell = lat_s[c0:c1]
            if side < 0:
                i0 = cell.searchsorted(-MAX_OFF, side='left')
                i1 = cell.searchsorted(-MIN_OFF, side='right')
                s = -(cell[i0:i1][::-1])   # возрастающая непрерывная копия:
                # шаг -1 дал бы BLAS-dot обратный порядок суммирования
            else:
                i0 = cell.searchsorted(MIN_OFF, side='left')
                i1 = cell.searchsorted(MAX_OFF, side='right')
                s = cell[i0:i1]
            if len(s) < MIN_PTS:
                continue
            ds.append(b * BIN + BIN / 2)
            es.append(AW._edge_val_outer_sorted(s) * side)
        return np.array(ds), np.array(es)
    h = up - floor
    k = (h >= z) & (h < z + W.H_STEP)
    f_l, l_l = fwd[k], lat[k]
    ds, es = [], []
    for lo in np.arange(0.0, max_range, BIN):
        m = (f_l >= lo) & (f_l < lo + BIN)
        if not m.any():
            continue
        s = l_l[m] * side
        s = s[(s >= MIN_OFF) & (s <= MAX_OFF)]
        if len(s) < MIN_PTS:
            continue
        ds.append(lo + BIN / 2)
        es.append(W.edge_val(s, outer=True) * side)
    return np.array(ds), np.array(es)


def cut(d, e):
    """Режет профиль кромок на куски по разрывам -> список индексов.

    Два признака разрыва, и оба физические:
      - ИЗМЕНЕНИЕ шага выноса между соседними бинами больше `JUMP` — своя
        стена гладкая даже на завороте (шаг растёт плавно: замер f123,
        шаги 0.64-0.85 м/бин при изменении шага <= 0.5), а чужая появляется
        скачком (med 3.5 м). Первой разностью резать нельзя: на дуге она
        законно превышает JUMP, и линия рассыпалась на куски короче
        MIN_BINS ровно там, где стена поворачивает (f123: стена есть до
        108 м, линия обрывалась на 78);
      - пропуск больше `GAP_BINS` бинов — за дырой между кольцами стена
        продолжается, а за длинным пропуском её уже нет.

    Кусок — это КАНДИДАТ в стены, а не стена: длину и гладкость проверяет
    `fit_seg`.
    """
    if len(d) == 0:
        return []
    segs, cur = [], [0]
    prev_step = None          # шаг выноса, нормированный на бин
    for i in range(1, len(d)):
        g = (d[i] - d[i - 1]) / BIN
        step = (e[i] - e[i - 1]) / g
        if g > GAP_BINS + 1:
            brk = True
        elif prev_step is None:
            # первого шага истории нет — доступна только сама величина шага
            brk = abs(step) > JUMP
        else:
            brk = abs(step - prev_step) > JUMP
        if brk:
            segs.append(cur)
            cur = []
            prev_step = None
        else:
            prev_step = step
        cur.append(i)
    segs.append(cur)
    return [np.array(s) for s in segs if len(s) >= MIN_BINS]


def fit_seg(d, e, tol=FIT_TOL):
    """Линия по куску профиля, с отбраковкой выбросов -> (coef, маска).

    Парабола, а не прямая: на дуге стена гнётся, и прямая на плече 60 м даёт
    невязку больше допуска сама по себе. Выше второй степени не берём —
    третья начинает объяснять выбросы вместо того, чтобы их отвергать.

    Два прохода: подогнали, выкинули то, что дальше `tol`, подогнали заново.
    Дальше состав почти не меняется.
    """
    k = np.ones(len(d), dtype=bool)
    coef = None
    for _ in range(2):
        if k.sum() < 3:
            return None, None
        deg = 2 if k.sum() >= 4 else 1
        coef = np.polyfit(d[k], e[k], deg)
        k = np.abs(e - np.polyval(coef, d)) <= tol
    if k.sum() < MIN_BINS or (d[k].max() - d[k].min()) < MIN_SPAN:
        return None, None
    return np.polyfit(d[k], e[k], 2 if k.sum() >= 4 else 1), k


def _merge(cands):
    """Сливает линии соседних слоёв, описывающие одну стену.

    Настоящая стена видна в нескольких слоях высоты подряд, и её линии там
    почти совпадают. Кабель, кронштейн, навес, край платформы живут в одной
    полосе высоты — у них слой ровно один, и `MIN_LAYERS` их снимает.

    Сравниваются линии на ОБЩЕМ участке дальности: две линии могут иметь
    близкий вынос в разных концах кадра и при этом описывать разные стены.
    """
    used = [False] * len(cands)
    out = []
    for i, a in enumerate(cands):
        if used[i]:
            continue
        used[i] = True
        group = [a]
        # Проходов несколько: группа растёт по ходу, и кандидат, ставший
        # соседом уже принятого слоя, при одном проходе остался бы пропущен —
        # цепочка слоёв собирается только тогда, когда её звенья видят друг
        # друга независимо от порядка в списке.
        grew = True
        while grew:
            grew = False
            for j in range(len(cands)):
                b = cands[j]
                if used[j] or b['side'] != a['side']:
                    continue
                # Сравнивать надо с БЛИЖАЙШИМ ПО ВЫСОТЕ членом группы, а не с её
                # первым кандидатом. Стена круглого тоннеля гнётся, и через три
                # слоя вынос уходит законно далеко: замер профиля правой стены
                # f108 (вынос кромки по слоям на 12.5 м) —
                #     0.6   1.1   1.6   2.1   2.6   3.1 м
                #    1.86  2.31  2.42  2.43  2.40  2.27
                # шаг между СОСЕДНИМИ слоями 0.01-0.45 м, а от нижнего слоя до
                # 2.1 уже 0.65 м. Сравнение с первым кандидатом рвало стену на
                # два куска ровно там, где дуга набирает размах: f108 давала
                # слои [0.6, 1.1, 1.6] и [2.1, 2.6, 3.1] вместо одной стены.
                nb = min(group, key=lambda g: abs(b['z'] - g['z']))
                if abs(b['z'] - nb['z']) > W.H_STEP * 1.5 + 1e-9:
                    continue
                lo = max(nb['d'].min(), b['d'].min())
                hi = min(nb['d'].max(), b['d'].max())
                if hi - lo < MERGE_OVER:
                    continue
                t = np.linspace(lo, hi, 5)
                if np.max(np.abs(np.polyval(nb['coef'], t)
                                 - np.polyval(b['coef'], t))) > MERGE_LAT:
                    continue
                used[j] = True
                group.append(b)
                grew = True
        d = np.concatenate([g['d'] for g in group])
        e = np.concatenate([g['e'] for g in group])
        o = np.argsort(d)
        d, e = d[o], e[o]
        coef = np.polyfit(d, e, 2 if len(d) >= 4 else 1)
        rms = float(np.sqrt(np.mean((e - np.polyval(coef, d)) ** 2)))
        out.append(Wall(coef, d, e, a['side'],
                        sorted({float(g['z']) for g in group}), rms))
    return out


def detect(fwd, lat, up, floor, max_range=MAX_RANGE, _grid=None):
    """Все стены кадра -> список `Wall`, отсортированный по протяжённости.

    Про ось не знает ничего: вход — только облако и уровень пола.

    _grid — необязательная решётка точек кадра (axis_wall._FrameGrid):
    кромки бинов берутся слайсами ячеек вместо масок по всему облаку.
    Вызывающий (axis_wall.frame_edges) передаёт свою решётку кадра; без неё
    строится своя. На выход не влияет.
    """
    if _grid is None or not _grid.ok or not _grid.covers(max_range):
        _grid = AW._FrameGrid(fwd, lat, up - floor, max_range)
    if not _grid.ok:
        _grid = None
    cands = []
    for z in np.arange(W.H_LO, W.H_HI - 1e-9, W.H_STEP):
        for side in (-1, +1):
            d, e = layer_edges(fwd, lat, up, floor, z, side, max_range,
                               _grid=_grid)
            if len(d) < MIN_BINS:
                continue
            for idx in cut(d, e):
                coef, k = fit_seg(d[idx], e[idx])
                if coef is None:
                    continue
                cands.append({'coef': coef, 'd': d[idx][k], 'e': e[idx][k],
                              'side': side, 'z': float(z)})
    walls = [w for w in _merge(cands) if len(w.layers) >= MIN_LAYERS]
    walls.sort(key=lambda w: (-w.span, w.d_lo))
    return walls


def leading(walls, axis=None, off=None):
    """Ведущая стена: та, что обрывается РАНЬШЕ -> `Wall` или None.

    Против интуиции, и это геометрия, а не особенность бэга. Наружная стена
    поворота — та, в которую поезд едет, и луч упирается в неё ПОПЕРЁК,
    поэтому она обрывается близко. Вдоль внутренней луч скользит, и она
    тянется далеко. Замер по карте (`OUTER_MARGIN` в axis_wall), дальность
    последней кромки:

        поворот влево : слева 97.5 м  справа 37.5 м
        поворот вправо: слева 32.5 м  справа 92.5 м
        прямая        : обе 97.5 м

    Зеркалится со знаком поворота. Здесь функция ничего не решает за ведение —
    она лишь отвечает на вопрос «какая из найденных стен наружная», и на
    прямой честно возвращает None: там обе стены равноправны и должны сверять
    друг друга.

    axis/off — прямая ось и отступ, измеренный в ближней зоне (как их выдаёт
    `axis_wall.measure_offset`). БЕЗ них кандидатом на сторону берётся самая
    дальняя стена — и на двухпутке ею оказывается стена ВТОРОГО пути: она
    тянется дальше всех. С осью кандидаты фильтруются по отступу, как в
    `axis_wall.frame_edges`: своя стена — ближняя к пути из протяжённых, а
    чужая отстоит от измеренного отступа дальше GATE.
    """
    best = {}
    for side in (-1, +1):
        cand = [w for w in walls if w.side == side]
        if not cand:
            continue
        if axis is not None and off is not None and not np.isnan(off[side]):
            near = [w for w in cand
                    if abs(abs(w.lat_at(max(w.d_lo, AW.SEED_HI))
                               - float(axis_at(axis, max(w.d_lo, AW.SEED_HI))))
                           - abs(off[side])) <= AW.GATE]
            if near:
                cand = near
        best[side] = max(cand, key=lambda w: w.d_hi)
    if len(best) < 2:
        return None
    l, r = best[-1], best[+1]
    if abs(l.d_hi - r.d_hi) < AW.OUTER_MARGIN:
        return None
    return l if l.d_hi < r.d_hi else r
