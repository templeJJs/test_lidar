class Wall:
    """Одна стена кадра.

    coef    — полином `lat(fwd)`, абсолютные координаты кадра (нуль лидара)
    d_lo/d_hi — отрезок дальности, на котором стена ПРОСЛЕЖЕНА, м
    side    — с какой стороны от нуля лидара (-1 слева, +1 справа)
    layers  — список слоёв высоты (низ слоя, м), где она подтверждена
    n_bins  — сколько кромок легло на линию
    rms     — невязка этих кромок от линии, м
    d/e     — сами кромки (дальность, вынос): для картинки и проверки
    """

    def __init__(self, coef, d, e, side, layers, rms):
        self.coef, self.d, self.e = coef, d, e
        self.side, self.layers, self.rms = side, layers, rms
        self.d_lo, self.d_hi = float(d.min()), float(d.max())
        self.n_bins = len(d)

    @property
    def span(self):
        return self.d_hi - self.d_lo

    def lat_at(self, fwd):
        """Вынос стены на дальности `fwd`, м. За отрезком — экстраполяция."""
        return np.polyval(self.coef, np.asarray(fwd, dtype=float))

    def __repr__(self):
        return (f'<Wall {"L" if self.side < 0 else "R"} '
                f'{self.d_lo:.0f}-{self.d_hi:.0f}м '
                f'{self.lat_at(self.d_lo):+.2f}->{self.lat_at(self.d_hi):+.2f} '
                f'слоёв={len(self.layers)} rms={self.rms:.2f}>')


def layer_edges(fwd, lat, up, floor, z, side, max_range=MAX_RANGE):
    """Кромка в каждом бине одного слоя высоты, независимо по бинам.

    Независимо — принципиально. Рекуррентный поиск (окно вокруг предыдущей
    кромки) имеет отказ, который не чинится порогами: одна испорченная кромка
    отравляет всё, что за ней, потому что следующее окно строится вокруг
    вранья. Здесь одна плохая кромка остаётся одной плохой кромкой, и её
    снимет либо разрез по разрыву, либо отбраковка при фите.

    Кромка берётся ВНЕШНЯЯ (`outer=True`): внутренний край стены размывают
    кабели, кронштейны и ниши, висящие перед ней, а внешний задан самой
    стеной — дальше неё луч не проходит. Габариту (блок 2) нужен внутренний,
    геометрии стены — внешний.

    -> (d[], e[]) — центры бинов и вынос кромки, абсолютные координаты.
    """
    h = up - floor
    k = (h >= z) & (h < z + W.H_STEP)
    f_l, l_l = fwd[k], lat[k]
    ds, es = [], []
    for lo in np.arange(0.0, max_range, BIN):
        m = (f_l >= lo) & (f_l < lo + BIN)
        if not m.any():
            continue
        s = l_l[m] * side
        s = s[(s >= MIN_OFF) & (s <= MAX_OFF)]
        if len(s) < MIN_PTS:
            continue
        ds.append(lo + BIN / 2)
        es.append(W.edge_val(s, outer=True) * side)
    return np.array(ds), np.array(es)


def layer_clusters(fwd, lat, up, floor, z, side, max_range=MAX_RANGE):
    """ВСЕ поверхности слоя в каждом бине, а не одна кромка.

    Зачем. `layer_edges` сводит бин к одному числу — ближайшей к лидару
    кромке. Пока в бине одна стена, это верно. Но в бине может стоять
    ВТОРАЯ поверхность ближе стены, и тогда оценка перескакивает на неё,
    а стена пропадает из профиля вовсе.

    Замер roundT_pressureGate_roundT f111, слева (кластеры по выносу,
    разрыв > 0.5 м, n >= 4):

        бин      стена              вторая поверхность
        45-50    -4.19..-4.54 (5 слоёв)   -0.50 только h=0.1-0.6
        50-55    -4.58..-4.80 (4 слоя)    -0.48 при h=3.1-3.6 (n=30)
        55-60    -4.67..-5.16 (4 слоя)    -0.43..-0.58 во ВСЕХ слоях
        60-65    -4.54..-5.26 (3 слоя)    -0.80..-2.02 во всех слоях

    Стена непрерывна: -4.5 -> -4.8 -> -5.1 -> -5.2. Но с 55 м рядом с осью
    встаёт конструкция от пола до свода (створка pressure gate), кромка
    перескакивает -4.80 -> -0.48, `cut` видит скачок 4 м и режет НЕПРЕРЫВНУЮ
    стену надвое. Больше точек не помогает: замер по накопленному облаку
    (184 тыс. -> 1.3 млн точек, полный SE(2) по 6 кадрам) даёт ровно тот же
    разрез в том же месте — оба объекта просто становятся плотнее.

    Поэтому бин отдаёт ВСЕ свои поверхности, а решение, какая из них
    продолжает стену, принимается по НЕПРЕРЫВНОСТИ вдоль дальности (см.
    `chains`): стена собирается в одну длинную линию, а створка остаётся
    коротким объектом и отваливается по `MIN_BINS`.

    Кластеры ищутся разрывом по выносу — тем же признаком, что отделяет
    стену от того, что перед ней: между двумя поверхностями есть пустота,
    внутри одной её нет.

    -> {бин: [(вынос, n_точек), ...]} — вынос в АБСОЛЮТНЫХ координатах,
       кластеры упорядочены от лидара наружу.
    """
    h = up - floor
    k = (h >= z) & (h < z + W.H_STEP)
    f_l, s_l = fwd[k], lat[k] * side
    # MIN_OFF держит не «стену», а ПУТЬ ВПЕРЕДИ: на дуге рельсы, балласт и
    # шпальная решётка попадают в полосу высот и складываются в псевдостену,
    # пересекающую ноль (замер f100 при пороге 0.0 — ложная линия 62-98 м).
    # Но путь впереди виден только в ближней зоне, а дальше у нуля лидара
    # своего пути быть не может: поезд туда не доехал. Замер высоты точек в
    # |lat| < 0.6 (три кадра двух бэгов), медиана h:
    #
    #     дальность   0-20 м      30-50 м     70 м+
    #     f313        0.2-0.4     0.17        2.28
    #     f100        0.2-0.3     0.09        1.97
    #     f240        0.3-0.8     1.54        —
    #
    # До 50 м это путь (h ~ 0.1-0.4, головки и балласт), дальше 70 м —
    # вертикальная поверхность (h ~ 2.0-2.3), то есть стена. Разделение
    # двукратное, не пограничное. Поэтому запрет действует только в ближней
    # зоне: дальше он не защищает ни от чего, а СВОЮ стену, подошедшую к
    # нулю лидара на дуге, разрывает надвое — до пересечения она левая,
    # после правая, и половинки уходят в разные проходы по side, которые
    # нигде не встречаются (замер doubleT_platform f313: стена непрерывна
    # -0.98 -> -0.40 -> +0.27 -> +1.56, а detect отдаёт 2-72 м и 82-128 м
    # как две разные стены с дырой 72-82 м).
    lo_off = np.where(f_l <= NEAR_FWD, MIN_OFF, 0.0)
    k2 = (s_l >= lo_off) & (s_l <= MAX_OFF) & (f_l > 0) & (f_l < max_range)
    f_l, s_l = f_l[k2], s_l[k2]
    out = {}
    if len(f_l) < MIN_PTS:
        return out
    b_all = np.floor(f_l / BIN).astype(int)
    for b in np.unique(b_all):
        s = np.sort(s_l[b_all == b])
        if len(s) < MIN_PTS:
            continue
        # Разрыв по выносу режет бин на поверхности.
        parts = np.split(s, np.flatnonzero(np.diff(s) > CLUST_GAP) + 1)
        cl = [(float(np.median(p)) * side, len(p))
              for p in parts if len(p) >= MIN_PTS]
        if cl:
            out[int(b)] = cl
    return out


def chains(clusters):
    """Цепочки поверхностей по бинам -> список [(d, e), ...].

    Из кластеров каждого бина собираются непрерывные линии: поверхность
    продолжает цепочку, если её вынос недалеко от предсказания по последним
    принятым бинам. Это то же требование непрерывности, которым блок 1
    отбирает свою пару рельсов среди 36 кандидатов, — но здесь оно решает,
    какая из нескольких поверхностей бина продолжает СТЕНУ.

    Жадно по цепочкам, а не по кластерам: каждая цепочка берёт ближайший к
    своему предсказанию свободный кластер. Так створка, встав рядом со
    стеной, заводит СВОЮ цепочку, а не перехватывает чужую.

    Цепочка ведётся предсказанием, а не последним значением: на дуге стена
    уходит законно быстро, и допуск вокруг замершего значения обрывал бы её
    на повороте (тот же урок, что `_predict` в walls.py).
    """
    if not clusters:
        return []
    live, done = [], []
    for b in sorted(clusters):
        taken = set()
        for ch in live:
            # Предсказание: последнее значение плюс ограниченный наклон по
            # последним принятым бинам.
            if len(ch) >= 2:
                (d0, v0), (d1, v1) = ch[-2], ch[-1]
                sl = (v1 - v0) / max(d1 - d0, 1e-6)
                sl = float(np.clip(sl, -CHAIN_SLOPE, CHAIN_SLOPE))
                pred = v1 + sl * (b * BIN + BIN / 2 - d1)
            else:
                pred = ch[-1][1]
            best, bd = None, CHAIN_TOL
            for ci, (v, _n) in enumerate(clusters[b]):
                if ci in taken:
                    continue
                if abs(v - pred) < bd:
                    best, bd = ci, abs(v - pred)
            if best is not None:
                taken.add(best)
                ch.append((b * BIN + BIN / 2, clusters[b][best][0]))
        # Непристроенные кластеры заводят новые цепочки.
        for ci, (v, _n) in enumerate(clusters[b]):
            if ci not in taken:
                live.append([(b * BIN + BIN / 2, v)])
        # Цепочка, не продолженная дольше GAP_BINS бинов, закрывается.
        still = []
        for ch in live:
            if b - int(ch[-1][0] // BIN) > GAP_BINS:
                done.append(ch)
            else:
                still.append(ch)
        live = still
    done += live
    return [(np.array([p[0] for p in ch]), np.array([p[1] for p in ch]))
            for ch in done if len(ch) >= MIN_BINS]


def cut(d, e):
    """Режет профиль кромок на куски по разрывам -> список индексов.

    Два признака разрыва, и оба физические:
      - ИЗМЕНЕНИЕ шага выноса между соседними бинами больше `JUMP` — своя
        стена гладкая даже на завороте (шаг растёт плавно: замер f123,
        шаги 0.64-0.85 м/бин при изменении шага <= 0.5), а чужая появляется
        скачком (med 3.5 м). Первой разностью резать нельзя: на дуге она
        законно превышает JUMP, и линия рассыпалась на куски короче
        MIN_BINS ровно там, где стена поворачивает (f123: стена есть до
        108 м, линия обрывалась на 78);
      - пропуск больше `GAP_BINS` бинов — за дырой между кольцами стена
        продолжается, а за длинным пропуском её уже нет.

    Кусок — это КАНДИДАТ в стены, а не стена: длину и гладкость проверяет
    `fit_seg`.
    """
    if len(d) == 0:
        return []
    segs, cur = [], [0]
    prev_step = None          # шаг выноса, нормированный на бин
    for i in range(1, len(d)):
        g = (d[i] - d[i - 1]) / BIN
        step = (e[i] - e[i - 1]) / g
        if g > GAP_BINS + 1:
            brk = True
        elif prev_step is None:
            # первого шага истории нет — доступна только сама величина шага
            brk = abs(step) > JUMP
        else:
            brk = abs(step - prev_step) > JUMP
        if brk:
            segs.append(cur)
            cur = []
            prev_step = None
        else:
            prev_step = step
        cur.append(i)
    segs.append(cur)
    return [np.array(s) for s in segs if len(s) >= MIN_BINS]


def fit_seg(d, e, tol=FIT_TOL):
    """Линия по куску профиля, с отбраковкой выбросов -> (coef, маска).

    Парабола, а не прямая: на дуге стена гнётся, и прямая на плече 60 м даёт
    невязку больше допуска сама по себе. Выше второй степени не берём —
    третья начинает объяснять выбросы вместо того, чтобы их отвергать.

    Два прохода: подогнали, выкинули то, что дальше `tol`, подогнали заново.
    Дальше состав почти не меняется.
    """
    k = np.ones(len(d), dtype=bool)
    coef = None
    for _ in range(2):
        if k.sum() < 3:
            return None, None
        deg = 2 if k.sum() >= 4 else 1
        coef = np.polyfit(d[k], e[k], deg)
        k = np.abs(e - np.polyval(coef, d)) <= tol
    if k.sum() < MIN_BINS or (d[k].max() - d[k].min()) < MIN_SPAN:
        return None, None
    return np.polyfit(d[k], e[k], 2 if k.sum() >= 4 else 1), k


def _merge(cands):
    """Сливает линии соседних слоёв, описывающие одну стену.

    Настоящая стена видна в нескольких слоях высоты подряд, и её линии там
    почти совпадают. Кабель, кронштейн, навес, край платформы живут в одной
    полосе высоты — у них слой ровно один, и `MIN_LAYERS` их снимает.

    Сравниваются линии на ОБЩЕМ участке дальности: две линии могут иметь
    близкий вынос в разных концах кадра и при этом описывать разные стены.
    """
    used = [False] * len(cands)
    out = []
    for i, a in enumerate(cands):
        if used[i]:
            continue
        used[i] = True
        group = [a]
        # Проходов несколько: группа растёт по ходу, и кандидат, ставший
        # соседом уже принятого слоя, при одном проходе остался бы пропущен —
        # цепочка слоёв собирается только тогда, когда её звенья видят друг
        # друга независимо от порядка в списке.
        grew = True
        while grew:
            grew = False
            for j in range(len(cands)):
                b = cands[j]
                if used[j] or b['side'] != a['side']:
                    continue
                # Сравнивать надо с БЛИЖАЙШИМ ПО ВЫСОТЕ членом группы, а не с её
                # первым кандидатом. Стена круглого тоннеля гнётся, и через три
                # слоя вынос уходит законно далеко: замер профиля правой стены
                # f108 (вынос кромки по слоям на 12.5 м) —
                #     0.6   1.1   1.6   2.1   2.6   3.1 м
                #    1.86  2.31  2.42  2.43  2.40  2.27
                # шаг между СОСЕДНИМИ слоями 0.01-0.45 м, а от нижнего слоя до
                # 2.1 уже 0.65 м. Сравнение с первым кандидатом рвало стену на
                # два куска ровно там, где дуга набирает размах: f108 давала
                # слои [0.6, 1.1, 1.6] и [2.1, 2.6, 3.1] вместо одной стены.
                nb = min(group, key=lambda g: abs(b['z'] - g['z']))
                if abs(b['z'] - nb['z']) > W.H_STEP * 1.5 + 1e-9:
                    continue
                lo = max(nb['d'].min(), b['d'].min())
                hi = min(nb['d'].max(), b['d'].max())
                if hi - lo < MERGE_OVER:
                    continue
                t = np.linspace(lo, hi, 5)
                if np.max(np.abs(np.polyval(nb['coef'], t)
                                 - np.polyval(b['coef'], t))) > MERGE_LAT:
                    continue
                used[j] = True
                group.append(b)
                grew = True
        d = np.concatenate([g['d'] for g in group])
        e = np.concatenate([g['e'] for g in group])
        o = np.argsort(d)
        d, e = d[o], e[o]
        coef = np.polyfit(d, e, 2 if len(d) >= 4 else 1)
        rms = float(np.sqrt(np.mean((e - np.polyval(coef, d)) ** 2)))
        out.append(Wall(coef, d, e, a['side'],
                        sorted({float(g['z']) for g in group}), rms))
    return out


def _stitch(walls):
    """Сшивает стену, разрезанную надвое пересечением нуля лидара.

    `layer_clusters` собирает поверхности двумя независимыми проходами —
    отдельно левую полуплоскость, отдельно правую, — потому что знак нужен
    для сортировки по выносу и для `MIN_OFF`. На прямой это безразлично: своя
    стена остаётся в своей полуплоскости. На дуге путь уходит вбок, стена
    идёт вдоль пути и ПЕРЕСЕКАЕТ ноль лидара — до пересечения она левая,
    после правая, и её половинки попадают в разные проходы, которые нигде не
    встречаются. `_merge` их тоже не сводит: он требует общего участка
    дальности (`MERGE_OVER`) и одинакового `side`, а половинки стыкуются
    концами и стороны у них разные.

    Замер doubleT_platform f313: кромка идёт непрерывно -0.98 -> -0.77 ->
    -0.40 -> -0.28 -> +0.27 -> +1.31 -> +1.56, ни одного пустого бина, а
    detect отдавал 2-72 м (L) и 82-128 м (R) как две разные стены с дырой
    72-82 м посередине. Ось, ведомая левой половиной, уходила в эту дыру и
    к 92 м промахивалась на +3.4 м при прямом пути.

    Критерий сшивки — тот же, которым `chains` ведёт цепочку внутри
    полуплоскости: продолжение одной линии попадает в начало другой. Нового
    признака не вводится, только снимается ограничение «в пределах своей
    стороны». Проверяются обе величины, и положение, и наклон: у одной стены
    в точке стыка они совпадают, у двух разных — расходятся.
    """
    out, used = [], [False] * len(walls)
    for i, a in enumerate(walls):
        if used[i]:
            continue
        cur = a
        used[i] = True
        grew = True
        while grew:
            grew = False
            for j, b in enumerate(walls):
                if used[j]:
                    continue
                # Половинки идут одна за другой по дальности. Стыковаться
                # они могут и встык, и С ПЕРЕКРЫТИЕМ: разрез проходит по
                # точке пересечения нуля, и обе линии тянутся до неё с
                # запасом (замер f239: левая 2-42 м кончается на +0.05,
                # правая 38-108 м начинается с -0.25 — перекрытие 4 м, и
                # проверка «только встык» такую пару не рассматривала вовсе).
                lo_w, hi_w = (cur, b) if cur.d_lo <= b.d_lo else (b, cur)
                gap = hi_w.d_lo - lo_w.d_hi      # < 0 при перекрытии
                if gap > GAP_BINS * BIN:
                    continue
                # Одна не должна лежать внутри другой: это не продолжение,
                # а две линии на одном участке (их сводит _merge).
                if hi_w.d_hi <= lo_w.d_hi:
                    continue
                # Слои должны пересекаться: сшивается одна и та же стена,
                # а не стена с навесом над ней.
                if not (set(lo_w.layers) & set(hi_w.layers)):
                    continue
                # Сверяемся в середине стыка: на перекрытии это его центр,
                # на разрыве — середина дыры.
                m = (lo_w.d_hi + hi_w.d_lo) / 2
                # Допуск — разброс самих линий, а не константа: чем шумнее
                # кромка, тем больше вправе разойтись продолжения. На разрыве
                # добавляется ход экстраполяции через дыру (CHAIN_SLOPE — тот
                # же предел хода цепочки); на перекрытии добавки нет.
                tol = (max(lo_w.rms + hi_w.rms, CLUST_GAP)
                       + max(gap, 0.0) * CHAIN_SLOPE)
                if abs(lo_w.lat_at(m) - hi_w.lat_at(m)) > tol:
                    continue
                # Наклон НЕ сверяется. На дуге он обязан меняться — стена
                # там и гнётся, — и требование совпадения отбрасывало
                # настоящие стыки ровно там, где дуга разгоняется (замер
                # roundT_pressureGate_roundT f239: своя левая стена шла
                # 2-38 м и 38-112 м двумя линиями, стык встык, а наклоны до
                # и после стыка законно разные). Стену от чужой линии
                # отделяет положение стыка, а не угол.
                d = np.concatenate([lo_w.d, hi_w.d])
                e = np.concatenate([lo_w.e, hi_w.e])
                o = np.argsort(d)
                d, e = d[o], e[o]
                coef = np.polyfit(d, e, 2 if len(d) >= 4 else 1)
                rms = float(np.sqrt(np.mean((e - np.polyval(coef, d)) ** 2)))
                # Сторону наследует более длинная половина: у сшитой стены
                # её нет как свойства точек, но потребители (leading,
                # frame_edges) до сих пор спрашивают, слева стена или справа.
                side = (lo_w if lo_w.span >= hi_w.span else hi_w).side
                cur = Wall(coef, d, e, side,
                           sorted(set(lo_w.layers) | set(hi_w.layers)), rms)
                used[j] = True
                grew = True
        out.append(cur)
    return out


def detect(fwd, lat, up, floor, max_range=MAX_RANGE):
    """Все стены кадра -> список `Wall`, отсортированный по протяжённости.

    Про ось не знает ничего: вход — только облако и уровень пола.
    """
    cands = []
    for z in np.arange(W.H_LO, W.H_HI - 1e-9, W.H_STEP):
        for side in (-1, +1):
            # Бин отдаёт ВСЕ свои поверхности, и какая из них продолжает
            # стену, решает непрерывность вдоль дальности, а не близость к
            # лидару: иначе конструкция, вставшая перед стеной, перехватывает
            # кромку и рвёт стену надвое (замер f111 в layer_clusters).
            cl = layer_clusters(fwd, lat, up, floor, z, side, max_range)
            for d, e in chains(cl):
                # cut остаётся: цепочка ведётся с допуском, и внутри неё
                # может уцелеть скачок, который линией уже не объясняется.
                for idx in cut(d, e):
                    coef, k = fit_seg(d[idx], e[idx])
                    if coef is None:
                        continue
                    cands.append({'coef': coef, 'd': d[idx][k],
                                  'e': e[idx][k], 'side': side,
                                  'z': float(z)})
    walls = [w for w in _merge(cands) if len(w.layers) >= MIN_LAYERS]
    # Сшивка идёт ПОСЛЕ отбора по слоям: половинки одной стены каждая
    # подтверждены своими слоями, а короткий мусор до сшивки не доживает и
    # не может приклеиться к настоящей стене.
    walls = _stitch(walls)
    walls.sort(key=lambda w: (-w.span, w.d_lo))
    return walls


def outer(walls, axis=None, off=None):
    """Наружная стена поворота: та, что обрывается РАНЬШЕ -> `Wall` или None.

    Раньше называлась `leading` («ведущая»), и имя врало: ведение — это
    построение ОСИ, а здесь считается лишь признак формы сцены. Вести по этой
    стене нельзя, она обрывается раньше всех. Ведущую стену — ту, по которой
    ось реально построена, — отдаёт `wall_rules.leading`.

    Против интуиции, и это геометрия, а не особенность бэга. Наружная стена
    поворота — та, в которую поезд едет, и луч упирается в неё ПОПЕРЁК,
    поэтому она обрывается близко. Вдоль внутренней луч скользит, и она
    тянется далеко. Замер по карте (`OUTER_MARGIN` в axis_wall), дальность
    последней кромки:

        поворот влево : слева 97.5 м  справа 37.5 м
        поворот вправо: слева 32.5 м  справа 92.5 м
        прямая        : обе 97.5 м

    Зеркалится со знаком поворота. Здесь функция ничего не решает за ведение —
    она лишь отвечает на вопрос «какая из найденных стен наружная», и на
    прямой честно возвращает None: там обе стены равноправны и должны сверять
    друг друга.

    axis/off — прямая ось и отступ, измеренный в ближней зоне (как их выдаёт
    `axis_wall.measure_offset`). БЕЗ них кандидатом на сторону берётся самая
    дальняя стена — и на двухпутке ею оказывается стена ВТОРОГО пути: она
    тянется дальше всех. С осью кандидаты фильтруются по отступу, как в
    `axis_wall.frame_edges`: своя стена — ближняя к пути из протяжённых, а
    чужая отстоит от измеренного отступа дальше GATE.
    """
    best = {}
    for side in (-1, +1):
        cand = [w for w in walls if w.side == side]
        if not cand:
            continue
        if axis is not None and off is not None and not np.isnan(off[side]):
            near = [w for w in cand
                    if abs(abs(w.lat_at(max(w.d_lo, SEED_HI))
                               - float(axis_at(axis, max(w.d_lo, SEED_HI))))
                           - abs(off[side])) <= GATE]
            if near:
                cand = near
        best[side] = max(cand, key=lambda w: w.d_hi)
    if len(best) < 2:
        return None
    l, r = best[-1], best[+1]
    if abs(l.d_hi - r.d_hi) < OUTER_MARGIN:
        return None
    return l if l.d_hi < r.d_hi else r
