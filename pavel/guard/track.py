"""Блок 1. Ось пути на прямом участке.

Задача блока: дать линию, от которой отсчитывается габарит. На прямой это
прямая, и здесь сознательно НЕ делается ничего сложнее: кривые — следующий
этап.

Ось ищется по головкам рельсов в ближней зоне. Два замера по данным задали
конструкцию:

1. ВЫСОТА ГОЛОВКИ. "Пол" под поездом (2-й перцентиль Z) — это низ балласта
   и лотка, а не уровень катания. Гистограмма высот в срезе 6-12 м
   (doubleT_platform f100) двугорбая: 380-614 точек на h = 0.00-0.10 (низ)
   и 1015 точек на h = 0.30-0.45 — это верх пути. Между ними провал в 30
   точек. Поэтому головка ищется в полосе H_LO..H_HI вокруг 0.35, а не
   вокруг 0.25 над полом.

2. ОТБОР ПАРЫ. В срезе 8-12 м находится до 36 пар пиков, подходящих под
   колею с допуском. Брать "ближайшую к номиналу" нельзя — соседний путь и
   кромка платформы дают такие же. Разделяет НЕПРЕРЫВНОСТЬ: своя пара
   повторяется во всех срезах подряд (замер: -0.85/+0.60 держится с 4 до
   29 м во всех проверенных кадрах), чужие появляются и пропадают. Поэтому
   сначала собираются все кандидаты по срезам, потом выбирается та ветка,
   что живёт на самом длинном плече и ближе всего к лидару.
"""

import numpy as np

# --- где искать головки --------------------------------------------------
NEAR_FWD = (7.0, 30.0)   # зона измерения оси, м. Ближе 7 м в полосу высот
                         # головки лезут шпальная решётка и крепёж: замер по
                         # doubleT_platform — срез 5 м даёт центр +0.37/-0.37
                         # при -0.10 на всех остальных, и один этот срез
                         # разворачивал наклон оси до 0.018 (2 м на 110 м).
                         # Дальше 30 м головок нет: луч идёт по касательной
SLICE_LEN = 4.0          # длина среза вдоль пути, м
LAT_WIN = 2.5            # полуширина поиска от нуля лидара, м
H_LO, H_HI = 0.28, 0.50  # полоса высот головки над полом, м (см. замер 1)
LAT_BIN = 0.05           # бин поперечного профиля, м
MIN_PTS_SLICE = 30       # меньше точек в полосе — среза нет

# --- колея ---------------------------------------------------------------
GAUGE_NOM = 1.45         # центр окна поиска СВОЕЙ пары по колее, м. Своя
                         # пара по замеру непрерывности (README, замер 2):
                         # -0.85/+0.60 -> 1450 мм; smoke по кадрам f100/f20
                         # doubleT_platform даёт 1469/1493 мм. Статистика
                         # 1405+-53 мм (README) — медиана ВЫХОДА блока по
                         # кадрам, где разброс выбора ветки тянет медиану
                         # вниз, а не положение своей пары. Проверка центра
                         # 1.405 (эта медиана) на f100/f20 сместила выбор
                         # ветки на чужие низкие пары (1469 -> 1435 мм),
                         # поэтому центр оставлен по замеру своей пары.
GAUGE_TOL = 0.20         # допуск на пару, м
PEAK_MIN_FRAC = 0.25     # пик — локальный максимум не ниже доли от главного
PEAK_MIN_CNT = 3         # и не меньше этого числа точек

# --- отбор своей ветки ---------------------------------------------------
LINK_TOL = 0.35          # насколько центр пары может сдвинуться между
                         # соседними срезами, чтобы считаться той же веткой, м
MIN_BRANCH = 3           # ветка короче этого числа срезов не рассматривается
OWN_LAT = 2.0            # своя ось не дальше этого от лидара, м
SLOPE_LIM = 0.004        # предел наклона оси на прямом участке, м/м.
                         # Этот блок работает ТОЛЬКО на прямой, где путь по
                         # определению не уходит вбок; 0.004 — это 0.44 м на
                         # 110 м, вдвое больше остаточного разброса замера.
                         # На кривой предел неверен — там будет свой блок.


def _peaks(lat_s, up_s, floor):
    """Локальные максимумы поперечного профиля среза в полосе высот головки."""
    m = (up_s - floor >= H_LO) & (up_s - floor < H_HI) & (np.abs(lat_s) < LAT_WIN)
    if m.sum() < MIN_PTS_SLICE:
        return np.zeros(0)
    v = lat_s[m]
    edges = np.arange(-LAT_WIN, LAT_WIN + LAT_BIN, LAT_BIN)
    cnt, _ = np.histogram(v, bins=edges)
    thr = max(PEAK_MIN_CNT, cnt.max() * PEAK_MIN_FRAC)
    out = []
    i = 1
    while i < len(cnt) - 1:
        if cnt[i] >= thr and cnt[i] >= cnt[i - 1] and cnt[i] >= cnt[i + 1]:
            # Плато (соседние бины с равными счётчиками) — один пик, а не
            # дубли в 50 мм друг от друга: сливаем весь прогон равных бинов,
            # центроид считается по всему плато, поэтому положение пика
            # не смещается.
            j = i
            while j + 1 < len(cnt) - 1 and cnt[j + 1] == cnt[i]:
                j += 1
            # Положение пика — центроид точек бина и соседей, а не центр
            # бина: бин 50 мм иначе квантует колею ступеньками.
            sel = v[(v >= edges[i - 1]) & (v < edges[j + 2])]
            if len(sel):
                out.append(float(sel.mean()))
            i = j + 1
        else:
            i += 1
    return np.array(sorted(out))


def _pairs(peaks):
    """Все пары пиков, подходящие под колею -> [(центр, колея)]."""
    out = []
    for i in range(len(peaks)):
        for j in range(i + 1, len(peaks)):
            g = peaks[j] - peaks[i]
            if abs(g - GAUGE_NOM) <= GAUGE_TOL:
                out.append(((peaks[i] + peaks[j]) / 2, g))
    return out


def _best_branch(cands):
    """Самая длинная непрерывная цепочка пар по срезам.

    cands — список по срезам: [(fwd, [(центр, колея), ...]), ...].
    Своя пара идёт через все срезы подряд, чужая рвётся (см. замер 2).
    """
    branches = []   # каждая: список (fwd, центр, колея)
    for fwd_s, pairs in cands:
        # Связывание внутри среза — жадно по лучшей паре (свежесть ветки,
        # расстояние), а не в порядке перебора: иначе дальняя пара, идущая
        # первой в списке, перехватывала живую ветку раньше ближней, и своя
        # цепочка обрывалась (f30 doubleT_platform: пара с центром -0.32
        # брала ветку у пары -0.16 с d=0.02). Свежесть (отставание по
        # дальности) важнее близости центра — заснувшая ветка не должна
        # перехватывать пару у живой. Допуск LINK_TOL тот же.
        links = []
        for pi, (c, g) in enumerate(pairs):
            for br in branches:
                if br[-1][0] == fwd_s:      # в одном срезе ветка не ветвится
                    continue
                d = abs(br[-1][1] - c)
                if d < LINK_TOL:
                    links.append(((fwd_s - br[-1][0], d), pi, br))
        links.sort(key=lambda t: t[0])
        used_p, used_b = set(), set()
        for _, pi, br in links:
            if pi in used_p or id(br) in used_b:
                continue
            br.append((fwd_s, pairs[pi][0], pairs[pi][1]))
            used_p.add(pi)
            used_b.add(id(br))
        for pi, (c, g) in enumerate(pairs):
            if pi not in used_p:
                branches.append([(fwd_s, c, g)])

    # Длина ветки — длина САМОГО ДЛИННОГО непрерывного прогона внутри неё,
    # а не просто число звеньев: дыры (срез без пары — кольца лидара)
    # допустимы, но ветка, набравшая звенья с дырами, не должна считаться
    # наравне с непрерывной. Шаг центров соседних срезов равен SLICE_LEN,
    # дыра его удваивает. Прогон считается в любом месте ветки, а не от её
    # начала: своя ветка может начинаться одиночным звеном перед дырой
    # (f40 doubleT_platform: звенья на 9, 21, 25, 28.5 м — прогон 3).
    def shoulder(b):
        best, n = 1, 1
        for k in range(1, len(b)):
            if b[k][0] - b[k - 1][0] > SLICE_LEN * 1.5:
                n = 1
            else:
                n += 1
                best = max(best, n)
        return best
    # Непрерывность — не только арбитр между ветками, но и фильтр: ветка
    # без прогона длиной MIN_BRANCH своей быть не может. Замер по f170
    # roundT_pressureGate_roundT: чужая ветка (колея 1.33, звенья 9/25/28.5 —
    # прогон 2) принималась, когда она единственная, и уводила ось на
    # +0.77 м от истины.
    branches = [b for b in branches
                if len(b) >= MIN_BRANCH and shoulder(b) >= MIN_BRANCH]
    if not branches:
        return None
    # Из длинных веток берём ту, что ближе к лидару: поезд стоит на своём
    # пути. Близость — последний арбитр: чужая ветка (рельс + кромка
    # платформы) бывает непрерывной, поэтому непрерывность выше близости
    # поднимать нельзя — замер по f100/f20 doubleT_platform.
    longest = max(shoulder(b) for b in branches)
    near = [b for b in branches if shoulder(b) >= longest - 1]
    return min(near, key=lambda b: abs(np.median([c for _, c, _ in b])))


def straight_axis(fwd, lat, up, floor):
    """Ось прямого пути по ближней зоне.

    Возвращает dict:
      lat0, slope — ось как lat = lat0 + slope * fwd
      gauge       — измеренная колея по осям головок, м; None, если ветка
                    отвергнута как чужая (measured=False)
      n_obs       — сколько срезов дали пару (мера доверия)
      obs_fwd/obs_lat — наблюдения, для отладки
      measured    — False, если ось не измерена и взята нулевая
    """
    cands = []
    for lo in np.arange(NEAR_FWD[0], NEAR_FWD[1], SLICE_LEN):
        # Последний срез обрезается границей зоны: иначе [27,31) лезет
        # на 1 м за NEAR_FWD=30 м.
        hi = min(lo + SLICE_LEN, NEAR_FWD[1])
        m = (fwd >= lo) & (fwd < hi)
        if m.sum() < MIN_PTS_SLICE:
            continue
        pr = _pairs(_peaks(lat[m], up[m], floor))
        if pr:
            cands.append(((lo + hi) / 2, pr))

    br = _best_branch(cands)
    if br is None:
        return dict(lat0=0.0, slope=0.0, gauge=GAUGE_NOM, n_obs=0,
                    obs_fwd=np.zeros(0), obs_lat=np.zeros(0), measured=False)

    obs_f = np.array([f for f, _, _ in br])
    obs_l = np.array([c for _, c, _ in br])
    gauges = np.array([g for _, _, g in br])

    # MIN_BRANCH гарантирует минимум 3 звена — фит прямой всегда определён.
    slope, lat0 = np.polyfit(obs_f, obs_l, 1)
    # Наклон сверх предела означает, что фит ведёт не путь, а промах среза.
    # Тогда наклон клампится в +-SLOPE_LIM (на прямой путь вбок не уходит,
    # см. обоснование предела выше), а lat0 пересчитывается медианой
    # остатков — она устойчива к промаху, в отличие от свободного фита.
    if abs(slope) > SLOPE_LIM:
        slope = float(np.clip(slope, -SLOPE_LIM, SLOPE_LIM))
        lat0 = float(np.median(obs_l - slope * obs_f))

    # Ось своего пути не может уехать от лидара: поезд на ней стоит.
    # Отвергнутая (чужая) ветка не даёт ни оси, ни колеи.
    if abs(lat0) > OWN_LAT:
        return dict(lat0=0.0, slope=0.0, gauge=None,
                    n_obs=len(obs_f), obs_fwd=obs_f, obs_lat=obs_l,
                    measured=False)

    return dict(lat0=float(lat0), slope=float(slope),
                gauge=float(np.median(gauges)), n_obs=len(obs_f),
                obs_fwd=obs_f, obs_lat=obs_l, measured=True)


def axis_at(axis, d):
    """Поперечное положение оси на дальности d, м (скаляр или массив)."""
    return axis['lat0'] + axis['slope'] * np.asarray(d, dtype=float)
